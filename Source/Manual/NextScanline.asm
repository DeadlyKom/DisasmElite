
; -----------------------------------------------------------------------------
; переход к следующей пиксельной строке Spectrum с обменом указателей
; In:
;   HL - второй указатель
;   DE - адрес текущей пиксельной строки
; Out:
;   HL - следующая пиксельная строка исходного DE
;   DE - исходный HL
; Corrupt:
;   AF
; Note:
;   учтены чередование знакомест и границы третей экрана
; -----------------------------------------------------------------------------
NextScanline:   ; переход к следующей пиксельной строке Spectrum с обменом указателей
                ; расчёт следующей пиксельной строки с обменом HL и DE
                EX DE, HL
                INC H
                LD A, H
                ; проверка границы восьмистрочного знакоместа
                AND #07
                RET NZ                                                          ; выход, если новая строка остаётся внутри восьмистрочного знакоместа

                ; расчёт следующей строки знакомест и проверка перехода между третями экрана
                LD A, L
                ADD A, #20
                LD L, A
                RET C                                                           ; выход, если перенос младшего байта уже перевёл адрес в следующую треть экрана

                ; коррекция старшего байта при переходе внутри одной трети экрана
                LD A, H
                SUB #08
                LD H, A
                RET

                ; проверка исходной границы блока
                assert $ = #9AFC
