
; -----------------------------------------------------------------------------
; управление паузой, скоростью, направлением и выходом
; In:
;   матрица клавиатуры, параметры текущего просмотра
; Out:
;   обновлённые параметры либо возврат из ShowSection
; Corrupt:
;   AF
;   при SPACE также SP, режим IM и разрешение прерываний
; Note:
;   S останавливает на границе символа, 6 и 7 меняют скорость
;   6 и 7 одновременно также вызывают остановку
;   при переходе через минимальную скорость направление меняется
;   SPACE восстанавливает сохранённый SP, IM 1 и завершает просмотр
;   HL, DE, BC и альтернативные регистры эта процедура не изменяет
;   обработка имеет приоритет S, затем 6/7, затем SPACE
;   KEYBOARD_*_BIT задают номера битов, прямой IN возвращает ноль для нажатой клавиши
; -----------------------------------------------------------------------------
ReadControls:   ; управление паузой, скоростью, направлением и выходом
                ; опрос клавиши S в ряду A-S-D-F-G
                LD A, #FD
                IN A, (#FE)
                BIT KEYBOARD_S_BIT, A
                JR NZ, ReadArrows                                               ; переход, если клавиша S не нажата

StopAligned:    ; проверка возможности остановки на границе восьми строк
                ; проверка возможности остановки на границе восьми строк
                LD A, (GlyphRow)
                AND MAN_ROW_MASK
                JR NZ, ResumePixel                                              ; переход, если пиксельный сдвиг ещё не выровнен по границе знакоместа

                ; установка паузы через нулевой счётчик прокрутки
                XOR A
                LD (ScrollTimer), A
                RET

ReadArrows:     ; опрос клавиш 6 и 7 в ряду 0-9-8-7-6
                ; опрос клавиш 6 и 7 в ряду 0-9-8-7-6
                LD A, #EF
                IN A, (#FE)
                BIT KEYBOARD_6_BIT, A
                JR NZ, CheckOtherKey                                            ; переход, если клавиша 6 не нажата

                ; проверка одновременного нажатия обеих клавиш скорости
                BIT KEYBOARD_7_BIT, A
                JR Z, StopAligned                                               ; переход, если одновременно нажаты клавиши 6 и 7, к остановке

                ; выбор ускорения или замедления с учётом направления
                LD A, (Reverse)
                AND A
                JR NZ, Slower                                                   ; переход, если направление обратное и клавиша 6 уменьшает скорость

Faster:         ; расчёт уменьшенной задержки кадра с сохранением режима шага в carry
                ; расчёт уменьшенной задержки кадра с сохранением режима шага в carry
                LD A, (DoubleStep)
                RRCA
                LD A, (FrameDelay)
                DEC A
                JR NZ, StoreDelay                                               ; переход, если после уменьшения задержка остаётся ненулевой

                JR C, EnsureRunning                                             ; переход, если уже включён двухстрочный сдвиг с минимальной задержкой

                ; проверка выравнивания перед переходом на две строки за кадр
                LD A, (GlyphRow)
                AND A
                JR NZ, ResumePixel                                              ; переход, если переключение шага пока невозможно внутри знакоместа

                ; включение двухстрочного шага с задержкой четыре кадра
                LD A, MAN_STEP_MASK
                LD (DoubleStep), A
                LD A, #04
StoreDelay:     ; сохранение выбранной задержки между сдвигами
                ; сохранение выбранной задержки между сдвигами
                LD (FrameDelay), A
                JR EnsureRunning

CheckOtherKey:  ; проверка второй клавиши скорости
                ; проверка второй клавиши скорости
                BIT KEYBOARD_7_BIT, A
                JR NZ, CheckExit                                                ; переход, если клавиша 7 также не нажата

                ; выбор реакции на клавишу 7 согласно направлению
                LD A, (Reverse)
                AND A
                JR NZ, Faster                                                   ; переход, если направление обратное и клавиша 7 увеличивает скорость

Slower:         ; расчёт увеличенной задержки с сохранением режима шага в carry
                ; расчёт увеличенной задержки с сохранением режима шага в carry
                LD A, (DoubleStep)
                RRCA
                LD A, (FrameDelay)
                INC A
                JR NC, CheckSlowest                                             ; переход, если режим использует одну строку за сдвиг

                ; проверка предела задержки двухстрочного режима
                CP #05
                JR C, StoreDelay                                                ; переход, если новая задержка двухстрочного режима меньше пяти

                ; переход к однострочному шагу с задержкой один кадр
                XOR A
                LD (DoubleStep), A
                INC A
CheckSlowest:   ; проверка предела задержки однострочного режима
                ; проверка предела задержки однострочного режима
                CP #0C
                JR C, StoreDelay                                                ; переход, если новая задержка однострочного режима меньше двенадцати

                ; смена направления при пересечении минимальной скорости
                LD A, (Reverse)
                XOR MAN_REV_MASK
                LD (Reverse), A
EnsureRunning:  ; проверка необходимости выхода из паузы
                ; проверка необходимости выхода из паузы
                LD A, (ScrollTimer)
                AND A
                RET NZ                                                          ; выход, если прокрутка уже запущена

                ; выбор направления возобновления по текущей клавише 7
                LD A, #EF
                IN A, (#FE)
                BIT KEYBOARD_7_BIT, A
                LD A, #00
                JR NZ, StoreDirection                                           ; переход, если клавиша 7 не нажата и выбирается обычное направление

                INC A
StoreDirection: ; сохранение направления и запуск таймера прокрутки
                ; сохранение направления и запуск таймера прокрутки
                LD (Reverse), A
                LD A, #01
                LD (ScrollTimer), A
                RET

CheckExit:      ; проверка клавиши SPACE в ряду SPACE-SYMBOL SHIFT-M-N-B
                ; проверка клавиши SPACE в ряду SPACE-SYMBOL SHIFT-M-N-B
                LD A, #7F
                IN A, (#FE)
                AND 1 << KEYBOARD_SP_BIT
                RET NZ                                                          ; выход, если SPACE не нажат и просмотр продолжается

                ; установка команды выхода и возврат через сохранённый стек ShowSection
                XOR A
                LD (Selection), A
                LD A, #45
                LD (ViewState), A
ReturnStack:    ; восстановление SP вызова ShowSection с обходом всех вложенных возвратов
ReturnSP        EQU $ + 1                                                       ; сохранённый SP вызова ShowSection, операнд следующей команды
                LD SP, #0000                                                    ; нулевой шаблон заменяется ShowSection перед просмотром
                IM 1
                EI
                RET

                ; проверка исходной границы блока
                assert $ = #9AEC
