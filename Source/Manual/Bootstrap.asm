; -----------------------------------------------------------------------------
; перенос просмотрщика и упакованного текста из строки REM в исходные адреса
; In:
;   BC - PROG + 5, адрес первой инструкции после токена REM
; Out:
;   HL - адрес шрифта минус 256, значение системной переменной CHARS
;   стек - адрес начала упакованного текста #C9BC
;   переход в Initialize
; Corrupt:
;   HL, DE, BC, AF
; Note:
;   текст переносится назад через LDDR, исходные и целевые области могут пересекаться
;   исходный абсолютный адрес BASIC-программы не фиксируется
; -----------------------------------------------------------------------------
Bootstrap:      ; перенос перемещаемых частей из BASIC-программы
                DI
                LD SP, BOOT_STACK
                ; расчёт адреса последнего байта упакованного блока относительно BC
                LD HL, #0839
                ADD HL, BC
                PUSH BC
                LD BC, PACK_SIZE
                ADD HL, BC
                ; перенос упакованного текста и словаря в #C9BC..#FFFF
                LD DE, PACK_LAST
                LDDR
                POP BC
                INC DE
                PUSH DE
                ; расчёт адреса кода просмотрщика внутри строки REM
                LD HL, #0028
                ADD HL, BC
                ; перенос кода просмотрщика в #9648..#9B59
                LD DE, CODE_BASE
                LD BC, CODE_SIZE
                LDIR
                ; расчёт базы шрифта для ROM, начало глифов минус 256
                DEC H
                LD (CHARS), HL
                JP Initialize
