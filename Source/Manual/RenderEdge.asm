
; -----------------------------------------------------------------------------
; вывод одного или двух растровых срезов текста у края окна
; In:
;   TextPointer - начало строки, GlyphRow - строка глифа
;   Reverse, DoubleStep - направление и величина шага
; Out:
;   буфер края заполнен, GlyphRow и при необходимости TextPointer изменены
; Corrupt:
;   HL, DE, BC, AF, HL', BC'
; Note:
;   коды 1-31 задают пробелы, 0 завершает текстовую строку
;   строка дополняется пробелами до 32 знакомест, входные строки должны укладываться в эту ширину
;   Reverse и DoubleStep имеют значения 0/1, FrameDelay равен 1..11 для одного растра и 1..4 для двух
;   индикатор задержки рисуется в атрибутах #5AE0..#5AFF
; -----------------------------------------------------------------------------
RenderEdge:     ; вывод одного или двух растровых срезов текста у края окна
                PUSH HL
                ; расчёт длины индикатора скорости по задержке и размеру шага
                LD HL, (FrameDelay)
                LD A, (DoubleStep)
                AND A
                LD A, #10
                JR NZ, SetBarLength                                             ; переход, если включён сдвиг по две пиксельные строки

                LD A, #0C
SetBarLength:   ; число цветных атрибутов равно пределу режима минус задержка
                SUB L
                LD HL, SPEED_ATTR
FillBar:        ; обновление цветной части индикатора в строке атрибутов #5AE0
                ; обновление цветной части индикатора в строке атрибутов #5AE0
                LD (HL), #28
                INC HL
                DEC A
                JR NZ, FillBar                                                  ; переход, если остались цветные клетки индикатора скорости

ClearBar:       ; очистка оставшейся части индикатора до #5AFF включительно
                ; очистка оставшейся части индикатора до #5AFF включительно
                LD (HL), #00
                INC L
                JR NZ, ClearBar                                                 ; переход, если младший байт адреса ещё не достиг границы строки атрибутов

                POP HL
                ; расчёт числа рисуемых растровых строк, один или два шага
                LD A, (DoubleStep)
                INC A
                ; обновление непосредственного счётчика строки RenderRow
                LD (RowCount + 1), A
                ; проверка режима одного или двух пикселей за сдвиг
                DEC A
                RRCA
                JR C, SetDoubleStep                                             ; переход, если младший бит режима задаёт сдвиг по две строки

                ; обновление старших байтов источников для однострочного сдвига
                LD A, #41
                LD (FromDown + 2), A
                LD A, #56
                LD (FromUp + 2), A
                JR SelectEdge

SetDoubleStep:  ; обновление старших байтов источников для двухстрочного сдвига
                ; обновление старших байтов источников для двухстрочного сдвига
                LD A, #42
                LD (FromDown + 2), A
                LD A, #55
                LD (FromUp + 2), A
SelectEdge:     ; выбор нижнего или верхнего буфера новой растровой строки
                ; выбор нижнего или верхнего буфера новой растровой строки
                LD DE, EDGE_BOTTOM
                LD A, (Reverse)
                AND A
                JR Z, RowCount                                                  ; переход, если выбрана обычная прокрутка и нижний буфер строки

                LD DE, EDGE_TOP
RowCount:       ; изменяемый счётчик одного либо двух растров за сдвиг
                LD B, #01
RenderRow:      ; построение очередного растра шириной 32 знакоместа
                PUSH BC
                ; чтение начала текущей текстовой строки и обнуление числа знакомест
                LD HL, (TextPointer)
                LD C, #00
ReadCharacter:  ; проверка разделителя строки и продвижение указателя входного текста
                ; проверка разделителя строки и продвижение указателя входного текста
                LD A, (HL)
                AND A
                INC HL
                JR Z, EndTextLine                                               ; переход, если прочитан нулевой разделитель текстовых строк

                ; проверка токена пробелов в диапазоне 1-31
                CP #20
                JR NC, RenderLiteral                                            ; переход, если код не меньше 32 и обозначает печатный символ

ExpandSpaces:   ; преобразование счётчика пробелов в число выводимых пустых глифов
                ; преобразование счётчика пробелов в число выводимых пустых глифов
                LD B, A
RenderSpaces:   ; вывод B пустых глифов с продвижением края
                LD A, #20
                CALL RenderGlyph
                INC C
                DJNZ RenderSpaces

                JR ReadCharacter

RenderLiteral:  ; отрисовка одного печатного глифа в текущей растровой строке
                ; отрисовка одного печатного глифа в текущей растровой строке
                CALL RenderGlyph
                INC C
                JR ReadCharacter

EndTextLine:    ; расчёт числа пробелов до правой границы 32 знакомест
                ; расчёт числа пробелов до правой границы 32 знакомест
                DEC HL
                LD A, #20
                SUB C
                JR NZ, ExpandSpaces                                             ; переход, если до правой границы остаются незаполненные позиции

                ; расчёт следующей строки глифа и проверка завершения восьмистрочного знакоместа
                INC HL
                LD A, (GlyphRow)
                INC A
                CP #08
                RES MAN_WRAP_BIT, A
                LD (GlyphRow), A
                CALL NC, AdvanceText                                            ; вызов, если счётчик достиг восьмой строки знакоместа
                ; выбор второй буферной строки при двухпиксельном сдвиге
                LD DE, EDGE_NEXT
                LD A, (Reverse)
                AND A
                JR Z, NextRaster                                                ; переход, если выбрана обычная прокрутка и вторая нижняя строка буфера

                LD DE, EDGE_PREV
NextRaster:     ; восстановление счётчика растров и переход ко второму срезу
                POP BC
                DJNZ RenderRow

                RET

                ; проверка исходной границы блока
                assert $ = #996F
