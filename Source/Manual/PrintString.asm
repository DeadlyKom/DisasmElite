
; -----------------------------------------------------------------------------
; вывод строки ROM до ограничителя #FF
; In:
;   HL - адрес первого байта строки
; Out:
;   HL - адрес ограничителя #FF
;   AF - A=0 и Z=1 после обнаружения ограничителя
; Corrupt:
;   AF и регистры, изменяемые обработчиком RST #10
; Note:
;   управляющие байты AT и INK интерпретирует ROM
; -----------------------------------------------------------------------------
PrintString:    ; вывод строки ROM до ограничителя #FF
                ; проверка конца строки, обозначенного байтом 255
                LD A, (HL)
                INC A
                RET Z                                                           ; выход, если прочитан завершающий байт 255

                ; вывод текущего байта через обработчик печати ROM
                DEC A
                RST #10
                INC HL
                JR PrintString

                ; проверка исходной границы блока
                assert $ = #977F
