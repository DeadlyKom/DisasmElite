OutputByte      EQU 0                                                           ; нулевое смещение выходного байта, IX является курсором распаковки

; -----------------------------------------------------------------------------
; распаковка текста с литералами, словарём пар и обратными ссылками
; In:
;   HL - начало упакованного потока #C9BC
; Out:
;   IX - курсор потока распаковки, нулевое смещение OutputByte обозначает текущий байт
;   после возврата IX указывает за результатом, для оригинала #FCBF
; Corrupt:
;   HL, DE, BC, AF, IX
; Note:
;   вход заканчивается перед словарём #FF80..#FFFF
;   0-127 - литерал, 192-255 - индекс одной из 64 пар
;   128-191 - расстояние 11 бит и длина 3-10 байт
;   копирование обратной ссылки допускает перекрытие
;   схема токена и маски полей описаны в Includes/Const/DiskFlags.inc
;   получено 23743 байта, результат #A000..#FCBE
; -----------------------------------------------------------------------------
UnpackText:     ; распаковка текста с литералами, словарём пар и обратными ссылками
                ; установка адреса результата и начала словаря двухбайтовых пар
                LD IX, TEXT_BEGIN
                LD DE, TEXT_DICTIONARY
NextToken:      ; проверка конца упакованного потока по адресу #FF80
                ; проверка конца упакованного потока по адресу #FF80
                AND A
                SBC HL, DE
                RET NC                                                          ; выход, если входной указатель достиг начала словаря пар

                ; восстановление входного указателя после сравнения и чтение токена
                ADD HL, DE
                LD A, (HL)
                ; проверка старшего бита, различающего литерал и упакованный токен
                BIT PACK_CODE_BIT, A
                JR NZ, PackedToken                                              ; переход, если старший бит токена установлен и требуется распаковка

WriteLiteral:   ; сохранение литерала и продвижение входного и выходного указателей
                ; сохранение литерала и продвижение входного и выходного указателей
                INC HL
                LD (IX + OutputByte), A
                INC IX
                JR NextToken

PackedToken:    ; проверка формата токена, обратная ссылка или словарь пар
                ; проверка формата токена, обратная ссылка или словарь пар
                CP PACK_PAIR_MIN
                JR C, BackReference                                             ; переход, если токен меньше 192 и задаёт обратную ссылку

                ; расчёт адреса пары, #FF00 + ((токен * 2) AND 255)
                ADD A, A
                PUSH HL
                LD L, A
                LD H, #FF
                ; сохранение первого символа пары и передача второго общему пути литерала
                LD A, (HL)
                INC HL
                LD (IX + OutputByte), A
                INC IX
                LD A, (HL)
                POP HL
                JR WriteLiteral

BackReference:  ; чтение младшего байта расстояния и сохранение входного указателя в стеке
                ; чтение младшего байта расстояния и сохранение входного указателя в стеке
                INC HL
                LD C, (HL)
                PUSH IX
                EX (SP), HL
                ; расчёт начала обратной ссылки, IX - ((токен AND 7) * 256 + следующий байт)
                PUSH AF
                AND PACK_DIST_MASK
                LD B, A
                SBC HL, BC
                ; расчёт длины обратной ссылки, ((токен >> 3) AND 7) + 3
                POP AF
                RRCA
                RRCA
                RRCA
                AND PACK_LEN_MASK
                ADD A, PACK_LEN_BIAS
                LD B, A
CopyReference:  ; копирование обратной ссылки вперёд с допустимым перекрытием результата
                ; копирование обратной ссылки вперёд с допустимым перекрытием результата
                LD A, (HL)
                INC HL
                LD (IX + OutputByte), A
                INC IX
                DJNZ CopyReference

                ; восстановление входного указателя после второго байта токена
                POP HL
                INC HL
                JR NextToken

                ; проверка исходной границы блока
                assert $ = #9B5A
