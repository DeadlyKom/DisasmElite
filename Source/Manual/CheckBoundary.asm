
; -----------------------------------------------------------------------------
; проверка ограничения области текста в текущем режиме просмотра
; In:
;   HL - проверяемая позиция текста
; Out:
;   AF - Z установлен при обнаружении запрещённой границы
;   HL сохранён
; Corrupt:
;   AF
; Note:
;   в отдельном разделе границей является любая решётка
;   для полного просмотра применяются маркеры 1 и 7 согласно направлению
;   байт #FF также считается границей
; -----------------------------------------------------------------------------
CheckBoundary:  ; проверка ограничения области текста в текущем режиме просмотра
                ; проверка байта-ограничителя 255 перед руководством
                LD A, (HL)
                INC A
                RET Z                                                           ; выход, если текущий байт равен ограничителю 255

                ; проверка начала маркера раздела
                LD A, (HL)
                CP #23
                RET NZ                                                          ; выход, если текущий байт не является маркером раздела

                ; проверка режима одного раздела или полного руководства
                LD A, (Selection)
                CP #30
                JR NZ, BoundaryFound                                            ; переход, если просматривается отдельный раздел и любой маркер ограничивает его

                ; выбор предельного маркера для текущего направления
                LD A, (Reverse)
                AND A
                LD A, #37
                JR NZ, CheckMarker                                              ; переход, если направление обратное и ограничителем служит маркер 7

                LD A, #31
CheckMarker:    ; проверка номера раздела без изменения итогового указателя
                ; проверка номера раздела без изменения итогового указателя
                INC HL
                CP (HL)
                DEC HL
                RET

BoundaryFound:  ; установка Z для любой границы при просмотре одного раздела
                ; установка Z для любой границы при просмотре одного раздела
                XOR A
                RET

                ; проверка исходной границы блока
                assert $ = #9A46
