
; -----------------------------------------------------------------------------
; очистка экрана ROM и печать заголовка
; In:
;   нет
; Out:
;   HL - завершающий байт заголовка
; Corrupt:
;   HL, DE, BC, AF согласно вызовам ROM
; Note:
;   переходит в PrintString без дополнительного CALL
; -----------------------------------------------------------------------------
ClearAndTitle:  ; очистка экрана ROM и печать заголовка
                ; очистка ROM-экрана и выбор верхнего потока
                CALL ROM_CLS
                LD A, #02
                CALL ROM_CHAN_OPEN
                LD HL, Title

                ; проверка исходной границы блока
                assert $ = #9777
