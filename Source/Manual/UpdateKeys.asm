
; -----------------------------------------------------------------------------
; опрос управления и согласование указателя при смене направления
; In:
;   состояние прокрутки и матрица клавиатуры
; Out:
;   состояние обновлено, при необходимости TextPointer смещён на 20 строк
; Corrupt:
;   HL, BC, AF
; Note:
;   перемена направления запрещается внутри знакоместа
;   байт #01 в #9A0E образует перекрытие с CPIR в #9A0F
;   при обратном проходе выполняется LD BC,#B1ED и CPIR пропускается
; -----------------------------------------------------------------------------
UpdateKeys:     ; опрос управления и согласование указателя при смене направления
                ; перезапуск таймера опроса клавиш на десять кадров
                LD A, #0A
                LD (KeyTimer), A
                ; сохранение направления для обнаружения его изменения после опроса
                LD A, (Reverse)
                PUSH AF
                CALL ReadControls
                POP AF
                ; проверка изменения направления
                LD HL, Reverse
                XOR (HL)
                RET Z                                                           ; выход, если направление после опроса клавиш не изменилось

                ; проверка возможности сменить направление на границе знакоместа
                LD A, (GlyphRow)
                AND MAN_ROW_MASK
                JR NZ, UndoDirection                                            ; переход, если смена направления произошла внутри знакоместа

                ; смещение указателя текста на двадцать строк при смене направления
                LD HL, (TextPointer)
                LD B, #14
ShiftWindow:    ; проверка границы перед поиском следующей строки окна
                ; проверка границы перед поиском следующей строки окна
                CALL CheckBoundary
                JR Z, UndoDirection                                             ; переход, если смещение видимого окна упирается в границу текста

                PUSH BC
                LD BC, #0000
                ; проверка направления поиска нулевого разделителя
                LD A, (Reverse)
                AND A
                LD A, B
                JR Z, ScanForward                                               ; переход, если новое направление обычное, к поиску следующего конца строки

                ; поиск предыдущего нулевого разделителя и восстановление начала строки
                DEC HL
                DEC HL
                CPDR
                LD A, (HL)
                INC HL
                INC HL
SkipForward:    ; общий байт перекрывающихся потоков
                ; сохранение префикса LD BC, который поглощает ED B1 следующей инструкции
                DB #01
ScanForward:    ; поиск следующего нулевого разделителя при обычном направлении
                ; поиск следующего нулевого разделителя при обычном направлении
                CPIR
                POP BC
                ; проверка ограничителя перед текстом после обратного поиска
                INC A
                JR Z, UndoDirection                                             ; переход, если при обратном поиске достигнут байт-ограничитель 255

                DJNZ ShiftWindow

                ; проверка окончательного положения указателя после двадцати строк
                CALL CheckBoundary
                JR Z, UndoDirection                                             ; переход, если конечная позиция сдвинутого окна лежит на границе текста

                ; сохранение указателя сдвинутого окна
                LD (TextPointer), HL
                RET

                ; проверка исходной границы блока
                assert $ = #9A20
