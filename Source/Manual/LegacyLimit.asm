
; -----------------------------------------------------------------------------
; сохранённый дополнительный путь проверки маркера первого раздела
; In:
;   HL - проверяемая позиция текста
; Out:
;   флаги либо изменение ViewState
; Corrupt:
;   HL, AF
; Note:
;   прямые входящие переходы из 1298-байтового блока не обнаружены
;   назначение не расширено предположениями, байты сохранены как инструкции
; -----------------------------------------------------------------------------
LegacyLimit:    ; сохранённый дополнительный путь проверки маркера первого раздела
                ; сохранённая проверка старого пути, входящих прямых переходов в блок не найдено
                LD A, (HL)
                ; проверка маркера в сохранённом старом пути
                CP #23
                RET NZ                                                          ; выход, если текущая строка не начинается с маркера раздела

                ; проверка начала первого раздела в сохранённом старом пути
                INC HL
                LD A, (HL)
                CP #31
                JR NZ, SectionLimit                                             ; переход, если маркер не равен началу первого раздела

                JR RestartText

                ; проверка исходной границы блока
                assert $ = #99B7
