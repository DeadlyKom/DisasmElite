
; -----------------------------------------------------------------------------
; поиск раздела и управление просмотром через прерывания IM 2
; In:
;   Selection - ASCII-код цифры 0-6
; Out:
;   возврат к вызвавшему коду после выхода из просмотра
; Corrupt:
;   HL, DE, BC, AF, HL', BC', I
;   SP, режим IM и разрешение прерываний
; Note:
;   ViewState - 255 продолжение, 0 повторный запуск, 69 выход
;   слово IRQ_VECTOR предполагает младший байт шины прерывания #FF
;   ReturnStack + 1 хранит SP для выхода из обработчика
;   после первого поиска нуля цикл просматривает байты последовательно, маркеры в исходном тексте стоят в началах строк
;   вызов сохраняет семантику оригинального CPIR и не требует нового нуля перед каждой решёткой
; -----------------------------------------------------------------------------
ShowSection:    ; поиск раздела и управление просмотром через прерывания IM 2
                ; сброс направления и номера строки глифа перед новым просмотром
                XOR A
                LD (Reverse), A
                LD (GlyphRow), A
                ; создание ограничителя 00 FF перед началом распакованного текста
                LD (TEXT_SENTINEL), A
                DEC A
                LD (TEXT_SENTINEL + 1), A
                ; сохранение стека вызова в операнде аварийного возврата из прерывания
                LD (ReturnSP), SP
                LD A, (Selection)
                LD HL, TEXT_BEGIN
                ; преобразование выбора 0 в номер первого раздела
                CP #30
                JR NZ, FindSection                                              ; переход, если выбран отдельный раздел, а не режим 0

                INC A
FindSection:    ; сохранение ASCII-номера искомого раздела в E
                LD E, A
                ; первый CPIR пропускает строку оглавления до нуля
                XOR A
                LD BC, #0000
FindMarker:     ; поиск очередного кандидата на маркер раздела
                ; после несовпадения A уже равен текущему (HL), повторный CPIR продвигает HL на один байт
                CPIR
                ; проверка очередного байта на символ решётки
                LD A, (HL)
                CP #23
                JR NZ, FindMarker                                               ; переход, если текущий байт не является решёткой, продолжить поиск

                ; проверка номера найденного раздела
                INC HL
                LD A, (HL)
                CP E
                JR NZ, FindMarker                                               ; переход, если номер найденного раздела не совпадает с выбранным

                ; пропуск найденной цифры раздела через CPIR, A и текущий байт HL уже совпадают
                CPIR
                ; сохранение указателя текста и установка исходного вектора IM 2
                LD (TextPointer), HL
                LD A, #5C
                LD I, A
                LD HL, Interrupt
                LD (IRQ_VECTOR), HL
                IM 2
                ; установка состояния продолжающегося просмотра
                LD A, #FF
                LD (ViewState), A
WaitFrame:      ; ожидание следующего кадра и проверка команды просмотра
                EI
                HALT
                DI
                ; проверка команды, оставленной обработчиком прерывания
                LD A, (ViewState)
                AND A
                JP Z, ShowSection                                               ; переход, если обработчик установил состояние 0 и требуется повторный запуск раздела

                ; проверка активного состояния 255
                INC A
                JR Z, WaitFrame                                                 ; переход, если состояние просмотра равно 255 и просмотр продолжается

                IM 1
                RET

                ; проверка исходной границы блока
                assert $ = #974E
