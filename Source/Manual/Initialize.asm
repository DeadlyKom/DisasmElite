
; -----------------------------------------------------------------------------
; подготовка шрифта и распаковка руководства перед входом в меню
; In:
;   HL - указатель CHARS, переданный bootstrap
;   стек - адрес Manual.PACK_BASE на вершине
; Out:
;   передача управления ShowMenu
; Corrupt:
;   HL, DE, BC, AF, IX
; Note:
;   строчная латиница a-z расширяется вправо на один бит
;   распаковка завершается до переноса SP в STACK_TOP
; -----------------------------------------------------------------------------
Initialize:     ; подготовка шрифта и распаковка руководства перед входом в меню
                ; расчёт адреса строчной латиницы, CHARS + 97 * 8
                LD DE, #0308
                ADD HL, DE
                LD B, #D0
BoldLoop:       ; преобразование 208 строк глифов a-z, (исходный байт OR исходный байт >> 1) AND 127
                LD A, (HL)
                ADD A, A
                OR (HL)
                SRL A
                LD (HL), A
                INC HL
                DJNZ BoldLoop

                ; восстановление начала упакованного потока из стека bootstrap
                POP HL
                ; распаковка руководства в исходную область Manual.TEXT_BEGIN
                CALL UnpackText
                ; установка стека у верхней границы памяти после завершения распаковки
                LD SP, STACK_TOP

                ; проверка исходной границы блока
                assert $ = #965E
                ; JP ShowMenu, продолжение в Menu.asm
