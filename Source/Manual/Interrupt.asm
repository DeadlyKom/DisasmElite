
; -----------------------------------------------------------------------------
; кадровый обработчик клавиатуры и пиксельной прокрутки
; In:
;   KeyTimer, ScrollTimer - текущие счётчики
; Out:
;   обновлённые счётчики, экран и состояние просмотра
; Corrupt:
;   HL, DE, BC, AF, HL', BC'
;   HL и AF меняются только при нелокальном выходе SPACE, обычный эпилог их восстанавливает
; Note:
;   основной цикл ожидает HALT, обычный путь явно сохраняет HL и AF
;   DE', AF', IX и IY процедуры просмотрщика не используют и не меняют
;   порт #7DFE объединяет ряды A-S-D-F-G и SPACE-SYMBOL SHIFT-M-N-B
;   A, S, SPACE и SYMBOL SHIFT вызывают немедленный опрос, смысловые команды проверяет ReadControls
;   обычный выход выполнен через EI и RET, не RETI
;   выход SPACE восстанавливает SP ShowSection и обходит этот эпилог
; -----------------------------------------------------------------------------
Interrupt:      ; кадровый обработчик клавиатуры и пиксельной прокрутки
                DI
                PUSH AF
                PUSH HL
                ; опрос двух совмещённых рядов клавиатуры для немедленной реакции на управление
                LD A, #7D
                IN A, (#FE)
                OR MAN_KEYS_IGNORE
                INC A
                CALL NZ, UpdateKeys                                             ; вызов, если в объединённых рядах клавиатуры нажата одна из двух младших клавиш
                ; обновление таймера планового опроса клавиатуры
                LD HL, KeyTimer
                DEC (HL)
                CALL Z, UpdateKeys                                              ; вызов, если истёк счётчик опроса клавиатуры
                ; проверка паузы прокрутки и обновление счётчика кадров
                LD HL, ScrollTimer
                LD A, (HL)
                AND A
                JR Z, InterruptExit                                             ; переход, если счётчик прокрутки равен нулю и установлен режим паузы

                ; проверка момента выполнения следующего пиксельного сдвига
                DEC (HL)
                CALL Z, ScrollFrame                                             ; вызов, если счётчик кадров до следующего сдвига достиг нуля
InterruptExit:  ; восстановление HL и AF, возврат в прерванный основной цикл
                POP HL
                POP AF
                EI
                RET

                ; проверка исходной границы блока
                assert $ = #9863
