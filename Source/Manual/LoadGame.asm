
; -----------------------------------------------------------------------------
; запуск токенизированной команды загрузки ELITE3 через TR-DOS
; In:
;   LoadCommand - исходная последовательность REM и LOAD
; Out:
;   возврат к меню, если TR-DOS вернул управление
; Corrupt:
;   HL, DE, BC, AF согласно вызванному ROM/TR-DOS
; Note:
;   CHARS временно указывает на стандартный шрифт #3C00
;   CH_ADD получает адрес встроенной BASIC-команды
; -----------------------------------------------------------------------------
LoadGame:       ; запуск токенизированной команды загрузки ELITE3 через TR-DOS
                ; сохранение пользовательского шрифта перед передачей команды TR-DOS
                LD HL, (CHARS)
                PUSH HL
                ; подстановка стандартного ROM-шрифта и адреса токенизированной команды
                LD HL, ROM_FONT
                LD (CHARS), HL
                LD HL, LoadCommand
                LD (CH_ADD), HL
                CALL TRDOS_COMMAND
                ; восстановление шрифта и возврат меню, если команда TR-DOS вернулась
                POP HL
                LD (CHARS), HL
                JP ShowMenu

                ; проверка исходной границы блока
                assert $ = #9768
