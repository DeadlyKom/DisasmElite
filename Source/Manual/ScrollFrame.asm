
; -----------------------------------------------------------------------------
; подготовка края и сдвиг окна высотой 152 пиксельные строки
; In:
;   Reverse, DoubleStep, FrameDelay - параметры сдвига
; Out:
;   экран обновлён, ScrollTimer перезапущен
; Corrupt:
;   HL, DE, BC, AF, HL', BC'
; Note:
;   область вывода занимает экранные строки 16-167
;   32 развёрнутых LDI копируют все 256 пикселей строки
;   два вызова шага с EX DE,HL обновляют оба адреса
; -----------------------------------------------------------------------------
ScrollFrame:    ; подготовка края и сдвиг окна высотой 152 пиксельные строки
                ; отрисовка новой строки у края до перемещения экранного окна
                CALL RenderEdge
                ; перезапуск задержки следующего сдвига
                LD A, (FrameDelay)
                LD (ScrollTimer), A
                ; выбор направления и функций перехода по строкам экрана
                LD A, (Reverse)
                AND A
                LD HL, NextScanline
                JR Z, SetLineStep                                               ; переход, если выбрана обычная прокрутка вверх

                LD HL, PrevScanline
SetLineStep:    ; обновление адресов двух CALL согласно направлению прокрутки
                ; обновление адресов двух CALL согласно направлению прокрутки
                LD (StepSource + 1), HL
                LD (StepDest + 1), HL
FromDown:       ; выбор исходной и целевой строк для движения текста вверх
                ; выбор исходной и целевой строк для движения текста вверх
                LD HL, VIEW_NEXT
                LD DE, VIEW_TOP
                JR Z, CopyArea                                                  ; переход, если сохранён признак обычной прокрутки вверх

FromUp:         ; выбор исходной и целевой строк для движения текста вниз
                ; выбор исходной и целевой строк для движения текста вниз
                LD HL, VIEW_PREV
                LD DE, VIEW_BOTTOM
CopyArea:       ; копирование 152 экранных строк по 32 байта
                ; копирование 152 экранных строк по 32 байта
                LD B, #98
CopyLine:       ; сохранение адресов и счётчика перед копированием полной строки
                PUSH BC
                PUSH HL
                PUSH DE
                ; перенос полной строки пикселей, сохранённый BC восстановится после 32 LDI
                LDI
                LDI
                LDI
                LDI
                LDI
                LDI
                LDI
                LDI
                LDI
                LDI
                LDI
                LDI
                LDI
                LDI
                LDI
                LDI
                LDI
                LDI
                LDI
                LDI
                LDI
                LDI
                LDI
                LDI
                LDI
                LDI
                LDI
                LDI
                LDI
                LDI
                LDI
                LDI
                POP DE
                POP HL
                POP BC
StepSource:     ; расчёт адреса следующей строки каждого из двух указателей
                ; расчёт адреса следующей строки каждого из двух указателей
                CALL NextScanline
StepDest:       ; второй обмен указателей и продвижение оставшегося адреса
                CALL NextScanline
                DJNZ CopyLine

                RET

                ; проверка исходной границы блока
                assert $ = #98DD
