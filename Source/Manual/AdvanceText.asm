
; -----------------------------------------------------------------------------
; переход к следующей или предыдущей строке после восьми растров
; In:
;   HL - начало следующей строки при прямом просмотре
;   Reverse, Selection, TextPointer - состояние просмотра
; Out:
;   TextPointer обновлён либо изменён ViewState/Reverse
; Corrupt:
;   HL, BC, AF
; Note:
;   в режиме 0 разрешён проход через промежуточные маркеры разделов
;   обратное направление использует поиск нуля через CPDR
; -----------------------------------------------------------------------------
AdvanceText:    ; переход к следующей или предыдущей строке после восьми растров
                ; проверка направления перехода между текстовыми строками
                LD A, (Reverse)
                AND A
                JR NZ, PreviousText                                             ; переход, если выбрано обратное направление просмотра

                ; сохранение следующей строки и проверка маркера нового раздела
                LD (TextPointer), HL
                LD A, (HL)
                CP #23
                RET NZ                                                          ; выход, если следующая строка не начинается с маркера раздела

                ; проверка завершающего маркера 7
                INC HL
                LD A, (HL)
                CP #37
                JR NZ, SectionLimit                                             ; переход, если найденный маркер не является завершающим разделом 7

RestartText:    ; установка команды повторного запуска выбранного просмотра
                XOR A
                LD (ViewState), A
                RET

SectionLimit:   ; проверка разрешения перехода между разделами в режиме 0
                LD A, (Selection)
                CP #30
                RET Z                                                           ; выход, если выбран режим 0 и разрешён переход к следующему разделу

                JR RestartText

PreviousText:   ; проверка границы перед переходом к предыдущей текстовой строке
                CALL CheckBoundary
                JP Z, UndoDirection                                             ; переход, если текущая позиция лежит на запрещённой границе

                ; поиск предыдущего нулевого разделителя через CPDR
                LD HL, (TextPointer)
                DEC HL
                DEC HL
                XOR A
                LD B, A
                LD C, A
                CPDR
                INC HL
                INC HL
                ; проверка допустимости найденного начала строки
                CALL CheckBoundary
                JP Z, UndoDirection                                             ; переход, если предыдущая строка выходит за разрешённый диапазон

                LD (TextPointer), HL
                RET

                ; проверка исходной границы блока
                assert $ = #99AB
