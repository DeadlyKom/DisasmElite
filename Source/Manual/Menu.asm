
; -----------------------------------------------------------------------------
; вывод оглавления и выбор раздела или загрузки ELITE3
; In:
;   данные - распакованный поток начинается с оглавления
; Out:
;   переход к ShowSection либо LoadGame
; Corrupt:
;   HL, DE, BC, AF, HL', BC', I
;   альтернативные HL/BC меняются при просмотре через ShowSection
; Note:
;   клавиши 0-6 выбирают просмотр, R/r передают команду TR-DOS
;   самомодифицируемый операнд #96B4 остаётся неизменным
;   OR A в #96B8 не является декрементом таймера
; -----------------------------------------------------------------------------
ShowMenu:       ; вывод оглавления и выбор раздела или загрузки ELITE3
                ; создание экрана меню с заголовком и нижней подсказкой
                CALL ClearAndTitle
                ; установка размера нижней области ROM-экрана в три строки
                LD A, #03
                LD (DF_SZ), A
                ; поиск конца оглавления, ограниченного первым маркером раздела
                LD HL, TEXT_BEGIN
                LD DE, #FFFE
CountLines:     ; поиск очередного нулевого конца строки оглавления
                ; поиск очередного нулевого конца строки оглавления
                XOR A
                LD BC, #0000
                CPIR
                INC DE
                ; проверка начала первого раздела после найденного нуля
                LD A, (HL)
                CP #23
                JR NZ, CountLines                                               ; переход, если после конца строки ещё не найден первый маркер раздела

                ; расчёт вертикального положения оглавления, (22 - E) / 2, E равен числу разделителей минус два
                LD A, #16
                RST #10
                LD A, #16
                SUB E
                SRL A
                RST #10
                XOR A
                RST #10
                ; вывод оглавления с раскрытием счётчиков пробелов
                LD HL, TEXT_BEGIN
MenuCharacter:  ; чтение следующего кода оглавления
                LD A, (HL)
                INC HL
                ; проверка нулевого разделителя строк
                AND A
                JR NZ, MenuToken                                                ; переход, если прочитан ненулевой код символа или пробелов

                ; проверка окончания оглавления перед первым разделом
                LD A, (HL)
                CP #23
                JR Z, MenuPrompt                                                ; переход, если после конца строки начинается первый раздел

                ; переход на новую экранную строку и добавление двух левых пробелов
                LD A, #0D
                RST #10
                LD BC, #0220
MenuSpaces:     ; вывод B пробелов через ROM
                LD A, C
                RST #10
                DJNZ MenuSpaces

                JR MenuCharacter

MenuToken:      ; проверка отличия печатного символа от счётчика пробелов
                ; проверка отличия печатного символа от счётчика пробелов
                CP #20
                JR NC, MenuLiteral                                              ; переход, если код не меньше 32 и обозначает печатный символ

                LD B, A
                LD C, #20
                JR MenuSpaces

MenuLiteral:    ; вывод печатного символа оглавления через ROM
                RST #10
                JR MenuCharacter

MenuPrompt:     ; выбор нижнего потока ROM и вывод подсказки выбора
                ; выбор нижнего потока ROM и вывод подсказки выбора
                LD A, #01
                CALL ROM_CHAN_OPEN
                LD HL, MenuHint
                CALL PrintString
MenuPoll:       ; проверка встроенного операнда ожидания, в исходнике OR A не уменьшает его
                ; проверка встроенного операнда ожидания, в исходнике OR A не уменьшает его
                LD A, #96
                AND A
                JR Z, WaitKey                                                   ; переход, если операнд ожидания равен нулю

                ; сохранение неизменённого операнда, автоматический выбор здесь не срабатывает
                OR A
                LD (MenuPoll + 1), A
                LD A, #30
                JR Z, CheckDigit                                                ; переход, если A равен нулю после OR A, при штатном исполнении ветвь недостижима

WaitKey:        ; ожидание кадрового опроса ROM-клавиатуры
                EI
                HALT
                ; чтение записи ROM-клавиатуры после кадрового прерывания
                LD A, (KEY_RECORD)
                ; проверка отсутствия клавиши
                CP #FF
                JR Z, MenuPoll                                                  ; переход, если запись клавиатуры равна 255 и новой клавиши нет

                ; проверка команды запуска игры строчной буквой r
                CP #72
                JP Z, LoadGame                                                  ; переход, если прочитана строчная r, к загрузке игры

                ; проверка команды запуска игры прописной буквой R
                CP #52
                JP Z, LoadGame                                                  ; переход, если прочитана прописная R, к загрузке игры

                ; проверка нижней границы диапазона клавиш 0-6
                CP #30
                JR C, MenuPoll                                                  ; переход, если код клавиши меньше кода цифры 0

CheckDigit:     ; проверка верхней границы диапазона клавиш 0-6
                ; проверка верхней границы диапазона клавиш 0-6
                CP #37
                JR NC, MenuPoll                                                 ; переход, если код клавиши не меньше кода цифры 7

                ; сохранение выбранного раздела и начального состояния прокрутки
                LD (Selection), A
                XOR A
                LD (GlyphRow), A
                INC A
                LD (ScrollTimer), A
                ; создание экрана просмотра и вывод подсказки управления
                CALL ClearAndTitle
                LD A, #01
                CALL ROM_CHAN_OPEN
                LD HL, ScrollHint
                CALL PrintString
                CALL ShowSection
                JP ShowMenu

                ; проверка исходной границы блока
                assert $ = #96FA
