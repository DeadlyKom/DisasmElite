
; -----------------------------------------------------------------------------
; немедленное продолжение сдвига до границы знакоместа
; In:
;   нет
; Out:
;   KeyTimer = 1, ScrollTimer = 1
; Corrupt:
;   AF
; Note:
;   используется при попытке остановить или изменить шаг посреди символа
; -----------------------------------------------------------------------------
ResumePixel:    ; немедленное продолжение сдвига до границы знакоместа
                ; перезапуск обоих таймеров для доведения сдвига до границы глифа
                LD A, #01
                LD (KeyTimer), A
                LD (ScrollTimer), A
                RET

                ; проверка исходной границы блока
                assert $ = #9A4F
