
; -----------------------------------------------------------------------------
; переход к предыдущей пиксельной строке Spectrum с обменом указателей
; In:
;   HL - второй указатель
;   DE - адрес текущей пиксельной строки
; Out:
;   HL - предыдущая пиксельная строка исходного DE
;   DE - исходный HL
; Corrupt:
;   AF
; Note:
;   учтены чередование знакомест и границы третей экрана
; -----------------------------------------------------------------------------
PrevScanline:   ; переход к предыдущей пиксельной строке Spectrum с обменом указателей
                ; расчёт предыдущей пиксельной строки с обменом HL и DE
                EX DE, HL
                LD A, H
                DEC H
                ; проверка первой растровой строки знакоместа
                AND #07
                RET NZ                                                          ; выход, если исходная строка не была первой строкой знакоместа

                ; расчёт предыдущей строки знакомест с учётом перехода между третями экрана
                LD A, L
                SUB #20
                LD L, A
                RET C                                                           ; выход, если заём младшего байта уже перевёл адрес в предыдущую треть экрана

                ; коррекция старшего байта при переходе внутри одной трети экрана
                LD A, H
                ADD A, #08
                LD H, A
                RET

                ; проверка исходной границы блока
                assert $ = #9B0C
