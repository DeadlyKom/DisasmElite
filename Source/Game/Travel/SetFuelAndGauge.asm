                module SetFuelAndGauge
; -----------------------------------------
; Ограничение топлива и обновление указателя прибора
; исходный диапазон #DEA2..#DF02
; In:
;   AF, A = запас в десятых светового года
; Out:
;   D082=min(A, 70), 70EC=2*D082+floor(D082/4)
; Corrupt:
;   BC, AF
; Note:
;   Насыщает входы>=71 до 70, после RET от DEB9 начинается блок семян, имён, параметров планеты
;   и рабочих переменных до DF02
; -----------------------------------------
                ; проверка исходного начала фрагмента
                ASSERT $ == #DEA2
                ; насыщение запаса топлива до 70 и пересчёт указателя прибора
Entry:          CP #47
                JR C, StoreFuel                                                 ; переход, если запрошенное топливо меньше 71, ограничивать его не нужно

                LD A, #46
StoreFuel:      LD (State.Fuel), A
                SLA A
                LD B, A
                SRL A
                SRL A
                SRL A
                ADD A, B
                LD (GaugeState + FGaugeState.Fuel.Current), A
                RET
                ; сохранённый байт перед областью выбранной системы
SeedPrefix      DB #00                                                          ; сохранённый байт перед семенами систем
                ; шесть байтов семени выбранной цели
TargetSeed      DB #38, #AD, #9C, #14, #1D, #15                                 ; шестибайтовое семя выбранной цели
                ; рабочее шестибайтовое семя генератора систем
WorkingSeed     DB #BC, #57, #82, #0A, #63, #AD                                 ; рабочее семя перебора и генерации имени
                ; резервная копия рабочего семени для временного перебора
SavedSeed       DB #38, #AD, #9C, #14, #1D, #15                                 ; копия рабочего семени на время вложенного перебора
                ; четыре байта отдельного генератора описаний
TextSeed        DB #00, #00, #00, #00                                           ; четыре байта генератора описаний
                ; буфер строкового ввода, десять символов и нулевой завершитель
InputBuffer     DB #4A, #41, #4D, #45, #53, #4F, #4E, #20                       ; десять вводимых символов и завершающий ноль
                DB #20, #20, #00                                                ; #DED8..#DEDA
                ; буфер сгенерированного имени системы, восемь символов и ноль
GeneratedName   DB #4C, #41, #56, #45, #00, #00, #00, #00                       ; восемь букв имени и завершающий ноль
                DB #00                                                          ; #DEE3..#DEE3
                ; сохранённое имя текущей системы
CurrentName     DB #4C, #41, #56, #45, #00, #00, #00, #00                       ; сохранённое имя текущей системы
                DB #00                                                          ; #DEEC..#DEEC
                ; сохранённое имя выбранной цели
TargetName      DB #4C, #41, #56, #45, #00, #00, #00, #00                       ; сохранённое имя выбранной цели
                DB #00                                                          ; #DEF5..#DEF5
                ; расстояние до цели в десятых светового года
Distance        DW #0000                                                        ; расстояние до цели в десятых светового года
                ; экономика выбранной системы, индекс 0..7
Economy         DB #05                                                          ; экономика выбранной системы, индекс 0..7
                ; правительство выбранной системы, индекс 0..7
Government      DB #03                                                          ; правительство выбранной системы, индекс 0..7
                ; технологический уровень, счёт с нуля
Technology      DB #04                                                          ; технологический уровень, счёт с нуля
                ; население в десятых миллиарда
Population      DB #19                                                          ; население в десятых миллиарда
                ; двухбайтовая производительность системы
Productivity    DW #1B58                                                        ; производительность системы
                ; сохранённые два байта между характеристиками и счётчиком перебора
Reserved        DW #0000                                                        ; сохранённые байты образа, обращений к полю не найдено
                ; счётчик перебора 256 систем, переполнение завершает цикл
ScanIndex       DB #00                                                          ; индекс перебора, переполнение завершает 256 систем
                ; указатель следующего символа генерируемого имени
NameCursor      DW #DEDF                                                        ; адрес следующего символа в GeneratedName
                ; проверка исходного конца фрагмента
                ASSERT $ == #DF03
                endmodule
