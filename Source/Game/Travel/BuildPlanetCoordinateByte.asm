                module BuildPlanetCoordinateByte
; -----------------------------------------
; Формирование очередного байта координаты планеты
; исходный диапазон #DD48..#DD52
; In:
;   HL = предыдущий байт семени, DE = предыдущая выходная позиция, BC = шаг
; Out:
;   HL+1, DE+BC, по DE записано(seed&83) OR1
; Corrupt:
;   HL, DE, AF
; Note:
;   Используется при создании компонент с шагом 3, BC сохраняется
; -----------------------------------------
                ; проверка исходного начала фрагмента
                ASSERT $ == #DD48
                ; построение байта координаты планеты по битам семени системы
Entry:          INC HL
                EX DE, HL
                ADD HL, BC
                EX DE, HL
                LD A, (HL)
                AND #83
                OR #01
                LD (DE), A
                RET
                ; проверка исходного конца фрагмента
                ASSERT $ == #DD53
                endmodule
                endmodule
