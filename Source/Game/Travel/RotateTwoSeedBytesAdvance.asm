                module RotateTwoSeedBytesAdvance
; -----------------------------------------
; Циклический поворот двух байтов семени с продвижением указателя
; исходный диапазон #DC83..#DC8D
; In:
;   HL = адрес двух байтов
; Out:
;   Оба байта RLC на 1, HL увеличен на 2, DE содержит результат
; Corrupt:
;   HL, DE, AF
; Note:
;   Каждый байт вращается независимо, перенос между байтами не передаётся
; -----------------------------------------
                ; проверка исходного начала фрагмента
                ASSERT $ == #DC83
                ; поворот двух байтов семени по кругу через перенос с продвижением HL
Entry:          LD E, (HL)
                RLC E
                LD (HL), E
                INC HL
                LD D, (HL)
                RLC D
                LD (HL), D
                INC HL
                RET
                ; проверка исходного конца фрагмента
                ASSERT $ == #DC8E
                endmodule
                endmodule
