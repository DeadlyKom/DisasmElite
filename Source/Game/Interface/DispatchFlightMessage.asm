                module Interface
                module DispatchFlightMessage
; -----------------------------------------
; Вектор обновления сообщений полётного экрана
; исходный диапазон #D03C..#D041
; In:
;   Нет параметров
; Out:
;   Переход в Game.Travel.UpdateFlightMessages.Entry
; Corrupt:
;   HL, DE, BC, AF
; Note:
;   После JP лежат JumpMode режим перехода, ViewKeyLock блокировка ввода, CloakActive включение маскировки, это
;   переменные, а не продолжение процедуры
; -----------------------------------------
                ; проверка исходного начала фрагмента
                ASSERT $ == #D03C
Entry:          JP Game.Travel.UpdateFlightMessages.Entry

                ; режим перехода, 0 нет запроса, 1 обычный, 2 галактический
JumpMode        DB #00                                                          ; режим перехода, 0 нет, 1 обычный, 2 галактический
                ; блокировка клавиатурного действия после смены экрана
ViewKeyLock     DB #00                                                          ; флаг, блокировка повторной обработки клавиши смены вида
                ; состояние маскировки, обнуляется при аварийном предупреждении
                ; миссия 2 CLOAKING DEVICE, рабочий флаг включённой маскировки отделён от признака наличия устройства
                ; описание в Docs/Manual.md, раздел mission-2
CloakActive     DB #00                                                          ; флаг, включена маскировка корабля
                ; проверка исходного конца фрагмента
                ASSERT $ == #D042
                endmodule
                endmodule
