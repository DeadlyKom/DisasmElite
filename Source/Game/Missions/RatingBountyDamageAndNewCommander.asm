                module Missions
                module RatingBountyDamageAndNewCommander
; -----------------------------------------
; прибавление к рейтингу и обработка переноса, #D1C7
; исходный диапазон #D1C7..#D2DD
; In:
;   DE, беззнаковое приращение младшего слова State.Rating
; Out:
;   при отсутствии переноса обновлено только младшее слово рейтинга
;   при переносе старший байт увеличен, обработаны вторжение и событие #D0C9
;   DE, BC, IX, IY сохранены
; Corrupt:
;   HL, AF
; Note:
;   старший байт объединяет числовой рейтинг и военные состояния, после переноса #5E78 может изменить его
;   PayBounty, DamageItem и ResetCommander являются самостоятельными входами
;   между DamageItem и ResetCommander лежит 102-байтовый исходный шаблон командира
; -----------------------------------------
                ; проверка исходного начала фрагмента
                ASSERT $ == #D1C7
                ; сложение DE с младшими 16 битами рейтинга, перенос увеличивает D062
Entry:          LD HL, State.Rating
                LD A, (HL)
                ADD A, E
                LD (HL), A
                INC HL
                LD A, (HL)
                ADC A, D
                LD (HL), A
                RET NC                                                          ; выход, если приращение не переполнило младшее слово рейтинга

                INC HL
                INC (HL)
                CALL Game.Extensions.UpdateInvasionOnRatingOverflow.Entry
                JR SetEvent

                ; дополнительный вход денежной награды, нулевая сумма не создаёт сообщения
; -----------------------------------------
; зачисление денежной награды и постановка уведомления, #D1D9
; In:
;   DE, сумма в десятых кредита, 0..9999
; Out:
;   при DE=0 немедленный возврат без записи
;   иначе CashLow/CashHigh увеличены, #DA77 содержит исходную сумму, #D0C5.7=1
;   BC, IX, IY сохранены, рейтинг не изменяется
; Corrupt:
;   HL, DE, AF
; Note:
;   AddCashLow нормализует младшую денежную группу одним переносом при достижении 10000
;   при ненулевой выплате DE=10000 без переноса либо DE=1 при переносе
; -----------------------------------------
PayBounty:      LD A, D
                OR E
                RET Z                                                           ; выход, если денежная награда DE равна нулю

                LD (FlightMessage.Reward), DE
                CALL Game.Economy.AddCashLow.Entry
                LD HL, FlightEvents + 4 * FFlightEvent
SetEvent:       SET EVENT_WAIT_BIT, (HL)
                RET

                ; выбор повреждения из шести старших битов полётного параметра
; -----------------------------------------
; выбор повреждения по сохранённому полётному параметру, #D1E9
; In:
;   #DA76, код текущего сообщения
;   #7105, сохранённый полётный параметр
; Out:
;   при #DA76=#FD повреждение запрещено
;   индекс 0 обнуляет топливо, 1..6 повреждают устройство, 7..16 одну тонну товара 2..11
;   индексы 17..63 возвращаются без изменения
; Corrupt:
;   HL, DE, BC, AF
; Note:
;   индекс равен #7105 >> 2, два RRCA и AND #3F выделяют старшие шесть битов
;   новых случайных чисел этот вход не получает
;   нулевое поле устройства или пустой слот груза сохраняются
;   для устройства устанавливается бит 7 и прибавляется 1 по модулю 256
;   после повреждения создаётся событие #D0C3 и код предмета в #DA79, обновляются цвета приборов
; -----------------------------------------
DamageItem:     LD A, (FlightMessage.Token)
                CP #FD
                RET Z                                                           ; выход, если код текущего сообщения равен FD, повреждение запрещено

                LD A, (FlightState.RandomByte)
                RRCA
                RRCA
                AND #3F
                JP Z, Game.Travel.EmptyFuelWithWarning.Entry                    ; переход, если случайный индекс повреждения равен нулю, потерять топливо

                CP #11
                RET NC                                                          ; выход, если случайный индекс не меньше 17, ничего не повреждать

                DEC A
                CP #06
                JR NC, DamageCargo                                              ; переход, если после вычитания единицы индекс не меньше 6, повреждать груз

                AND A
                JR Z, SelectDevice                                              ; переход, если выбрана первая категория повреждения, сместить индекс оборудования

                ADD A, #02
                ; адресация повреждаемого устройства в странице D0, нулевое поле не меняется
SelectDevice:   ADD A, #85
                LD L, A
                LD H, #D0
                INC (HL)
                DEC (HL)
                RET Z                                                           ; выход, если выбранное оборудование отсутствует

                SET DEVICE_SIGN_BIT, (HL)
                INC (HL)
                ADD A, #E7
QueueDamage:    LD (FlightMessage.DamagedItem), A
                CALL Game.Flight.DispatchDeviceAndAppendDigit.Entry
                LD HL, FlightEvents + 3 * FFlightEvent
                SET EVENT_WAIT_BIT, (HL)
                RET

                ; повреждение грузового слота, уменьшение количества и возврат места в трюме
DamageCargo:    LD HL, State.Cargo - 4
CargoOffset     EQU $ + 1                                                       ; операнд CALL прибавления индекса к адресу груза
                CALL Game.Trade.AddByteOffsetToHL.Entry
                LD A, (HL)
                AND A
                RET Z                                                           ; выход, если в выбранном грузовом слоте нет товара

                DEC (HL)
                LD HL, State.FreeCargo
                INC (HL)
                LD A, #CC
                ADD A, E
                JR QueueDamage
                ; начальный шаблон пилота, Name, +00..0A, имя с нулём, ввод изменяет первые восемь байтов
NewCommander:   DB #4A, #41, #4D, #45, #53, #4F, #4E, #20                       ; #D232..#D239
                DB #20, #20, #00                                                ; #D23A..#D23C
                ; начальный шаблон пилота, LegalStatus, +0B, 0 законопослушный, 1..49 нарушитель, от 50 разыскивается
                DB #00                                                          ; #D23D..#D23D
                ; начальный шаблон пилота, Rating, +0C..0E, младшие 16 бит рейтинга и байт D062 с военным кодом
                DB #00, #00, #00                                                ; #D23E..#D240
                ; начальный шаблон пилота, JumpCount, +0F..10, счётчик переходов, увеличивается при прибытии
                DB #00, #00                                                     ; #D241..#D242
                ; начальный шаблон пилота, Galaxy, +11, индекс галактики 0..7
                DB #00                                                          ; #D243..#D243
                ; начальный шаблон пилота, CashHigh, +12..13, целые тысячи кредитов
                DB #00, #00                                                     ; #D244..#D245
                ; начальный шаблон пилота, CashLow, +14..15, остаток в десятых кредита, штатно меньше 10000
                DB #E8, #03                                                     ; #D246..#D247
                ; начальный шаблон пилота, MarketRandom, +16, случайный параметр воспроизводимого рынка
                DB #00                                                          ; #D248..#D248
                ; начальный шаблон пилота, Cargo, +17..27, количества товаров по индексам 0..16
                DB #00, #00, #00, #00, #00, #00, #00, #00                       ; #D249..#D250
                DB #00, #00, #00, #00, #00, #00, #00, #00                       ; #D251..#D258
                DB #00                                                          ; #D259..#D259
                ; начальный шаблон пилота, FreeCargo, +28, оставшееся место в трюме в тоннах
                DB #14                                                          ; #D25A..#D25A
                ; начальный шаблон пилота, FrontLaser, +29, тип переднего лазера
                DB #01                                                          ; #D25B..#D25B
                ; начальный шаблон пилота, RearLaser, +2A, тип заднего лазера
                DB #00                                                          ; #D25C..#D25C
                ; начальный шаблон пилота, LeftLaser, +2B, тип левого лазера
                DB #00                                                          ; #D25D..#D25D
                ; начальный шаблон пилота, RightLaser, +2C, тип правого лазера
                DB #00                                                          ; #D25E..#D25E
                ; начальный шаблон пилота, Mission1, +2D, активность первой миссии, изменяется #DE6F
                DB #00                                                          ; #D25F..#D25F
                ; начальный шаблон пилота, Fuel, +2E, топливо в десятых светового года, максимум 70
                DB #46                                                          ; #D260..#D260
                ; начальный шаблон пилота, Missiles, +2F, число ракет, покупка ограничена четырьмя
                DB #03                                                          ; #D261..#D261
                ; начальный шаблон пилота, LargeCargo, +30, расширенный трюм, используется #EA4C и #F0D8
                DB #00                                                          ; #D262..#D262
                ; начальный шаблон пилота, ECM, +31, установленная ECM, бит 7 также участвует в повреждении
                DB #00                                                          ; #D263..#D263
                ; начальный шаблон пилота, AlienComputer, +32, ALIEN COMPUTER, bit0 установлен, остальные биты счётчик событий
                DB #00                                                          ; #D264..#D264
                ; начальный шаблон пилота, MineralLife, +33, MINERAL LIFE, 0 до колонизации, bit7 запрещает живую колонию
                DB #00                                                          ; #D265..#D265
                ; начальный шаблон пилота, FuelScoops, +34, топливный ковш, #DB6C разрешает пополнение топлива
                DB #00                                                          ; #D266..#D266
                ; начальный шаблон пилота, EscapePod, +35, спасательная капсула
                DB #00                                                          ; #D267..#D267
                ; начальный шаблон пилота, EnergyBomb, +36, энергетическая бомба
                DB #00                                                          ; #D268..#D268
                ; начальный шаблон пилота, EnergyUnit, +37, энергетический блок
                DB #00                                                          ; #D269..#D269
                ; начальный шаблон пилота, DockComputer, +38, стыковочный компьютер
                DB #00                                                          ; #D26A..#D26A
                ; начальный шаблон пилота, GalacticDrive, +39, галактический гиперпривод, проверяется #DBC0
                DB #00                                                          ; #D26B..#D26B
                ; начальный шаблон пилота, ShipUpgrade, +3A, Cobra Mk4, #FD после покупки, влияет на уровни оборудования
                DB #00                                                          ; #D26C..#D26C
                ; начальный шаблон пилота, Invasion, +3B, фаза и размер вторжения, #81..FF наступление, #7F..01 отступление
                DB #00                                                          ; #D26D..#D26D
                ; начальный шаблон пилота, GalaxySeed, +3C..41, три слова исходного семени галактики
                DB #4A, #5A, #48, #02, #53, #B7                                 ; #D26E..#D273
                ; начальный шаблон пилота, SystemSeed, +42..47, семя текущей системы, Y по +43, X по +45
                DB #38, #AD, #9C, #14, #1D, #15                                 ; #D274..#D279
                ; начальный шаблон пилота, Technology, +48, технологический уровень текущей системы, счёт с нуля
                DB #05                                                          ; #D27A..#D27A
                ; начальный шаблон пилота, Government, +49, правительство текущей системы, 0..7
                DB #03                                                          ; #D27B..#D27B
                ; начальный шаблон пилота, MarketStock, +4A..5A, остатки товаров станции, последний слот обычно нулевой
                DB #11, #12, #1A, #0E, #27, #08, #00, #00                       ; #D27C..#D283
                DB #0A, #19, #00, #00, #3D, #0E, #11, #0C                       ; #D284..#D28B
                DB #00                                                          ; #D28C..#D28C
                ; начальный шаблон пилота, Mission3, +5B, состояние третьей миссии, переходы проверены в #D123/#DDF7
                DB #00                                                          ; #D28D..#D28D
                ; начальный шаблон пилота, MissionFlags, +5C, флаги наград, особого оборудования и занятого миссией трюма
                DB #00                                                          ; #D28E..#D28E
                ; начальный шаблон пилота, SunPosition, +5D..65, три трёхбайтовые координаты светила, копируются в #7107
                DB #27, #08, #01, #2A, #4D, #8F, #F2, #88                       ; #D28F..#D296
                DB #05                                                          ; #D297..#D297
                ; копирование исходного командира из шаблона D232 и восстановление производных данных
; -----------------------------------------
; восстановление исходного командира и производного состояния, #D298
; In:
;   NewCommander, неизменённый шаблон из 102 байтов
; Out:
;   первые 93 байта шаблона скопированы в State.Name
;   координаты солнца перенесены отдельно в полётный блок #7107
;   система и рынок пересозданы, имена текущей и выбранной систем согласованы, отсчёт перехода=0
; Corrupt:
;   HL, DE, BC, AF, HL', DE', BC'
; Note:
;   данные рынка пересчитываются GenerateMarket, поэтому результат не является простым LDIR всех 102 байтов
;   код записи количества товара по #E1B0 временно заменяется NOP и восстанавливается байтом #77
;   адреса исходного размещения сохранены
; -----------------------------------------
ResetCommander: CALL Game.Travel.ClearFlightEventsAndHandleJump.Entry
                LD HL, NewCommander
                LD DE, State.Name
                LD BC, #005D
                ; перенос имени, статуса, оборудования, семян и сохранённого рынка в блок командира
                LDIR
                LD A, (State.SystemSeed + FSystemSeed.X)
                LD (TargetX), A
                LD A, (State.SystemSeed + FSystemSeed.Y)
                LD (TargetY), A
                CALL Game.Galaxy.FindNearestSystem.Entry
                LD HL, MarketStore
                LD (HL), #00
                PUSH HL
                CALL Game.Trade.GenerateMarket.Entry
                POP HL
                LD (HL), #77
                LD HL, GalaxyState.TargetName
                LD DE, GalaxyState.CurrentName
                LD BC, #0008
                ; копирование восьми символов выбранной системы в имя текущей системы
                LDIR
                LD HL, NewCommander + FCommander.SunPosition
                LD DE, FlightState.Sun
                LD BC, #0009
                ; восстановление трёх трёхбайтовых координат солнца из шаблона
                LDIR
                XOR A
                LD (JumpCountdown), A
                RET
                ; остаток десятичного числа после очередного разряда
DecimalRest     DW #0000                                                        ; остаток десятичного преобразования числа
                ; проверка исходного конца фрагмента
                ASSERT $ == #D2DE
                endmodule
                endmodule
