                module DoubleSignedAngle
; -----------------------------------------
; подготовка удвоенного коэффициента поворота перестановкой битов
; исходный диапазон #A281..#A28C
; In:
;   AF, A содержит угол, входной перенос входит в результат
; Out:
;   BC, C=(A вх AND #80) OR ((A вх AND #3F)*2) OR переносвх
;   AF, A=(A вх AND #FE) OR ((A вх SHR 6) AND 1)
; Corrupt:
;   нет дополнительных регистров
; Note:
; Входной перенос значим, цепочку нельзя заменить простым удвоением A.
; после RET сохранены два нулевых байта, отдельные данные исходного образа
; -----------------------------------------
                ; проверка исходного начала фрагмента
                ASSERT $ == #A281
                ; расчёт удвоенного шестибитного модуля с сохранением знака
Entry:          LD C, A
                RL C
                RRA
                RL C
                RLA
                RR C
                RET

                ; данные между процедурами, два исходных нулевых байта
                DB #00, #00
                ; проверка исходного конца фрагмента
                ASSERT $ == #A28D
                endmodule
                endmodule
