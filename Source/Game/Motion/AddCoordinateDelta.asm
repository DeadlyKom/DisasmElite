                module AddCoordinateDelta
; -----------------------------------------
; сложение координаты и смещения со знаком и отдельным модулем
; исходный диапазон #A098..#A0AA
; In:
;   HL, модуль координаты
;   DE, смещение, D содержит знак, E модуль
;   AF, A содержит знак координаты
; Out:
;   HL, модуль новой координаты
;   BC, B содержит её знак
; Corrupt:
;   DE, AF
; Note:
; При одинаковых знаках модули складываются, при разных вычитаются.
; Если смещение больше координаты, знак результата меняется.
; -----------------------------------------
                ; проверка исходного начала фрагмента
                ASSERT $ == #A098
                ; проверка знаков перед выбором сложения или вычитания
Entry:          LD B, A
                LD C, D
                XOR C
                RES 7, D
                JR NZ, SubtractDelta                                            ; переход, если знаки координаты и смещения различаются

                ADD HL, DE
                RET

                ; расчёт разности модулей и выбор результирующего знака
SubtractDelta:  SBC HL, DE
                RET NC                                                          ; выход, если модуль координаты не меньше смещения и исходный знак сохраняется

                ADD HL, DE
                EX DE, HL
                AND A
                SBC HL, DE
                LD B, C
                RET

                ; проверка исходного конца фрагмента
                ASSERT $ == #A0AB
                endmodule
                endmodule
