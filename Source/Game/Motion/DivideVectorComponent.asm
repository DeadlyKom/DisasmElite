                module DivideVectorComponent
; -----------------------------------------
; деление одной компоненты на длину вектора
; исходный диапазон #9ECF..#9EF0
; In:
;   DE, ненулевой делитель
;   AF, A равен нулю
;   IX, адрес знако-модульного слова
; Out:
;   HL, исходная компонента
;   DE, исходный делитель
;   BC, записанная нормализованная компонента
;   AF, A равен нулю
;   IX, адрес следующего слова
; Corrupt:
;   нет дополнительных регистров
; Note:
; Divide получает модуль компоненты, частное затем делится пополам.
; Знак исходного слова возвращается в бит 15 результата.
; -----------------------------------------
                ; проверка исходного начала фрагмента
                ASSERT $ == #9ECF
                ; деление модуля с отдельным сохранением исходного знака
Entry:          LD H, (IX + FSignWord.SignHigh)
                LD L, (IX + FSignWord.Low)
                PUSH HL
                RES 7, H
                CALL Game.Math.Divide
                ; расчёт масштаба частного и восстановление знака
                SRL B
                RR C
                POP HL
                BIT 7, H
                JR Z, StoreQuotient                                             ; переход, если исходная компонента неотрицательна и знак менять не нужно

                SET 7, B
StoreQuotient:  LD (IX + FSignWord.Low), C
                LD (IX + FSignWord.SignHigh), B
                INC IX
                INC IX
                RET

                ; проверка исходного конца фрагмента
                ASSERT $ == #9EF1
                endmodule
                endmodule
