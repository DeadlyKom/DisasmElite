                module VelocityComponentDelta
; -----------------------------------------
; расчёт смещения из скорости и компоненты направления
; исходный диапазон #A076..#A097
; In:
;   DE, знако-модульная компонента направления
;   BC, C содержит скорость, используются шесть бит
; Out:
;   DE, смещение, D содержит знак, E модуль
; Corrupt:
;   HL, BC, AF
; Note:
; Шесть итераций делят направление пополам и суммируют части, выбранные битами скорости.
; Добавление #00FF округляет смещение вверх перед выбором старшего байта.
; Знак временно переносится через C и возвращается в бит 7 D.
; -----------------------------------------
                ; проверка исходного начала фрагмента
                ASSERT $ == #A076
                ; подготовка разрядов скорости и сохранение знака
Entry:          SLA D
                RL C
                RL C
                SRL D
                LD HL, #0000
                LD B, #06
                ; расчёт суммы частичных произведений
MultiplyBit:    SRL D
                RR E
                SLA C
                JR NC, NextSpeedBit                                             ; переход, если очередной бит скорости равен нулю и частичное произведение не добавляется

                ADD HL, DE
NextSpeedBit:   DJNZ MultiplyBit

                LD DE, #00FF
                ADD HL, DE
                LD E, H
                SLA C
                RR D
                RET
                ; проверка исходного конца фрагмента
                ASSERT $ == #A098
                endmodule
                endmodule
