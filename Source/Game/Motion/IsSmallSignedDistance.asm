                module IsSmallSignedDistance
; -----------------------------------------
; проверка малого модуля знако-модульного расстояния
; исходный диапазон #A537..#A53E
; In:
;   HL, знако-модульное расстояние
; Out:
;   HL, исходное слово сдвинуто влево
;   AF, Z при модуле меньше 32, NZ иначе
; Corrupt:
;   нет дополнительных регистров
; Note:
; Удвоение выталкивает знак из бита 15, затем проверяются оставшиеся старшие разряды.
; Физический порог зависит от масштаба вызывающей процедуры.
; -----------------------------------------
                ; проверка исходного начала фрагмента
                ASSERT $ == #A537
                ; проверка модуля расстояния без знакового бита
Entry:          ADD HL, HL
                LD A, H
                AND A
                RET NZ                                                          ; выход, если модуль расстояния не помещается в нижние семь бит

                LD A, L
                AND #C0
                RET
                ; проверка исходного конца фрагмента
                ASSERT $ == #A53F
                endmodule
                endmodule
