                module Economy
                module PrintBytePrice
; -----------------------------------------
; Печать байта с десятичной точкой перед последней цифрой
; исходный диапазон #D2DE..#D2E0
; In:
;   AF, A = значение в десятых
; Out:
;   Значение напечатано через общий числовой механизм
; Corrupt:
;   HL, DE, BC, AF
; Note:
;   SCF выбирает денежный формат, переход D2E2 расширяет A до HL
; -----------------------------------------
                ; проверка исходного начала фрагмента
                ASSERT $ == #D2DE
                ; дробный формат, перенос передаёт общему принтеру наличие десятичной точки
Entry:          SCF
                JR @Game.Economy.PrintByteInteger.ExtendByte
                ; проверка исходного конца фрагмента
                ASSERT $ == #D2E1
                endmodule
                endmodule
