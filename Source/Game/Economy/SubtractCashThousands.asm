                module Economy
                module SubtractCashThousands
; -----------------------------------------
; Списание целых тысяч кредитов
; исходный диапазон #D3EF..#D3FC
; In:
;   DE = число тысяч, AF, CY = входной заём
; Out:
;   CY=0 при успехе, CY=1 при недостатке денег
; Corrupt:
;   HL, AF
; Note:
;   SBC использует входной CY, при недостатке D066 не изменяется, успешный путь сбрасывает CY
; -----------------------------------------
                ; проверка исходного начала фрагмента
                ASSERT $ == #D3EF
                ; списание старшей группы с учётом входного переноса и признаком нехватки
Entry:          LD HL, (State.CashHigh)
                SBC HL, DE
                JR C, NoFunds                                                   ; переход, если списание старшей группы дало заём, вернуть признак нехватки денег

                LD (State.CashHigh), HL
                AND A
                RET

NoFunds:        SCF
                RET
                ; проверка исходного конца фрагмента
                ASSERT $ == #D3FD
                endmodule
                endmodule
