                module Economy
                module SubtractCashLow
; -----------------------------------------
; Списание суммы в десятых кредита
; исходный диапазон #D3FD..#D420
; In:
;   DE = сумма меньше 10000
; Out:
;   CY=0 при успехе, CY=1 при недостатке денег
; Corrupt:
;   HL, DE, AF
; Note:
;   При заёме из младшей группы берёт одну тысячу из D066 и прибавляет 10000, при нулевой
;   старшей группе возвращается без записи, D420 после RET является режимом текстового декодера
; -----------------------------------------
                ; проверка исходного начала фрагмента
                ASSERT $ == #D3FD
                ; списание младшей группы, при заёме берётся одна единица старшей группы
Entry:          LD HL, (State.CashLow)
                AND A
                SBC HL, DE
                JR NC, StoreBalance                                             ; переход, если младшей группы достаточно для списания, сохранить её остаток

                LD HL, (State.CashHigh)
                LD A, L
                OR H
                SCF
                RET Z                                                           ; выход, если старшая группа денег нулевая, заём для списания невозможен

                DEC HL
                LD (State.CashHigh), HL
                LD HL, #2710
                AND A
                SBC HL, DE
                LD DE, (State.CashLow)
                ADD HL, DE
StoreBalance:   LD (State.CashLow), HL
                AND A
                RET
                ; режим второй таблицы сообщений, 0 основной, 1 специальный
TextDecodeMode  DB #01                                                          ; режим декодирования текста, 0 основная таблица, 1 описания
                ; проверка исходного конца фрагмента
                ASSERT $ == #D421
                endmodule
                endmodule
