                module CompareWordPreserveHL
; -----------------------------------------
; Вычитательное сравнение с сохранением HL
; исходный диапазон #D3CE..#D3D2
; In:
;   HL, DE = сравниваемые слова, AF, CY = входной заём
; Out:
;   Флаги от HL-DE-CY, HL сохранён
; Corrupt:
;   AF
; Note:
;   Вызывающий обязан предварительно сбросить CY для обычного сравнения
; -----------------------------------------
                ; проверка исходного начала фрагмента
                ASSERT $ == #D3CE
                ; сравнение через SBC использует входной перенос, исходное HL восстанавливается
Entry:          PUSH HL
                SBC HL, DE
                POP HL
                RET

                ; проверка исходного конца фрагмента
                ASSERT $ == #D3D3
                endmodule
                endmodule
