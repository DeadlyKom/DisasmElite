                module Sound
                module StartHyperjumpNoise
; -----------------------------------------
; подготовка шумовых параметров гиперперехода
; исходный диапазон #96B7..#96C4
; In:
;   нет
; Out:
;   BC=#C010, DE=#100A переданы общему входу #96AF
; Corrupt:
;   HL, DE, BC, AF
; Note:
;   после JR управление не возвращается в этот фрагмент
;   #96BF хранит номер текущего звукового запроса
;   #96C0..#96C4 уже относятся к состоянию сканера, а не к коду проигрывателя
; -----------------------------------------
                ; проверка исходного начала фрагмента
                ASSERT $ == #96B7
Entry:          LD BC, #C010
                LD DE, #100A
                JR @Game.Sound.StartLaunchNoise.DisableIrq
RequestIndex    DB #00                                                          ; номер выбранного звукового запроса, 0..7
ScaledX         DB #00                                                          ; масштабированная координата X объекта для сканера
ScaledY         DB #00                                                          ; масштабированная высота Y объекта для сканера
ScaledZ         DB #00                                                          ; масштабированная глубина Z объекта для сканера
ObjectIndex     DB #00                                                          ; номер обрабатываемого слота сканера
Redraw          DB #00                                                          ; флаг, фон сканера требуется восстановить
                ; проверка исходного конца фрагмента
                ASSERT $ == #96C5
                endmodule
                endmodule
