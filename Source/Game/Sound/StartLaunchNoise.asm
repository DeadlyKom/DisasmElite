                module Sound
                module StartLaunchNoise
; -----------------------------------------
; инициализация шума старта и общий параметризованный вход
; исходный диапазон #969B..#96B6
; In:
;   для входа #969B регистровых параметров нет
;   для входа #96AF BC и DE уже содержат параметры эффекта
; Out:
;   передача управления первому пакету шумового проигрывателя
; Corrupt:
;   HL, DE, BC, AF
; Note:
;   вход #969B задаёт BC=#5002, DE=#4020 и запрещает прерывания
;   общий #9684 записывает C в шаг периода #95BD, B в длину пакета #95AE
;   байты #96A9..#96AE задают отдельный вход с BC=#C0F0, DE=#C00C
;   вход #96AF использует переданные BC/DE и также устанавливает режим 3
; -----------------------------------------
                ; проверка исходного начала фрагмента
                ASSERT $ == #969B
Entry:          LD A, #03
                LD (SoundState.Mode), A
                DI
                LD BC, #5002
                LD DE, #4020                                                    ; D=64 задержка шумового пакета, E=32 число пакетов
                JR @Game.Sound.StepPitchSweep.SetNoisePatch

; -----------------------------------------
; настройка длинного шума перехода
; In:
;   не требуются
; Out:
;   BC=#C0F0, DE=#C00C, далее общий вход #96AF
; Corrupt:
;   HL, DE, BC, AF
; Note:
;   #9538 вызывает этот вход перед синхронным ожиданием
;   C=#F0 уменьшает задержку на 16, B=#C0 задаёт 192 отсчёта
;   D=#C0 задаёт начальную задержку, E=12 число пакетов
;   #96AF запрещает прерывания, устанавливает режим 3 и переходит в #9684
; -----------------------------------------
HyperParams:    ; настройка длинного шума перехода
                LD BC, #C0F0
                LD DE, #C00C                                                    ; D=192 задержка шумового пакета, E=12 число пакетов
DisableIrq:     DI
                LD A, #03
                LD (SoundState.Mode), A
                JR @Game.Sound.StepPitchSweep.SetNoisePatch
                ; проверка исходного конца фрагмента
                ASSERT $ == #96B7
                endmodule
                endmodule
