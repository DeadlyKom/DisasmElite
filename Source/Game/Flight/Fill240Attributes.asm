                module Fill240Attributes
; -----------------------------------------
; Заливка 240 атрибутов белыми чернилами
; исходный диапазон #7467..#7470
; In:
;   HL адрес начала
; Out:
;   240 байтов 07, HL увеличен на 240,B=0
; Corrupt:
;   HL, BC, AF
; Note:
;   DemoModel отдельный индекс модели демонстрационного экрана
; -----------------------------------------
                ASSERT $ == #7467
                ; заливка 240 байтов значением 07, HL указывает продолжение
Entry:          LD B, #F0
                LD A, #07
FillAttribute:  LD (HL), A
                INC HL
                DJNZ FillAttribute

                RET

                ; счётчик демонстрационных моделей, используется младшая тетрада с пропуском 12..15
DemoModel       DB #00                                                          ; номер демонстрационной модели, младшая тетрада с пропуском 12..15
                ASSERT $ == #7471
                endmodule
                endmodule
