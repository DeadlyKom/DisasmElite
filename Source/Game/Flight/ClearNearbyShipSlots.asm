                module ClearNearbyShipSlots
; -----------------------------------------
; Удаление семи соседних объектов
; исходный диапазон #9509..#9526
; In:
;   объекты по 6048 с шагом 39
; Out:
;   станции снимается bit2 поля 21, семь последующих полей 22 обнуляются,9C99=0
; Corrupt:
;   DE, BC, AF, IX
; Note:
;   Станция в первом слоте 6048 остаётся, IX после семи шагов равен 6159
;   9522..9526 являются активным состоянием звука, режим, DE и указатель данных HL
; -----------------------------------------
                ASSERT $ == #9509
                ; снятие враждебности станции и признака атаки
Entry:          LD IX, Memory.Station
                RES OBJ_HOSTILE_BIT, (IX+FSpaceObject.Hostility)
                XOR A
                LD (CombatState.Danger), A
                LD DE, FSpaceObject
                LD B, #07
ClearShip:      ADD IX, DE
                LD (IX+FSpaceObject.Energy), A
                DJNZ ClearShip

                RET
                ; активный режим звука,0 нет,1 меняющийся тон,2 данные периода,3 шум
Mode            DB #00                                                          ; 0 тишина, 1 скользящий тон, 2 тон из данных, остальные значения шум
                ; состояние DE проигрывателя, счётчик пакетов и задержка зависят от режима
Duration        DW #0000                                                        ; сохранённые DE, назначение D/E зависит от звукового режима
                ; адрес следующего звукового отсчёта или периода
DataCursor      DW #0000                                                        ; сохранённый HL, адрес следующего отсчёта либо параметр тона
                ASSERT $ == #9527
                endmodule
                endmodule
