                module Flight
                module DispatchChartCircle
; -----------------------------------------
; Вектор рисования окружности карты
; исходный диапазон #7119..#7120
; In:
;   MapCircleX=X, MapCircleY=Y, MapRadius=радиус окружности карты
; Out:
;   окружность нарисована, временные параметры экрана восстановлены
; Corrupt:
;   HL, DE, BC, AF, HL', DE', BC', AF'
; Note:
;   Game.Circles.DrawChartCircleWithPatchedViewport.Entry временно заменяет геометрию области обзора и рисует окружность, направление JP не вращает
;   координаты объектов
;   StationZone, StationFar, SunScooping, PlayerDead и XorObjects после JP являются отдельными полями FlightState
; -----------------------------------------
                ASSERT $ == #7119
                ; передача окружности карты в рисователь с временной геометрией экрана
Entry:          JP Game.Circles.DrawChartCircleWithPatchedViewport.Entry

                ; зона ближнего станционного компаса, разрешает компьютер стыковки
StationZone     DB #00                                                          ; ближняя станционная зона, разрешает стыковку и запрещает появление кораблей
                ; режим координат станции, FF требует нормирования старших слов
StationFar      DB #00                                                          ; #FF для дальних координат станции, 0 для ближних
                ; сохранённый признак зоны черпаков, сбрасывается при входе в систему и на заставке
SunScooping     DB #00                                                          ; признак зоны черпаков, сбрасывается при входе в систему и на заставке
                ; признак гибели игрока, читается главным циклом
PlayerDead      DB #00                                                          ; флаг, главный цикл должен показать гибель игрока
                ; режим наложения объектов OR/XOR при большом солнечном диске
XorObjects      DB #00                                                          ; нуль выбирает OR, ненулевое значение выбирает XOR при выводе объектов
                ASSERT $ == #7121
                endmodule
                endmodule
