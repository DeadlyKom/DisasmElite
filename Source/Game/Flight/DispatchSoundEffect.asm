                module Flight
                module DispatchSoundEffect
; -----------------------------------------
; Вектор звукового эффекта
; исходный диапазон #7125..#7129
; In:
;   InputState.Config bit7 разрешение звука, FlightState.SoundRequests маска запросов, SoundState режим эффекта
; Out:
;   продолжен активный эффект либо выбран младший установленный запрос
; Corrupt:
;   HL, DE, BC, AF
; Note:
;   FlightState.SoundRequests/FlightState.AutoDock являются отдельными рабочими байтами,FlightState.AutoDock помечает автоматическую стыковку
;   FlightState.SoundRequests заполняется битами запросов выстрела, взрыва, ракеты и попадания, диспетчер Game.Sound.UpdateSound.Entry вызывается
;   из прерывания
; -----------------------------------------
                ASSERT $ == #7125
                ; передача запросов диспетчеру звуковых эффектов
Entry:          JP Game.Sound.UpdateSound.Entry

; -----------------------------------------
;      7    6    5    4    3    2    1    0
;   +----+----+----+----+----+----+----+----+
;   | AT | HT | EC | FT | LS | EX | MS | EB |
;   +----+----+----+----+----+----+----+----+
;
;   Requests, очередь звуковых эффектов:
;   EB      [0]     - флаг, звук энергетической бомбы, SlowNoise
;   MS      [1]     - флаг, звук запуска ракеты, FastNoise
;   EX      [2]     - флаг, взрыв либо столкновение, ChainedNoise
;   LS      [3]     - флаг, попадание лазера по объекту, ShiftedTone
;   FT      [4]     - флаг, запрос FallingTone, игровой установщик не найден
;   EC      [5]     - флаг, работа ECM, LongTone
;   HT      [6]     - флаг, выстрел или полученный удар, AddedTone
;   AT      [7]     - флаг, второй запрос AddedTone, игровой установщик не найден
;
;   UpdateSound выбирает младший установленный бит только при завершённом эффекте
;   StepDataTone.FinishEffect сбрасывает бит выбранного запроса после воспроизведения
;   разные причины одного эффекта объединяются в один бит, отдельного счётчика нет
; -----------------------------------------
                ; маска восьми запросов звуковых эффектов
Requests        DB #00                                                          ; маска ожидающих звуковых запросов, бит 0 имеет наивысший приоритет
                ; признак включённой автоматической стыковки
AutoDock        DB #00                                                          ; флаг, ненулевое значение включает автоматическую стыковку
                ASSERT $ == #712A
                endmodule
                endmodule
