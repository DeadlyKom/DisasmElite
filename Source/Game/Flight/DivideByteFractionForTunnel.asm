                module Flight
                module DivideByteFractionForTunnel
; -----------------------------------------
; Восемь разрядов частного для радиуса тоннеля
; исходный диапазон #93AC..#93EC
; In:
;   BC, B делитель, AF, A начальный остаток, штатно 0<=A<B
; Out:
;   BC, C=floor(A_in*256/B), AF, A остаток, C-флаг 0
; Corrupt:
;   BC только C, AF
; Note:
;   Маркер FE заканчивает восемь итераций, переполнение удвоения обрабатывается до сравнения
;   Проверки B=0 нет, при нулевом делителе получается C=FF
;   93C0 отдельный завершающий обработчик тоннеля,93D0..93EC таблицы и счётчики колец
; -----------------------------------------
                ASSERT $ == #93AC
                ; дробное деление, C=FE содержит частное и маркер восьми разрядов
Entry:          LD C, #FE
                ; удвоение остатка перед очередным битом частного
QuotientBit:    ADD A, A
                JR C, SubDivisor                                                ; переход, если удвоение остатка дало девятый бит, вычесть делитель

                CP B
                JR NC, SubDivisor                                               ; переход, если удвоенный остаток не меньше делителя, записать единичный бит частного

                ; нулевой бит частного, выход определяется маркером
                SLA C
                RET NC                                                          ; выход, если маркер восьми разрядов вышел из C, частное готово

                JR QuotientBit

                ; вычитание делителя и единичный бит частного
SubDivisor:     SUB B
                SCF
                RL C
                RET NC                                                          ; выход, если маркер восьми разрядов вышел из C, частное готово

                JR QuotientBit

                ; завершение гипертуннеля, обычный цвет возвращается вне первой миссии
FinishTunnel:   LD A, (State.Mission1)
                AND A
                LD L, #07
                CALL Z, Game.Extensions.AttributeVectorAndEnergyBomb.Entry      ; вызов процедуры, если первая миссия не активна, восстановить обычные атрибуты окна
                XOR A
                LD (Game.Flight.MainGameLoop.NovaRadius), A
                JP Game.Sound.PlayLaunchSound.HyperSound
                ; число колец активного туннеля,8 для стыковки,16 для гиперперехода
RingCount       DB #08                                                          ; число колец туннеля, 8 либо 16
                ; число ещё не обработанных колец текущего кадра
RingsLeft       DB #00                                                          ; число ещё не обработанных колец кадра
                ; оставшееся время текущего этапа анимации туннеля
PhaseFrames     DB #00                                                          ; число кадров до смены фазы туннеля
                ; шестнадцать глубин гипертуннеля, каждое кольцо приближается на единицу за кадр
HyperDepths     DB #1E, #21, #23, #26, #28, #2B, #2D, #30                       ; шестнадцать глубин колец гиперперехода
                DB #32, #35, #37, #3A, #3C, #3F, #41, #44                       ; #93DB..#93E2
                ; восемь глубин стыковочного и стартового туннеля
DockDepths      DB #10, #10, #10, #18, #20, #28, #30, #38                       ; восемь глубин колец стыковки и старта
                ; два сохранённых нулевых байта после таблицы колец
                DB #00, #00                                                     ; #93EB..#93EC
                ASSERT $ == #93ED
                endmodule
                endmodule
