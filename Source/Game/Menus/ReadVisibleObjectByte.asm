                module Menus
                module ReadVisibleObjectByte
; -----------------------------------------
; Чтение поля объекта с отсечением адреса записи
; исходный диапазон #ED69..#ED77
; In:
;   IX = объект
; Out:
;   AF, A содержит FSpaceObject.Energy, при возврате CY=1 и старший байт IX равен #60 либо #61
; Corrupt:
;   AF
; Note:
;   для страниц 60/61 возвращается, для других страниц остаётся в цикле InvalidObject, три байта после цикла
;   отдельные данные, MapNameLength хранит длину имени
; -----------------------------------------
                ; проверка исходного начала фрагмента
                ASSERT $ == #ED69
                ; тип записи по старшему байту IX определяет доступность её видимого параметра
Entry:          LD A, IXH
                SUB #60
                CP #02
                LD A, (IX+FSpaceObject.Energy)
                RET C                                                           ; выход, если IX расположен в страницах 60 или 61, вернуть поле объекта непосредственно

InvalidObject:  JR InvalidObject

                ; сохранённые нулевые байты после бесконечной защитной петли Game.Menus.ReadVisibleObjectByte.InvalidObject
                DB #00, #00                                                     ; #ED75..#ED76
                ; длина имени планеты при размещении подписи на карте
NameLength      DB #06                                                          ; длина имени системы при размещении подписи на карте
                ; проверка исходного конца фрагмента
                ASSERT $ == #ED78
                endmodule
                endmodule
