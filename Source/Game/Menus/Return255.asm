                module Return255
; -----------------------------------------
; Значение 255 для насыщения координаты
; исходный диапазон #EC3D..#EC3F
; In:
;   Нет параметров
; Out:
;   A=255, флаги сохранены
; Corrupt:
;   AF, только A
; Note:
;   Используется условным CALL при переполнении верхней границы карты
; -----------------------------------------
                ; проверка исходного начала фрагмента
                ASSERT $ == #EC3D
                ; насыщение переполненной координаты до 255 для вычисления границы карты
Entry:          LD A, #FF
                RET

                ; проверка исходного конца фрагмента
                ASSERT $ == #EC40
                endmodule
                endmodule
