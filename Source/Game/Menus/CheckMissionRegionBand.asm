                module Menus
                module CheckMissionRegionBand
; -----------------------------------------
; Проверка полосы между двумя специальными границами
; исходный диапазон #EC40..#EC4A
; In:
;   Координаты и состояние миссии по контракту D67A
; Out:
;   CY отражает попадание между двумя проверками
; Corrupt:
;   HL, DE, BC, AF
; Note:
;   Первый встроенный параметр равен коду INC A=3C, второй равен NOP=0, первый успешный внешний
;   выход возвращается сразу, второй результат инвертируется CCF
; -----------------------------------------
                ; проверка исходного начала фрагмента
                ASSERT $ == #EC40
                ; миссия 7 INVASION, проверка полосы сопротивления между границами фронта
                ; описание в Docs/Manual.md, раздел mission-7-invasion
                ; две проверки с разными встроенными порогами выделяют полосу сопротивления
Entry:          CALL Game.Text.CheckMissionRegion.Entry
                INC A
                RET NC                                                          ; выход, если первая граница не охватывает систему, она вне полосы сопротивления

                CALL Game.Text.CheckMissionRegion.Entry
                NOP
                CCF
                RET
                ; проверка исходного конца фрагмента
                ASSERT $ == #EC4B
                endmodule
                endmodule
