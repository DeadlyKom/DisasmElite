                module Menus
                module ChooseEncounterVariant
; -----------------------------------------
; Случайная замена типа объекта для группы 13..17
; исходный диапазон #EF01..#EF20
; In:
;   Результат Game.Screen.SelectTrafficType.Entry содержит B = исходный тип
; Out:
;   HL=Memory.ModelIndex, B может стать 19..22
; Corrupt:
;   HL, DE, BC, AF
; Note:
;   Только типы 13..17 и случайное A<80 допускают замену, тип 15 получает 19, меньшие 20,
;   большие 21 либо 22 в зависимости от младшего бита исходного типа
; -----------------------------------------
                ; проверка исходного начала фрагмента
                ASSERT $ == #EF01
                ; редкая случайная замена применяется только к группе типов 13..17
Entry:          CALL Game.Screen.SelectTrafficType.Entry
                LD HL, Memory.ModelIndex
                LD A, B
                CP #0D
                RET C                                                           ; выход, если тип объекта меньше 13, случайная замена для него не предусмотрена

                CP #12
                RET NC                                                          ; выход, если тип объекта не меньше 18, случайная замена для него не предусмотрена

                CALL Game.Combat.NextRandomByte.Entry
                CP #50
                RET NC                                                          ; выход, если случайный байт не меньше 80, оставить первоначальный тип объекта

                LD A, B
                CP #0F
                LD B, #13
                RET Z                                                           ; выход, если первоначальный тип равен 15, выбрать замену с кодом 19

                INC B
                RET C                                                           ; выход, если первоначальный тип меньше 15, выбрать замену с кодом 20

                INC B
                RRCA
                RET NC                                                          ; выход, если младший бит первоначального типа нулевой, выбрать замену с кодом 21

                INC B
                RET

                ; проверка исходного конца фрагмента
                ASSERT $ == #EF21
                endmodule
                endmodule
