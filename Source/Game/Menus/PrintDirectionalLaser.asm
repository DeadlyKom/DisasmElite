                module Menus
                module PrintDirectionalLaser
; -----------------------------------------
; Печать одного установленного лазера
; исходный диапазон #F07A..#F0A0
; In:
;   HL = слот лазера, BC, C = счётчик направлений 4..1
; Out:
;   Ненулевой тип напечатан после названия направления
; Corrupt:
;   HL, DE, BC, AF
; Note:
;   Направление определяется токеном 60+(4-C), типы 1..4 преобразуются в токены 67/68/75/76,
;   прочие в F6, следующая DeviceFields содержит младшие байты адресов обычных устройств
; -----------------------------------------
                ; проверка исходного начала фрагмента
                ASSERT $ == #F07A
                ; нулевой тип пропускается, остальные типы получают подпись направления и класса лазера
Entry:          LD A, (HL)
                AND A
                RET Z                                                           ; выход, если на данном направлении лазер не установлен

                PUSH AF
                LD A, #04
                SUB C
                ADD A, #60
                CALL Game.Trade.PrintMainTokenSpace.Entry
                POP AF
                CP #05
                JR NC, SpecialLaser                                             ; переход, если индекс типа лазера не меньше 5, использовать прямой код описания

                LD B, #72
                CP #03
                JR NC, LaserToken                                               ; переход, если индекс типа лазера равен 3 или 4, выбрать вторую группу названий

                LD B, #66
LaserToken:     ADD A, B
                JR PrintLaser

SpecialLaser:   LD A, #F6
PrintLaser:     JP Game.Menus.PrintEquipmentLine.Entry

                ; шесть младших байтов адресов оборудования в странице D0
DeviceFields    DB #85, #88, #8A, #8B, #8C, #8D                                 ; шесть младших адресных байтов полей оборудования командира
                ; проверка исходного конца фрагмента
                ASSERT $ == #F0A1
                endmodule
                endmodule
