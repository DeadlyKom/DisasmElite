                module ClearCharacterRowsBackward
; -----------------------------------------
; Очистка нескольких символьных строк перед данным адресом
; исходный диапазон #EBEE..#EC13
; In:
;   HL = адрес сразу после очищаемой области первой пиксельной строки, AF, A = число строк
; Out:
;   Пиксели выбранных строк равны 0
; Corrupt:
;   HL, DE, BC, AF
; Note:
;   Восемь проходов по подпиксельным строкам, каждый очищает A*32 байт движением назад, после
;   восстановления HL увеличивает H, EC02..EC13 содержат остаток отдельной процедуры со своим
;   восстановлением SP
; -----------------------------------------
                ; проверка исходного начала фрагмента
                ASSERT $ == #EBEE
                ; очистка идёт назад по символьным строкам и вперёд по восьми линиям растра
Entry:          LD E, #08
RasterLine:     PUSH HL
                LD D, A
CharacterRow:   LD BC, #2000
ClearByte:      DEC HL
                LD (HL), C
                DJNZ ClearByte

                DEC D
                JR NZ, CharacterRow                                             ; переход, если остались символьные строки текущей растровой линии, продолжить очистку

                POP HL
                INC H
                DEC E
                JR NZ, RasterLine                                               ; переход, если остались растровые линии символа, продолжить очистку

                RET
                ; остаток прежней стековой очистки после RET, переходы не образуют действующий вход
                DB #10, #FD, #3D, #20, #F8, #24, #0D, #20                       ; #EC02..#EC09
                DB #F0, #ED, #7B, #12, #EC, #FB, #C9, #00                       ; #EC0A..#EC11
                DB #00, #00                                                     ; #EC12..#EC13
                ; проверка исходного конца фрагмента
                ASSERT $ == #EC14
                endmodule
                endmodule
