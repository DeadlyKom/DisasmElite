                module Data
                module LaunchCounter
; -----------------------------------------
; флаг отложенного увеличения счётчика при вылете и само значение счётчика
; Game.Text.BeginSystemLaunchState.Entry устанавливает флаг #E0 во время перехода в новую систему
; вход Game.Input.ResetDemoAndNormalizeControls.Entry сбрасывает флаг при подготовке начального состояния
; завершение вылета Game.Extensions.FillBackwardAndCountDemo.CountDemo проверяет флаг, обнуляет его и при ненулевом
; прежнем значении увеличивает слово LaunchCount ровно на единицу
; эти байты не входят в 102-байтную область сохранения State
; следующие три байта используются проверкой дискового маркера в оверлее
; TimingFailures и MarkFailures считают неудачи, ProtectPassed хранит #FF либо 0
; -----------------------------------------
                ; проверка исходного начала фрагмента
                ASSERT $ == #E07A
Pending         DB #00                                                          ; флаг, при следующем вылете увеличить счётчик
Count           DW #0000                                                        ; число вылетов после отмеченного перехода в систему
TimingFailures  DB #00                                                          ; число отказов временной проверки маркера дорожки
MarkFailures    DB #00                                                          ; число отказов VerifyMark, порог отказа равен 8
ProtectPassed   DB #00                                                          ; результат проверки дисковой защиты, #FF допуск, 0 отказ
                ; проверка исходного конца фрагмента
                ASSERT $ == #E080
                endmodule
