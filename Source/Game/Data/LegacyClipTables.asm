                module Data
                module LegacyClipTables
; -----------------------------------------
; сохранившиеся таблицы предыдущего алгоритма отсечения линий
; первые 16 байтов преобразуют признаки координат точки в код области
; следующие 64 байта задают решение для пары кодов областей
; значения 0, 1 и 2 различали отбрасывание и варианты отсечения
; в справочной версии эта таблица читается процедурой PrnLineInBuf_clip
; здешний вход #B044 заменён арифметическим алгоритмом без обращения к таблице
; прямых обращений к #AFF0..#B043 в установленной карте кода нет
; четыре последних байта сохраняют прежние временные слова отсечения
; таблица оставлена в исходном месте для воспроизведения файла
; -----------------------------------------
                ; проверка исходного начала фрагмента
                ASSERT $ == #AFF0
Quadrants:      DB #00, #04, #02, #03, #00, #04, #06, #05
                DB #00, #08, #02, #01, #00, #08, #06, #07                       ; исходные байты #AFF8..#AFFF
PairCases:      DB #00, #00, #00, #02, #01, #02, #00, #00
                DB #00, #00, #00, #02, #02, #01, #02, #02                       ; исходные байты #B008..#B00F
                DB #00, #00, #00, #00, #00, #02, #01, #02                       ; исходные байты #B010..#B017
                DB #02, #02, #00, #00, #00, #02, #02, #01                       ; исходные байты #B018..#B01F
                DB #01, #02, #00, #00, #00, #00, #00, #02                       ; исходные байты #B020..#B027
                DB #02, #01, #02, #02, #00, #00, #00, #02                       ; исходные байты #B028..#B02F
                DB #00, #02, #01, #02, #00, #00, #00, #00                       ; исходные байты #B030..#B037
                DB #00, #02, #02, #01, #02, #02, #00, #00                       ; исходные байты #B038..#B03F
Scratch:        DB #00, #00, #00, #00                                           ; два прежних временных слова
                ; проверка исходного конца фрагмента
                ASSERT $ == #B044
                endmodule
                endmodule
