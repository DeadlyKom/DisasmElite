                module Trade
                module PrintKilometreSuffix
; -----------------------------------------
; Окончание единицы KM и проверка тоннажа
; исходный диапазон #E347..#E359
; In:
;   Нет параметров для E347
; Out:
;   Печатается M после K
; Corrupt:
;   HL, DE, BC, AF
; Note:
;   E34C считывает индекс E1DF, CY=1 для индексов <13 и 16, CY=0 для 13..15 и >=17
; -----------------------------------------
                ; проверка исходного начала фрагмента
                ASSERT $ == #E347
                ; общий хвост дописывает M к выбранному префиксу единицы измерения
Entry:          LD A, #4D
PrintSuffix:    JP Game.Text.PrintMainToken.Entry

                ; проверка тоннажа, товары 0..12 и 16 занимают тонны, 13..15 другую единицу
UsesTonnes:     LD A, (MarketWork.Commodity)
                CP #0D
                RET C                                                           ; выход, если индекс товара меньше 13, товар занимает тоннаж трюма

                CP #10
                JR NZ, NoTonnage                                                ; переход, если индекс товара не равен 16, товары 13..15 не занимают тоннаж

                SCF
                RET

NoTonnage:      AND A
                RET
                ; проверка исходного конца фрагмента
                ASSERT $ == #E35A
                endmodule
                endmodule
