                module Trade
                module Wait20Interrupts
; -----------------------------------------
; Задержка на 20 прерываний
; исходный диапазон #E35A..#E35D
; In:
;   Прерывания включены
; Out:
;   B=0
; Corrupt:
;   BC
; Note:
;   Старое имя файла использует число 14 в шестнадцатеричной записи, выполняются ровно 20 HALT
; -----------------------------------------
                ; проверка исходного начала фрагмента
                ASSERT $ == #E35A
                ; B=20 задаёт число последовательных HALT в общем цикле ожидания прерываний
Entry:          LD B, #14
                JR @Game.Trade.Wait36Interrupts.WaitFrame
                ; проверка исходного конца фрагмента
                ASSERT $ == #E35E
                endmodule
                endmodule
