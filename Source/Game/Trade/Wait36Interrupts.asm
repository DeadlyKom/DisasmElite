                module Wait36Interrupts
; -----------------------------------------
; Задержка на 36 прерываний
; исходный диапазон #E35E..#E363
; In:
;   Прерывания включены
; Out:
;   B=0
; Corrupt:
;   BC
; Note:
;   Вход E35E задаёт B=24 в шестнадцатеричной записи, вход E360 использует заданный B, A и флаги
;   сохраняются
; -----------------------------------------
                ; проверка исходного начала фрагмента
                ASSERT $ == #E35E
                ; B=36 задаёт более длинную паузу в том же цикле HALT
Entry:          LD B, #24
WaitFrame:      HALT
                DJNZ WaitFrame

                RET
                ; проверка исходного конца фрагмента
                ASSERT $ == #E364
                endmodule
                endmodule
