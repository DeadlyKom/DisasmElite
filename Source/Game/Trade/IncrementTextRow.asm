                module Trade
                module IncrementTextRow
; -----------------------------------------
; Увеличение строки текстового курсора
; исходный диапазон #E2B1..#E2B6
; In:
;   D046 = текущая строка
; Out:
;   Y увеличен, при Y>=24 устанавливаются Y=1 и X=0
; Corrupt:
;   AF
; Note:
;   Ограничение выполняет общий вход E2C8
; -----------------------------------------
                ; проверка исходного начала фрагмента
                ASSERT $ == #E2B1
                ; увеличение строки с переходом к общему ограничителю высоты
Entry:          LD A, (TextRow)
                INC A
                JR Game.Trade.SetTextRow.Entry
                ; проверка исходного конца фрагмента
                ASSERT $ == #E2B7
                endmodule
                endmodule
