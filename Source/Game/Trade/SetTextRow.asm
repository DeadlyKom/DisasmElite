                module SetTextRow
; -----------------------------------------
; Установка строки с циклическим ограничением
; исходный диапазон #E2C8..#E2D4
; In:
;   AF, A = новая Y
; Out:
;   D046=A при A<24, иначе Y=1 и X=0
; Corrupt:
;   AF
; Note:
;   Нулевая строка допустима, проверяется только верхняя граница
; -----------------------------------------
                ; проверка исходного начала фрагмента
                ASSERT $ == #E2C8
                ; строка записывается до проверки, выход за 23 замыкает счётчик в начало экрана
Entry:          LD (TextRow), A
                CP #18
                RET C                                                           ; выход, если номер строки меньше 24, он находится на экране

                LD A, #01
                LD (TextRow), A
                JR Game.Trade.ResetTextColumn.Entry
                ; проверка исходного конца фрагмента
                ASSERT $ == #E2D5
                endmodule
                endmodule
