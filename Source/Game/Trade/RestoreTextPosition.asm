                module Trade
                module RestoreTextPosition
; -----------------------------------------
; Восстановление печатного курсора
; исходный диапазон #E38D..#E397
; In:
;   E1E6/E1E7 = сохранённая позиция
; Out:
;   D045/D046 восстановлены, HL = позиция
; Corrupt:
;   HL
; Note:
;   E394..E397 после RET являются рабочими счётчиками ввода
; -----------------------------------------
                ; проверка исходного начала фрагмента
                ASSERT $ == #E38D
                ; восстановление сохранённых X и Y после диалога ввода
Entry:          LD HL, (MarketWork.TextPosition)
                LD (TextColumn), HL
                RET
                ; длина введённой строки
Length          DB #00                                                          ; число введённых символов
                ; указатель следующего символа буфера ввода
Cursor          DW #0000                                                        ; адрес следующего символа в буфере ввода
                ; последний код клавиши строкового редактора
LastKey         DB #00                                                          ; последний принятый код клавиши
                ; проверка исходного конца фрагмента
                ASSERT $ == #E398
                endmodule
                endmodule
