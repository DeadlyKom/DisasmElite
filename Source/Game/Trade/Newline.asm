                module Newline
; -----------------------------------------
; Перевод текстового курсора на новую строку
; исходный диапазон #E2A9..#E2B0
; In:
;   D045/D046 = координаты
; Out:
;   X=0, Y увеличен с переходом 24→1, D0D2=1
; Corrupt:
;   AF
; Note:
;   После сброса X исполнение продолжается в E2B1
; -----------------------------------------
                ; проверка исходного начала фрагмента
                ASSERT $ == #E2A9
                ; общий хвост нового абзаца увеличивает Y и сбрасывает X
Entry:          LD A, #01
                LD (WordStart), A
                CALL Game.Trade.ResetTextColumn.Entry
                ; проверка исходного конца фрагмента
                ASSERT $ == #E2B1
                endmodule
                endmodule
