                module AddByteOffsetToHL
; -----------------------------------------
; Прибавление байтового смещения к HL
; исходный диапазон #EB3E..#EB42
; In:
;   HL = база, AF, A = смещение
; Out:
;   HL=HL+A, DE=A
; Corrupt:
;   HL, DE, AF
; Note:
;   D обнуляется, A сохраняется, флаг CY отражает переполнение 16 бит
; -----------------------------------------
                ; проверка исходного начала фрагмента
                ASSERT $ == #EB3E
                ; прибавление беззнакового A к HL учитывает перенос младшего байта
Entry:          LD D, #00
                LD E, A
                ADD HL, DE
                RET
                ; проверка исходного конца фрагмента
                ASSERT $ == #EB43
                endmodule
                endmodule
