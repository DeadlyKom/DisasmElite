                module Extensions
                module SetExtendedTextCursor
; -----------------------------------------
; установка координат текстового курсора
; исходный диапазон #F90E..#F915
; смысловое имя SetExtendedTextCursor
; In: нет
; Out: слово TextPosition=#0206, HL=#0206
; Corrupt: HL
; AF и остальные регистры сохраняются, байт после RET не исполняется
; -----------------------------------------
                ; проверка исходного начала фрагмента
                ASSERT $ == #F90E
                ; запись обеих координат курсора одной 16-битной операцией
Entry:          LD HL, #0206
                LD (TextColumn), HL
                RET

                DB #00                                                          ; данные #F915..#F915
                ; проверка исходного конца фрагмента
                ASSERT $ == #F916
                endmodule
                endmodule
