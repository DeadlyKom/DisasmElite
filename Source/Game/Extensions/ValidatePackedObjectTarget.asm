                module Extensions
                module ValidatePackedObjectTarget
; -----------------------------------------
; проверка упакованного номера живого объекта
; исходный диапазон #F9E8..#FA0C
; смысловое имя ValidatePackedObjectTarget
; In: AF — младшая тетрада A задаёт номер 1..8, C выбирает проверку идентификатора
; Out: Z=0 и C-регистр равен номеру при успехе, Z=1 при отсутствии цели
; Corrupt: BC, AF, AF', HL и DE сохраняются
; Номер развёрнут в адрес энергии #6043+(9-номер)*#27
; Нулевая энергия или нулевой номер означают отказ
; При входном C=1 дополнительно требуются ненулевые флаги +20 соответствующего слота
; При входном C=0 успешная ветка возвращает исходные флаги AF, её вызывают с исходным Z=0
; При C=1 успешная ветка формирует Z=0 проверкой ненулевых флагов +20
; Флаг C на выходе не является признаком успеха, вызывающие процедуры используют Z
; -----------------------------------------
                ; проверка исходного начала фрагмента
                ASSERT $ == #F9E8
                ; сохранение входного C в альтернативном AF и извлечение номера
Entry:          PUSH AF
                EX AF, AF'
                POP AF
                AND #0F
                RET Z                                                           ; выход, если номер цели в младшей тетраде равен нулю

                ; расчёт адреса энергии по обратному номеру 1..8
                PUSH HL
                LD HL, Memory.Station - FSpaceObject + FSpaceObject.Energy
                LD B, A
                PUSH DE
                LD DE, #0027
FindEnergy:     ADD HL, DE
                INC A
                CP #09
                JR C, FindEnergy                                                ; переход, если индекс ещё меньше 9, продолжить развёртку номера в адрес

                POP DE
                ; проверка энергии и чтение флагов +20 на два байта раньше
                LD A, (HL)
                AND A
                DEC HL
                DEC HL
                LD A, (HL)
                POP HL
                RET Z                                                           ; выход, если энергия связанного объекта равна нулю

                ; восстановление режима проверки из AF' и проверка флагов объекта
                EX AF, AF'
                JR NC, ReturnNumber                                             ; переход, если входной C был сброшен, ненулевые флаги +20 не требуются

                EX AF, AF'
                AND A
                RET Z                                                           ; выход, если флаги +20 связанного объекта равны нулю

                ; возврат номера подтверждённой цели в C
ReturnNumber:   LD C, B
                RET
                ; проверка исходного конца фрагмента
                ASSERT $ == #FA0D
                endmodule
                endmodule
