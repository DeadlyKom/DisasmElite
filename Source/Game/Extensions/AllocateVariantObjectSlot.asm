                module Extensions
                module AllocateVariantObjectSlot
; -----------------------------------------
; поиск свободного слота с выбором варианта корабля
; исходный диапазон #FACA..#FAFF
; смысловое имя AllocateVariantObjectSlot
; In: BC — C содержит тип, IX — исходный объект
; Out: при успехе IX — свободный слот, C — выбранный тип, A=0 и Z=1
; Corrupt: HL, DE, BC, AF и IX по контрактам поиска и #7EC8
; При неуспехе #B936 возвращается NZ и создание объекта не производится
; Если младший байт исходного IX=#48 и тип #0A, случайно выбирается либо сохраняется тип #09/#0A/#0D/#0E
; Для типа 1 дополнительная запись не меняется
; Для остальных типов через #7EC8 находится отдельная запись и сбрасывается её бит 5
; Это подготовка слота, полную инициализацию выполняет вызывающий код
; -----------------------------------------
                ; проверка исходного начала фрагмента
                ASSERT $ == #FACA
                ; поиск свободного слота с сохранением исходного адреса объекта
Entry:          PUSH IX
                CALL Game.Objects.FindFreeObjectSlot.Entry
                POP HL
                RET NZ                                                          ; выход, если свободный слот не найден

                ; проверка условия случайного выбора варианта корабля
                LD A, L
                CP #48
                JR NZ, ClearMetaFlag                                            ; переход, если младший байт исходного IX отличается от #48, сохранить тип

                LD A, C
                CP #0A
                JR NZ, ClearMetaFlag                                            ; переход, если исходный тип отличается от #0A, сохранить тип

                ; расчёт вариантов типа из случайного байта
                CALL Game.Combat.NextRandomByte.Entry
                RLCA
                JR C, MixVariant                                                ; переход, если старший случайный бит установлен, сохранить промежуточный тип #0A

                DEC C
MixVariant:     AND C
                JR NZ, ClearMetaFlag                                            ; переход, если случайная маска ненулевая, оставить промежуточный тип #09 либо #0A

                LD A, C
                ADD A, #04
                LD C, A
                ; проверка исключения типа 1 и очистка бита отдельной записи
ClearMetaFlag:  LD A, C
                DEC A
                RET Z                                                           ; выход, если выбран тип 1, метаданные не требуют сброса бита 5

                PUSH IX
                CALL Game.Universe.GetObjectMetadataAddress.Entry
                RES FX_TIMER_BIT, (IX+FEffectRecord10.TypeFlags)
                POP IX
ProfileBase     XOR A                                                           ; код #AF также является элементом 0 таблицы малого профиля
                RET
                DB #81, #C1, #C2, #E2, #E3, #F3, #F4                            ; данные #FAF9..#FAFF
                ; проверка исходного конца фрагмента
                ASSERT $ == #FB00
                endmodule
                endmodule
