                module Extensions
                module ConsumeGalacticDriveCharge
; -----------------------------------------
; расход заряда галактического гиперпривода
; исходный диапазон #5D70..#5DC7
; смысловое имя ConsumeGalacticDriveCharge
; In: (#D08D) — наличие/остаток галактического гиперпривода, ноль означает отсутствие
; Out: ненулевой байт гиперпривода увеличен по модулю 256, Z отражает новое значение
; Corrupt: HL, AF
; Вызывается #DC29 после галактического перехода, #FF превращается в ноль и расходует одноразовый привод
; После RET находятся десять восьмибайтовых знаков дополнительного шрифта
; -----------------------------------------
                ; проверка исходного начала фрагмента
                ASSERT $ == #5D70
                ; расход ненулевого галактического гиперпривода после межгалактического перехода
Entry:          LD HL, State.GalacticDrive
                LD A, (HL)
                AND A
                RET Z                                                           ; выход, если галактический гиперпривод отсутствует

                INC (HL)
                RET
                ; десять знаков по восемь строк для дополнительного банка #5D70
                DB #7F, #40, #40, #20, #20, #10, #0C, #03                       ; данные #5D78..#5D7F
                DB #FE, #02, #02, #04, #04, #08, #30, #C0                       ; данные #5D80..#5D87
                DB #7F, #7F, #7F, #3F, #3F, #1F, #0F, #03                       ; данные #5D88..#5D8F
                DB #FE, #FE, #FE, #FC, #FC, #F8, #F0, #C0                       ; данные #5D90..#5D97
                DB #00, #7E, #42, #42, #42, #7E, #00, #FF                       ; данные #5D98..#5D9F
                DB #00, #C0, #F0, #F8, #FC, #FC, #FE, #FE                       ; данные #5DA0..#5DA7
                DB #00, #08, #10, #00, #00, #00, #00, #00                       ; данные #5DA8..#5DAF
                DB #00, #10, #20, #20, #20, #20, #10, #00                       ; данные #5DB0..#5DB7
                DB #00, #08, #04, #04, #04, #04, #08, #00                       ; данные #5DB8..#5DBF
                DB #00, #10, #10, #10, #10, #00, #10, #00                       ; данные #5DC0..#5DC7
                ; проверка исходного конца фрагмента
                ASSERT $ == #5DC8
                endmodule
                endmodule
