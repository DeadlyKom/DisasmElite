                module Extensions
                module SelectCharacterFont
; -----------------------------------------
; выбор банка знакогенератора по коду символа
; исходный диапазон #5DFB..#5E19
; смысловое имя SelectCharacterFont
; In: AF — A содержит код символа
; Out: HL — #3D00 для пробела, цифр с двоеточием и латинских букв, иначе #5D70
; Corrupt: HL, AF — изменяются только флаги, A сохраняется
; Адрес начала глифа вычисляет вызывающий код, здесь выбирается только база
; Проверяются интервалы #30..#3A, #41..#5A и #61..#7A включительно
; -----------------------------------------
                ; проверка исходного начала фрагмента
                ASSERT $ == #5DFB
                ; выбор стандартного знакогенератора для пробела и буквенно-цифровых диапазонов
Entry:          LD HL, RomFont
                CP #20
                RET Z                                                           ; выход, если код является пробелом, выбран шрифт ROM

                CP #30
                JR C, ExtraFont                                                 ; переход, если код меньше #30, нужен дополнительный шрифт

                CP #3B
                RET C                                                           ; выход, если код находится в диапазоне #30..#3A, выбран шрифт ROM

                CP #41
                JR C, ExtraFont                                                 ; переход, если код между #3B и #40, нужен дополнительный шрифт

                CP #5B
                RET C                                                           ; выход, если код находится в диапазоне A..Z, выбран шрифт ROM

                CP #61
                JR C, ExtraFont                                                 ; переход, если код между #5B и #60, нужен дополнительный шрифт

                CP #7B
                RET C                                                           ; выход, если код находится в диапазоне a..z, выбран шрифт ROM

ExtraFont:      LD HL, ExtraFontBase
                RET
                ; проверка исходного конца фрагмента
                ASSERT $ == #5E1A
                endmodule
                endmodule
