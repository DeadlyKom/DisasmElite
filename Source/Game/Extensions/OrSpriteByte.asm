                module Extensions
                module OrSpriteByte
; -----------------------------------------
; наложение байта силуэта на экранный буфер
; исходный диапазон #FB00..#FB02
; смысловое имя OrSpriteByte
; In: HL — адрес байта экрана, AF — A содержит маску
; Out: A и (HL) равны прежнему (HL) OR маска, C=0
; Corrupt: AF
; Нулевые пиксели маски оставляют фон прежним, HL не изменяется
; -----------------------------------------
                ; проверка исходного начала фрагмента
                ASSERT $ == #FB00
                ; объединение маски силуэта с уже нарисованными пикселями
Entry:          OR (HL)
                LD (HL), A
                RET

                ; проверка исходного конца фрагмента
                ASSERT $ == #FB03
                endmodule
                endmodule
