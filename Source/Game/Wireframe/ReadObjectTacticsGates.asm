                module Wireframe
                module ReadObjectTacticsGates
; -----------------------------------------
; чтение двух независимых условий допуска тактического обновления
; исходный диапазон #B4C4..#B4D7
; In:
;   IX, объект
;   память ObjectEffects.Current, указатель его метаданных
; Out:
;   HL, адрес FEffectRecord10.Links текущей расширенной записи
;   DE, число 8
;   AF, A содержит младшую тетраду FEffectRecord10.Links, CY установлен при её нуле, Z установлен при сброшенном OBJ_ANGER_BIT в FSpaceObject.Hostility
; Corrupt:
;   нет дополнительных регистров
; Note:
; CP 1 задаёт перенос по младшей тетраде, последующий BIT не меняет перенос.
; Поэтому C и Z описывают разные признаки, их одновременно использует Game.Motion.CheckObjectBoxAndChooseCourse.ChooseCourse.
; Три завершающих нулевых байта являются данными между процедурами.
; -----------------------------------------
                ; проверка исходного начала фрагмента
                ASSERT $ == #B4C4
                ; поиск признака разрешения тактики в расширенных метаданных
Entry:          LD HL, (ObjectEffects.Current)
                LD DE, #0008
                ADD HL, DE
                LD A, (HL)
                AND #0F
                CP #01
                ; проверка отдельного бита объекта с сохранением переноса
                BIT OBJ_ANGER_BIT, (IX + FSpaceObject.Hostility)
                RET

                ; данные между процедурами
LaserData       EQU $                                                           ; начало сохранённых рабочих данных, исходное размещение
.Reserved       DB #00                                                          ; исходный байт без установленного потребителя
.Signs          DB #00                                                          ; биты 3/2 знаков центральной точки свободного лазерного луча
.TriggerHeld    DB #00                                                          ; флаг, спуск лазера был активен на предыдущем обновлении
                ; проверка исходного конца фрагмента
                ASSERT $ == #B4D8
                endmodule
                endmodule
