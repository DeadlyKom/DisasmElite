                module Wireframe
                module SavePreviousVertexFlags
; -----------------------------------------
; сохранение предыдущего байта признаков вершины
; исходный диапазон #AA2B..#AA30
; In:
;   память AA0F, текущий байт признаков
; Out:
;   память AA0E, копия предыдущего байта
; Corrupt:
;   HL, AF
; Note:
; Фрагмент без RET продолжается в AA31 и читает признаки следующей записи.
; AA0E/AA0F позволяют переиспользовать произведения симметричных вершин с другими знаками.
; -----------------------------------------
                ; проверка исходного начала фрагмента
                ASSERT $ == #AA2B
                ; сохранение предыдущих знаков перед чтением следующей вершины
Entry:          LD HL, VertexFlags.Current
                LD A, (HL)
                DEC HL
                LD (HL), A
                ; проверка исходного конца фрагмента
                ASSERT $ == #AA31
                endmodule
                endmodule
