                module Wireframe
                module DivideProjectionRatio
; -----------------------------------------
; нормализация и дробное деление перспективной проекции
; исходный диапазон #AC69..#AC8A
; In:
;   HL, старшие 16 бит делителя
;   DE, старшие 16 бит делимого
;   BC, C содержит младший байт делимого
;   AF, A содержит младший байт делителя
; Out:
;   BC, C содержит восьмибитное отношение с насыщением FF
; Corrupt:
;   HL, DE, AF
; Note:
; Входные величины имеют формат DE.C и HL.A, результат 0.C.
; Общие сдвиги нормализуют старшие байты с учётом переполнения.
; Числитель не меньше знаменателя возвращает FF, иначе фрагмент продолжается в AC8B.
; -----------------------------------------
                ; проверка исходного начала фрагмента
                ASSERT $ == #AC69
                ; нормализация двух трёхбайтовых величин
Entry:          LD B, #09
NormalizeRatio: DEC B
                JR Z, CheckSaturate                                             ; переход, если выполнены восемь нормализующих сдвигов

                RLA
                ADC HL, HL
                JR C, UndoOverflow                                              ; переход, если делитель при удвоении вышел за 16 бит

                RL C
                RL E
                RL D
                JR NC, NormalizeRatio                                           ; переход, если делимое ещё не переполнилось и нормализация продолжается

                RR D
                RR E
                SCF
                ; согласование масштаба при переполнении
UndoOverflow:   RR H
                RR L
                ; проверка насыщения перед делением
CheckSaturate:  LD A, D
                LD C, #FF
                CP H
                RET NC                                                          ; выход, если старший числитель не меньше знаменателя и результат насыщается

                LD B, H
                DEC C
                ; проверка исходного конца фрагмента
                ASSERT $ == #AC8B
                endmodule
                endmodule
