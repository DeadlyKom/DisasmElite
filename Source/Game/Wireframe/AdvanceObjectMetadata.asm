                module Wireframe
                module AdvanceObjectMetadata
; -----------------------------------------
; переход к следующей расширенной записи объекта
; исходный диапазон #A8EC..#A9C8
; In:
;   память B452, текущая запись
; Out:
;   HL, следующая запись
;   DE, число 39 для шага основного слота
; Corrupt:
;   AF
; Note:
; Метаданные имеют шаг 10, основной объект шаг 39.
; После RET лежит рабочая область геометрии, её исходные содержимые сохранены.
; A8FA..A983, 46 экранных вершин по три байта. A984..A993, 16 флагов граней.
; A994..A9A5, девять слов матрицы. A9A6..A9B7, девять кэшированных произведений.
; A9B8, глубина. A9BA, смещение вершины. A9BB..A9C0, повёрнутые X/Y/Z.
; A9C1..A9C3, проекции и знаки. A9C4..A9C6, знаки пространственных координат.
; A9C7, число сдвигов ближней проекции. A9C8, запрет использования кэша.
; -----------------------------------------
                ; проверка исходного начала фрагмента
                ASSERT $ == #A8EC
                ; обновление указателя метаданных и подготовка шага основного объекта
Entry:          LD HL, (ObjectEffects.Current)
                LD DE, #000A
                ADD HL, DE
                LD (ObjectEffects.Current), HL
                LD E, #27
                RET
                ; рабочие данные проекций, граней, матрицы и промежуточных вычислений
LeadingByte     DB #7B                                                          ; исходный байт перед таблицей экранных вершин
GeometryData    EQU $                                                           ; начало сохранённых рабочих данных, исходное размещение
.Vertices       DB #2A, #53, #00, #0A, #1F, #02, #08, #04                       ; 46 экранных вершин по три байта, X, Y, признаки
                DB #00, #0B, #0F, #03, #1C, #02, #03, #25                       ; продолжение сохранённых байтов
                DB #2D, #03, #1C, #34, #03, #16, #31, #03                       ; продолжение сохранённых байтов
                DB #1E, #08, #00, #0E, #19, #01, #0E, #38                       ; продолжение сохранённых байтов
                DB #03, #08, #08, #03, #16, #0F, #01, #09                       ; продолжение сохранённых байтов
                DB #12, #01, #01, #13, #01, #0C, #14, #03                       ; продолжение сохранённых байтов
                DB #0B, #0D, #03, #02, #0A, #01, #0B, #08                       ; продолжение сохранённых байтов
                DB #01, #18, #08, #01, #0A, #18, #02, #0B                       ; продолжение сохранённых байтов
                DB #1C, #02, #2C, #07, #01, #2B, #0B, #01                       ; продолжение сохранённых байтов
                DB #2F, #08, #01, #22, #16, #03, #26, #15                       ; продолжение сохранённых байтов
                DB #03, #23, #12, #03, #00, #00, #00, #00                       ; продолжение сохранённых байтов
                DB #00, #00, #00, #00, #00, #00, #00, #00                       ; продолжение сохранённых байтов
                DB #00, #00, #00, #00, #00, #00, #00, #00                       ; продолжение сохранённых байтов
                DB #00, #00, #00, #00, #00, #00, #00, #00                       ; продолжение сохранённых байтов
                DB #00, #00, #00, #00, #00, #00, #00, #00                       ; продолжение сохранённых байтов
                DB #00, #00, #00, #00, #00, #00, #00, #00                       ; продолжение сохранённых байтов
                DB #00, #00, #00, #00, #00, #00, #00, #00                       ; продолжение сохранённых байтов
                DB #00, #00                                                     ; продолжение сохранённых байтов
.Faces          DB #00, #01, #00, #01, #00, #01, #00, #01                       ; 16 байтов видимости граней
                DB #00, #01, #01, #00, #01, #01, #01, #01                       ; продолжение сохранённых байтов
.Matrix         DW #1B7E, #EF81, #37F3, #1D81, #3C7E, #6DF3, #F8F2, #8BF2       ; матрица поворота, три строки по три знаковых слова
                DW #27F3                                                        ; продолжение сохранённых байтов
.Products       DW #0000, #0015, #8030, #0000, #800B, #805F, #8000, #0002       ; девять кэшированных произведений модулей вершины и матрицы
                DW #8022                                                        ; продолжение сохранённых байтов
.Depth          DW #0202                                                        ; глубина объекта, младший байт затем переиспользуется как уровень детализации
.VertexOffset   DB #1E                                                          ; смещение трёхбайтовой записи в таблице экранных вершин
.X              DW #001B                                                        ; повёрнутая X-компонента, затем X с добавленным положением объекта
.Y              DW #006A                                                        ; повёрнутая Y-компонента, затем Y с добавленным положением объекта
.Z              DW #01DF                                                        ; повёрнутая Z-компонента, затем Z с добавленным положением объекта
.ScreenX        DB #0E                                                          ; модуль горизонтальной проекции центра или вершины
.ScreenY        DB #38                                                          ; модуль вертикальной проекции центра или вершины
.Flags          DB #03                                                          ; бит 1 знак X, бит 0 знак Y, схема в FProjectionState
.SignX          DB #80                                                          ; знаковый старший байт пространственной координаты X
.SignY          DB #80                                                          ; знаковый старший байт пространственной координаты Y
.SignZ          DB #00                                                          ; знаковый старший байт пространственной координаты Z
.Scale          DB #01                                                          ; число левых сдвигов для повышенной точности ближней вершины
.NoCache        DB #00                                                          ; флаг, произведения предыдущей вершины нельзя использовать
                ; проверка исходного конца фрагмента
                ASSERT $ == #A9C9
                endmodule
                endmodule
