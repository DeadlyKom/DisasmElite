                module Wireframe
                module MultiplyHighByteApprox
; -----------------------------------------
; приближённый старший байт произведения двух беззнаковых байтов
; исходный диапазон #AB0B..#AB1D
; In:
;   BC, B и C содержат множители
; Out:
;   BC, исходные множители
;   AF, A содержит разность старших байтов двух квадратов
; Corrupt:
;   HL, DE, D меняется, E сохраняется
; Note:
; Индексы таблицы равны floor((B+C)/2) и floor(abs(B-C)/2).
; Вычитаются только старшие байты квадратов #BF00, заём младших байтов не учитывается.
; Поэтому результат не всегда равен старшему байту результата AB34.
; -----------------------------------------
                ; проверка исходного начала фрагмента
                ASSERT $ == #AB0B
                ; расчёт половины модуля разности множителей
Entry:          LD A, B
                SUB C
                JR NC, HalfDifference                                           ; переход, если B не меньше C и модуль разности уже положителен

                NEG
HalfDifference: SRL A
                LD H, #BF
                LD L, A
                ; расчёт половины суммы и разности старших байтов квадратов
                LD D, (HL)
                LD A, B
                ADD A, C
                RRA
                LD L, A
                LD A, (HL)
                SUB D
                RET
                ; проверка исходного конца фрагмента
                ASSERT $ == #AB1E
                endmodule
                endmodule
