                module Wireframe
                module SetTargetDisplayState
; -----------------------------------------
; сохранение состояния цели и сброс старшего флага метаданных
; исходный диапазон #B4B1..#B4B9
; In:
;   AF, A содержит состояние
;   память B452, указатель метаданных текущего объекта
; Out:
;   HL, адрес метаданных
;   память 9CB4, новое состояние
; Corrupt:
;   нет дополнительных регистров
; Note:
; RES 7,(HL) меняет только старший бит первого байта метаданных.
; Состояние 9CB4 используется обработчиками ракетного прицеливания.
; -----------------------------------------
                ; проверка исходного начала фрагмента
                ASSERT $ == #B4B1
                ; обновление состояния цели и сброс признака в метаданных
Entry:          LD (ObjectIndex), A
                LD HL, (ObjectEffects.Current)
                RES 7, (HL)
                RET
                ; проверка исходного конца фрагмента
                ASSERT $ == #B4BA
                endmodule
                endmodule
