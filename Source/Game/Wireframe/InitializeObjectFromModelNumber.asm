                module Wireframe
                module InitializeObjectFromModelNumber
; -----------------------------------------
; инициализация объекта по номеру в общем каталоге моделей
; исходный диапазон #AE35..#AE4F
; In:
;   AF, A содержит номер модели
;   IX, инициализируемый слот
; Out:
;   объект заполнен общим инициализатором B89C
; Corrupt:
;   HL, DE, BC, AF, IY
; Note:
; Хвостовой переход использует каталог #6180, результат соответствует инициализатору объектов.
; #AE3C..#AE47 содержит двенадцать номеров кораблей демонстрационного выбора.
; После таблицы сохранены остаточные машинные байты и отдельный RET в #AE4F.
; -----------------------------------------
                ; проверка исходного начала фрагмента
                ASSERT $ == #AE35
                ; поиск модели в общем каталоге перед инициализацией слота
Entry:          LD HL, Memory.ModelIndex
                LD B, A
                JP Game.Objects.InitializeObject.ModelIndex
                ; данные списка двенадцати моделей демонстрации
DemoModels      DB #06, #07, #08, #0B, #0C, #0D, #11, #0E                       ; двенадцать номеров моделей демонстрационного экрана
                ; оставшиеся четыре номера моделей демонстрации, продолжение списка #AE3C
                DB #14, #0F, #12, #13

; -----------------------------------------
; сохранённая последовательность фиксации адреса с ожиданием прерывания
; In:
;   HL, адрес читаемого байта
; Out:
;   AF, A содержит прочитанный байт, собственные инструкции флаги не меняют
;   слово #F3D8 получает исходный HL
; Corrupt:
;   AF
; Note:
;   прямые входящие переходы не найдены
;   после LD A,(HL) записывает L в #F3D8 и H в #F3D9, затем выполняет HALT и RET
;   запись заменяет символ S и нулевой конец строки EXTRA PULSE LASERS, сообщение #6D
;   выход из HALT требует принятого прерывания, команды DI и EI здесь отсутствуют
;   найденные ссылки не подтверждают запуск, глобальная недостижимость не утверждается
;   причина присутствия этой последовательности и намерение автора не установлены
;   фрагмент не включён в действующий список 12 демонстрационных моделей #AE3C..#AE47
; -----------------------------------------
LegacyLatch:    ; сохранённая последовательность фиксации адреса с ожиданием прерывания
                LD A, (HL)
                LD (Game.Extensions.PrintCargoAndMessageBanks.PulseLaserTail), HL
                HALT
                RET

; -----------------------------------------
; дополнительный сохранённый пустой вход
; In:
;   любые регистры
; Out:
;   все регистры и флаги сохраняются
; Corrupt:
;   нет
; Note:
;   прямые входящие переходы не найдены
; -----------------------------------------
EmptyReturn:    ; дополнительный сохранённый пустой вход
                RET

                ; пустой совместимый выход исходного образа
                RET
                ; проверка исходного конца фрагмента
                ASSERT $ == #AE50
                endmodule
                endmodule
