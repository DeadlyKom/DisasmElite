                module Wireframe
                module ReadFaceVisibilityNibble
; -----------------------------------------
; чтение видимости грани по младшей тетраде номера
; исходный диапазон #AA20..#AA2A
; In:
;   AF, A содержит упакованный номер грани
; Out:
;   AF, A содержит байт видимости выбранной грани
; Corrupt:
;   нет дополнительных регистров
; Note:
; Младшая тетрада выбирает один из 16 байтов #A984..#A993.
; Адрес выбирается изменением младшего байта операнда LD A,(nn) в #AA28.
; Процедура самомодифицируется и требует записываемого кода.
; -----------------------------------------
                ; проверка исходного начала фрагмента
                ASSERT $ == #AA20
                ; поиск флага грани через изменение младшего байта адреса чтения
Entry:          AND #0F
                ADD A, #84
                LD (VertexRaster.FaceAddress), A
FaceAddress     EQU $ + 1                                                       ; младший байт адреса чтения флага выбранной грани
                LD A, (FaceVisibility)
                RET
                ; проверка исходного конца фрагмента
                ASSERT $ == #AA2B
                endmodule
                endmodule
