                module Wireframe
                module DrawScannerMarkerSegment
; -----------------------------------------
; вывод отрезка маркера сканера с изменяемыми командами шага
; исходный диапазон #B440..#B4B0
; In:
;   HL, два однобайтовых кода шага координат B/C
;   DE, E содержит ненулевую длину
;   BC, начальные координаты
; Out:
;   HL, DE, BC, исходные значения
; Corrupt:
;   AF
; Note:
; Два байта HL записываются непосредственно в код #B446/#B447.
; Вызывающий код подставляет INC/DEC B/C и NOP, после каждого шага рисуется пиксель.
; #B452 хранит указатель текущих расширенных метаданных, далее лежит рабочая область записей объектов.
; -----------------------------------------
                ; проверка исходного начала фрагмента
                ASSERT $ == #B440
                ; сохранение координат и установка двух команд шага
Entry:          PUSH BC
                PUSH DE
                PUSH HL
                LD (ScannerRaster.StepOpcodes), HL
                ; самомодифицируемый шаг координат перед очередным пикселем
StepOpcodes     EQU $                                                           ; два кода INC/DEC B/C либо NOP, шаг отрезка маркера
DrawPixel:      NOP
                NOP
                CALL Game.Motion.XorFarObjectPixel.Entry
                DEC E
                JR NZ, DrawPixel                                                ; переход, если ещё не выведены все пиксели отрезка

                POP HL
                POP DE
                POP BC
                RET
                ; данные указателя и рабочей области расширенных метаданных объектов
EffectData      EQU $                                                           ; начало сохранённых рабочих данных, исходное размещение
.Current        DW #B4A7                                                        ; указатель текущей десятибайтовой записи расширенного эффекта
.Phase          DB #00                                                          ; фаза распределения объектов, младшие два бита проходят 1, 2, 3
.Remaining      DB #00                                                          ; обратный номер текущего слота, счётчик обхода от 8 до 1
.Flags          DB #00                                                          ; общие флаги режима расширенных эффектов
.Records        DB #00, #00, #00, #00, #00, #00, #00, #00                       ; восемь десятибайтовых записей FEffectRecord10
                DB #00, #00, #00, #00, #00, #00, #00, #00                       ; продолжение сохранённых байтов
                DB #00, #00, #00, #00, #00, #00, #00, #00                       ; продолжение сохранённых байтов
                DB #00, #00, #00, #00, #00, #00, #00, #00                       ; продолжение сохранённых байтов
                DB #00, #00, #00, #00, #00, #00, #00, #00                       ; продолжение сохранённых байтов
                DB #00, #00, #00, #00, #00, #00, #00, #00                       ; продолжение сохранённых байтов
                DB #00, #00, #00, #00, #00, #00, #00, #00                       ; продолжение сохранённых байтов
                DB #00, #00, #00, #00, #00, #00, #00, #00                       ; продолжение сохранённых байтов
                DB #00, #00, #00, #00, #00, #00, #00, #00                       ; продолжение сохранённых байтов
                DB #00, #00, #00, #00, #00, #00, #00, #00                       ; продолжение сохранённых байтов
.Scratch        DB #00, #00, #00, #00, #00, #00, #00, #00                       ; дополнительная запись, исходная цель указателя Current
                DB #00, #00                                                     ; продолжение сохранённых байтов
                ; проверка исходного конца фрагмента
                ASSERT $ == #B4B1
                endmodule
                endmodule
