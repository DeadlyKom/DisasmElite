                module Wireframe
                module AdvanceVertexFlags
; -----------------------------------------
; переход к следующей трёхбайтовой записи признаков вершины
; исходный диапазон #AE1D..#AE25
; In:
;   память 6FEB, текущая запись признаков
; Out:
;   HL, следующая запись
;   BC, 3 если её бит 0 установлен, иначе 0
;   AF, Z если координаты можно переиспользовать
; Corrupt:
;   нет дополнительных регистров
; Note:
; Общий хвост AE2D записывает указатель и проверяет необходимость следующей тройки модулей.
; BC затем добавляется к IX с координатами, позволяя симметричным вершинам повторно использовать модуль.
; -----------------------------------------
                ; проверка исходного начала фрагмента
                ASSERT $ == #AE1D
                ; поиск следующей записи признаков вершины
Entry:          LD BC, #0003
                LD HL, (Game.Extensions.DrawCompressedEdges.FlagsStream)
                ADD HL, BC
                JR Game.Wireframe.AdvanceNormalFlags.StoreFlags
                ; проверка исходного конца фрагмента
                ASSERT $ == #AE26
                endmodule
                endmodule
