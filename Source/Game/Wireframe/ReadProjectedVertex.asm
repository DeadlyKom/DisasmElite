                module Wireframe
                module ReadProjectedVertex
; -----------------------------------------
; чтение экранных координат и признаков вершины
; исходный диапазон #AE50..#AE68
; In:
;   AF, A содержит номер вершины
; Out:
;   HL, адрес третьего байта записи
;   DE, D содержит модуль X, E модуль Y
;   AF, A содержит признаки, Z при сброшенном бите 7
; Corrupt:
;   BC
; Note:
; Адрес записи равен ProjectedVerts+3*A. Три байта содержат X, Y и знаки/признак скрытия.
; Бит 7 отмечает непроецируемую или находящуюся за камерой вершину.
; -----------------------------------------
                ; проверка исходного начала фрагмента
                ASSERT $ == #AE50
                ; расчёт адреса трёхбайтовой экранной записи
Entry:          LD B, A
                ADD A, A
                LD HL, ProjectedVerts
                JR NC, AddThirdIndex                                            ; переход, если удвоение номера не переносит единицу в старший байт адреса

                INC H
AddThirdIndex:  ADD A, B
                JR NC, AddTableBase                                             ; переход, если добавление третьего номера не переносит единицу

                INC H
AddTableBase:   ADD A, L
                LD L, A
                JR NC, ReadPosition                                             ; переход, если добавление младшего байта базы не переносит единицу

                INC H
                ; чтение координат и проверка признака скрытой вершины
ReadPosition:   LD D, (HL)
                INC HL
                LD E, (HL)
                INC HL
                LD A, (HL)
                BIT VERT_HIDDEN_BIT, A
                RET

                ; проверка исходного конца фрагмента
                ASSERT $ == #AE69
                endmodule
                endmodule
