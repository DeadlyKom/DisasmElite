                module Wireframe
                module MergeInverseHostilityFlag
; -----------------------------------------
; добавление бита 2 к A при сброшенном бите исходного байта
; исходный диапазон #B4BA..#B4C3
; In:
;   HL, адрес исходного байта признаков
;   AF, A содержит формируемые признаки
; Out:
;   AF, A может получить установленный бит 2
; Corrupt:
;   нет дополнительных регистров
; Note:
; Обёртка инвертирует смысл одного проверяемого бита при формировании признаков.
; После RET сохранены четыре байта прежней команды LD DE,(ProjectionState.ScreenX), этот вход их не исполняет.
; -----------------------------------------
                ; проверка исходного начала фрагмента
                ASSERT $ == #B4BA
                ; проверка необходимости добавить бит 2 к результирующим признакам
Entry:          BIT FX_ALLOW_BIT, (HL)
                RET NZ                                                          ; выход, если бит 2 исходного байта уже установлен и A менять не нужно

                SET FX_ALLOW_BIT, A
                RET

                ; сохранённые байты прежнего чтения экранных координат

; -----------------------------------------
; сохранённое чтение пары проекционных координат перед общим хвостом
; In:
;   слово ProjectionState.ScreenX, проекция X и Y
;   IX, объект
;   слово ObjectEffects.Current, текущая запись расширенных данных
; Out:
;   продолжение Game.Wireframe.ReadObjectTacticsGates.Entry, прочитанное DE там заменяется числом 8
; Corrupt:
;   HL, DE, AF
; Note:
;   сохранённый вход, прямые входящие переходы не найдены
;   первая загрузка не влияет на конечный результат, далее выполняется полный контракт Game.Wireframe.ReadObjectTacticsGates.Entry
; -----------------------------------------
LegacyReadPoint:; сохранённое чтение пары проекционных координат перед общим хвостом
                LD DE, (ProjectionState.ScreenX)                                ; далее Game.Wireframe.ReadObjectTacticsGates.Entry без команды перехода
                ; проверка исходного конца фрагмента
                ASSERT $ == #B4C4
                endmodule
                endmodule
