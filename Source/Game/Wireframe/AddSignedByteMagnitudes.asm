                module Wireframe
                module AddSignedByteMagnitudes
; -----------------------------------------
; сложение двух байтовых модулей с отдельными знаками
; исходный диапазон #AAFB..#AB0A
; In:
;   HL, H содержит знак первого слагаемого, L модуль
;   DE, D содержит знак второго слагаемого, E модуль
; Out:
;   HL, H содержит знак результата
;   AF, A содержит модуль, перенос сообщает переполнение суммы
; Corrupt:
;   нет дополнительных регистров
; Note:
; При разных знаках выбираются разность модулей и знак большего.
; Переполнение одинаковых знаков не насыщается здесь, его обрабатывает вызывающий код.
; -----------------------------------------
                ; проверка исходного начала фрагмента
                ASSERT $ == #AAFB
                ; проверка знаков перед выбором сложения или вычитания
Entry:          LD A, H
                XOR D
                RLA
                JR C, SubtractTerms                                             ; переход, если знаки слагаемых различаются

                LD A, L
                ADD A, E
                RET

                ; расчёт разности модулей с выбором её знака
SubtractTerms:  LD A, L
                SUB E
                RET NC                                                          ; выход, если модуль первого слагаемого не меньше второго

                NEG
                AND A
                LD H, D
                RET
                ; проверка исходного конца фрагмента
                ASSERT $ == #AB0B
                endmodule
                endmodule
