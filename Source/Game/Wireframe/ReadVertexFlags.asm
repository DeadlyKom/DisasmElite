                module Wireframe
                module ReadVertexFlags
; -----------------------------------------
; чтение признаков вершины через текущий указатель модели
; исходный диапазон #AA31..#AA3C
; In:
;   память Game.Extensions.DrawCompressedEdges.FlagsStream, адрес записи признаков
; Out:
;   HL, адрес записи
;   AF, A содержит прочитанный байт с установленным битом 0
;   память AA0F, исходный байт признаков
; Corrupt:
;   нет дополнительных регистров
; Note:
; В памяти сохраняется исходный байт, OR 1 влияет только на возвращаемое A.
; Следующие два байта #9C,#B8 сохранены как данные между процедурами.
; -----------------------------------------
                ; проверка исходного начала фрагмента
                ASSERT $ == #AA31
                ; чтение текущих признаков без изменения записи модели
Entry:          LD HL, (Game.Extensions.DrawCompressedEdges.FlagsStream)
                LD A, (HL)
                LD (VertexFlags.Current), A
                OR #01
                RET

                ; сохранённые байты между процедурами
                DB #9C, #B8
                ; проверка исходного конца фрагмента
                ASSERT $ == #AA3D
                endmodule
                endmodule
