                module Wireframe
                module AddRotatedVertexCoordinate
; -----------------------------------------
; сложение координаты объекта и преобразованной координаты вершины
; исходный диапазон #AB4F..#AB72
; In:
;   HL, модуль координаты объекта
;   DE, знако-модульная координата вершины
;   BC, B содержит знак координаты объекта
;   AF, перенос содержит дополнительный младший разряд вершины
;   стек, под адресом возврата сохранено AF с дробной частью вершины
; Out:
;   HL, модуль суммы
;   AF, A содержит знак результата
;   стек, дробная часть может быть заменена при смене знака
; Corrupt:
;   DE, BC
; Note:
; DE разворачивается на один разряд влево, освобождая старший знаковый бит.
; Для разных знаков вычисляется разность и выбирается знак большего модуля.
; Если требуется отрицание дробной части, функция извлекает сохранённое AF из стека вызывающего кода.
; DEC HL компенсирует переход от целой части к отрицанной дробной, это специальный стековый контракт.
; -----------------------------------------
                ; проверка исходного начала фрагмента
                ASSERT $ == #AB4F
                ; распаковка знака вершины и проверка знаков слагаемых
Entry:          LD C, D
                RL E
                RL D
                LD A, B
                XOR C
                JR NZ, SubtractVertex                                           ; переход, если знаки координаты объекта и вершины различаются

                ADD HL, DE
                LD A, B
                RET

                ; расчёт разности модулей
SubtractVertex: SBC HL, DE
                JR NC, CheckFraction                                            ; переход, если модуль координаты объекта не меньше преобразованной вершины

                ADD HL, DE
                EX DE, HL
                AND A
                SBC HL, DE
                LD A, C
                RET

CheckFraction:  LD A, H
                OR L
                LD A, C
                RET Z                                                           ; выход, если целая часть разности нулевая и коррекция дробной части не требуется

                POP DE
                ; обновление дробной части на стеке при смене направления
                POP AF
                NEG
                PUSH AF
                PUSH DE
                DEC HL
                LD A, B
                RET
                ; проверка исходного конца фрагмента
                ASSERT $ == #AB73
                endmodule
                endmodule
