                module Galaxy
                module OnesComplementDifference
; -----------------------------------------
; Разность координат в однобайтовой арифметике
; исходный диапазон #DFEA..#DFF1
; In:
;   BC, B = вычитаемое, AF, A = уменьшаемое
; Out:
;   A=A-B при A>=B, иначе B-A-1
; Corrupt:
;   AF
; Note:
;   Отрицательная разность инвертируется CPL без INC, поэтому отличается от точного абсолютного
;   значения на 1, Game.Galaxy.OnesComplementDifference.ToggleBit1 отдельные байты LD A, (HL), XOR2, RET
; -----------------------------------------
                ; проверка исходного начала фрагмента
                ASSERT $ == #DFEA
                ; для отрицательной разности используется CPL, результат равен B-A-1, а не B-A
Entry:          SUB B
                RET NC                                                          ; выход, если вычитание координат не дало заём, разность уже имеет нужное направление

                CPL
                RET

                ; сохранённый вход чтения байта с инверсией бита 1, завершается следующим RET
ToggleBit1:     LD A, (HL)
                XOR #02
                RET

                ; проверка исходного конца фрагмента
                ASSERT $ == #DFF2
                endmodule
                endmodule
