                module Galaxy
                module RotateSeedPair
; -----------------------------------------
; Циклический поворот двух байтов семени
; исходный диапазон #DF1A..#DF23
; In:
;   HL = адрес пары
; Out:
;   DE содержит изменённую пару, HL указывает на второй байт
; Corrupt:
;   HL, DE, AF
; Note:
;   В отличие от DC83 указатель после второго байта не увеличивается
; -----------------------------------------
                ; проверка исходного начала фрагмента
                ASSERT $ == #DF1A
                ; поворот пары байтов семени с замыканием переноса через старший разряд
Entry:          LD E, (HL)
                RLC E
                LD (HL), E
                INC HL
                LD D, (HL)
                RLC D
                LD (HL), D
                RET
                ; проверка исходного конца фрагмента
                ASSERT $ == #DF24
                endmodule
                endmodule
