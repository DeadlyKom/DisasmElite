                module CopyFlightView
; -----------------------------------------
; вывод 120 строк буфера вида в экран начиная со строки 8
; In:
;   не требуются
; Out:
;   120 строк экрана начиная с Memory.Screen + #0020 обновлены из буфера Memory.Frame
; Corrupt:
;   HL, DE, BC, AF
; Note:
;   сначала копируются 60 чётных строк, затем 60 нечётных
;   каждая строка содержит 32 байта, всего переносится 3840 байтов
;   вывод первой половины вызывает Game.Screen.CopySixtyRows.Entry, вторая половина проваливается туда же
;   буфер использует ту же перестановку строк, что видеопамять Spectrum
; -----------------------------------------
                ; проверка исходного размещения
                ASSERT $ == #7FBE
                ; вывод чётных строк, исходная строка 0 соответствует экранной строке 8
Entry:          LD HL, Memory.Frame                                             ; строка 0 буфера, начало чётных строк
                LD DE, Memory.Screen + #0020                                    ; строка 8 экрана, левый край полётного вида
                CALL Game.Screen.CopySixtyRows.Entry
                ; вывод нечётных строк, общий цикл выполняется через проваливание
                LD HL, Memory.Frame + #0100                                     ; строка 1 буфера, начало нечётных строк
                LD DE, Memory.Screen + #0120                                    ; строка 9 экрана, левый край полётного вида, далее Game.Screen.CopySixtyRows.Entry без команды перехода
                ASSERT $ == #7FCD
                endmodule
                endmodule
