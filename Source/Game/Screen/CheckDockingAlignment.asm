                module CheckDockingAlignment
; -----------------------------------------
; проверка ориентации и положения относительно стыковочного проёма
; In:
;   IX, объект с координатами и ориентацией
;   байт #D03F, состояние туннеля
; Out:
;   AF, перенос устанавливается при активном туннеле или недопустимом смещении
; Corrupt:
;   AF
; Note:
;   проверяет старшую компоненту оси IX+#1A после удвоения
;   для последующей проверки использует старшие биты младших координат X и Y
;   при (2*orientation) < 4 возвращает перенос от CP без дополнительной обработки
;   точный контракт флагов важен, Z и CY имеют различные значения на ранних выходах
; -----------------------------------------
                ; проверка исходного размещения
                ASSERT $ == #8429
                ; проверка уже начатого стыковочного туннеля
Entry:          LD A, (JumpMode)
                RRCA
                RET C                                                           ; выход, если младший бит состояния туннеля установлен

                ; проверка ориентации продольной оси
                LD A, (IX + FSpaceObject.AxisZ.Z + FSignWord.SignHigh)
                ADD A, A
                CP #04
                RET C                                                           ; выход, если удвоенная компонента ориентации меньше 4

                ; проверка допустимого поперечного смещения
                LD A, (IX + FSpaceObject.X.Fraction)
                AND #C0
                OR (IX + FSpaceObject.Y.Fraction)
                AND #F0
                RET Z                                                           ; выход, если проверяемые биты смещения равны нулю

                SCF
                RET
                ASSERT $ == #8442
                endmodule
                endmodule
