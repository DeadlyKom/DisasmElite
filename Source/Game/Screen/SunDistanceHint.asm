                module Screen
                module SunDistanceHint
; -----------------------------------------
; быстрая оценка старших координат солнца или планеты
; In:
;   вход #8400 выбирает солнце, вход #83FE выбирает планету
; Out:
;   AF, сумма выбранных старших компонент и перенос
; Corrupt:
;   HL, AF
; Note:
;   IX временно заменяется адресом #7107 или #7110 и восстанавливается
;   результат строится из старших байтов X,Y,Z с удвоениями
;   выход по переносу после ADD A,H сохраняет раннее переполнение
;   это дешёвая оценка, она не равна евклидовой длине вектора
; -----------------------------------------
                ; проверка исходного размещения
                ASSERT $ == #8400
; вариант исполнения #8400, LD L,#07
; вариант исполнения #8401, RLCA
Entry:          DB #2E, #07                                                     ; перекрывающиеся команды, байты сохранены буквально
                ; чтение трёх старших компонент с сохранением IX
                LD H, #71
                PUSH IX
                PUSH HL
                POP IX
                LD A, (IX + FCoordinate + FCoordinate + FCoordinate.SignHigh)
                LD L, (IX + FCoordinate + FCoordinate.SignHigh)
                LD H, (IX + FCoordinate.SignHigh)
                POP IX
                ; расчёт быстрой оценки положения без квадратного корня
                ADD HL, HL
                ADD A, A
                ADD A, H
                RET C                                                           ; выход, если промежуточная оценка вышла за восемь битов

                ADD A, L
                RET
                ASSERT $ == #841A
                endmodule
                endmodule
