; -----------------------------------------
; запись граничного байта шкалы с коррекцией маркера
; In:
;   HL, адрес граничного байта
;   BC, C содержит маску
; Out:
;   маска записана, при необходимости предыдущий байт заменён на #01
; Corrupt:
;   AF
; Note:
;   в режиме #8523=1 при маске #80 или #81 предыдущий байт перезаписывается значением #01
;   HL восстанавливается после временного DEC L
;   с #8619 начинается блок состояния построения окружностей, это литеральные данные
; -----------------------------------------
                ; проверка исходного размещения
                ASSERT $ == #8606
                ; запись текущей маски и проверка необходимости продолжения маркера слева
Entry:          LD (HL), C
                LD A, (IndicatorDraw.MarkerMode)
                DEC A
                RET NZ                                                          ; выход, если рисуется обычная полоса

                LD A, C
                AND #FE
                CP #80
                JR Z, MarkerAtEdge                                              ; переход, если маркер занимает старший бит текущего байта

                RET

MarkerAtEdge:   DEC L
                LD (HL), #01
                INC L
                RET
CircleData      EQU $                                                           ; начало сохранённых рабочих данных, исходное размещение
.Reserved       DB #00                                                          ; исходный байт перед параметрами окружности
.OffsetY        DB #00                                                          ; модуль вертикального смещения центра
.OffsetX        DB #1F                                                          ; модуль горизонтального смещения центра
.Flags          DB #0C                                                          ; знаки и признаки диапазона центра, схема в FCircleState
.Radius         DB #46                                                          ; радиус окружности в пикселях
.ClipY          DB #00                                                          ; рабочий модуль Y или расстояние до вертикальной границы
.ClipX          DB #1F                                                          ; рабочий модуль X или расстояние до боковой границы
.ScreenY        DB #60                                                          ; экранная строка центра или начало отсечённой дуги
.ScreenX        DB #61                                                          ; экранный столбец центра
.Cathetus       DB #00                                                          ; катет точки пересечения круга с границей
.SavedSP        DW #CFFC                                                        ; реальный стек до временного заполнения или чтения таблицы
.Radicand       DW #0000                                                        ; подкоренное значение r*r - d*d - входной перенос
.LeftMask       DB #10                                                          ; маска левого края перед заполнением строки
.DirectionDown  DB #01                                                          ; направление дуги, 0 вверх, 1 вниз
.OutlineOnly    DB #01                                                          ; режим окружности, 0 заливка, 1 только контур
.PatchCount     DB #20                                                          ; число байтов патча области обзора
