                module Screen
                module SelectTrafficType
; -----------------------------------------
; уточнение типа случайного корабля по геометрии системы и особым областям
; In:
;   AF, A содержит исходный номер модели
; Out:
;   BC, B содержит итоговый номер модели
; Corrupt:
;   HL, DE, BC, AF
; Note:
;   номера 9 и 15, номера меньше 7 и номера от 18 возвращаются без изменения
;   для остальных #8E64 проверяет оценки координат солнца и планеты, сброшенный перенос выбирает тип 6
;   проверки #D67A и #EC40 ограничивают появление особых кораблей текущей системой
;   INC A после первого вызова одновременно служит встроенным порогом #3C
;   ветвь #801A заменяет тип на 15, остальные ветви сохраняют исходный B
; -----------------------------------------
                ; проверка исходного размещения
                ASSERT $ == #7FF0
Entry:          LD B, A
                ; проверка типов, для которых замена запрещена
                CP #09
                RET Z                                                           ; выход, если выбран тип 9

                CP #07
                RET C                                                           ; выход, если тип меньше 7

                CP #0F
                RET Z                                                           ; выход, если выбран тип 15

                CP #12
                RET NC                                                          ; выход, если тип не меньше 18

                ; проверка оценок координат светил для замены обычного транспорта
                CALL Game.Circles.CheckBodiesAndRestoreViewport.Entry
                JR C, CheckSpecial                                              ; переход, если проверка геометрии не запросила замену на тип 6

                LD B, #06
                RET

CheckSpecial:   PUSH BC
                ; проверка положения системы и вероятности появления особого корабля
                CALL Game.Text.CheckMissionRegion.Entry
                INC A
                JR NC, KeepType                                                 ; переход, если система не прошла проверку области с порогом #3C
InvasionCall    EQU $ + 1                                                       ; адрес проверки особой области, изменяемый установщиком
                CALL Game.Menus.CheckMissionRegionBand.Entry
                JR NC, ChooseSpecial                                            ; переход, если система находится вне специальной полосы

                LD A, (FlightState.StationZone)
                RRCA
                CALL NC, Game.Combat.NextRandomByte.Entry                       ; вызов, если бит 0 близости станции сброшен, выбор зависит от генератора
                JR C, KeepType                                                  ; переход, если проверка близости или генератор сохранили перенос, тип остаётся прежним

ChooseSpecial:  POP BC
                LD B, #0F
                RET

KeepType:       POP BC
                RET
                ASSERT $ == #8020
                endmodule
                endmodule
