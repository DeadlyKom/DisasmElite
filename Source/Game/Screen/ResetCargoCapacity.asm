                module Screen
                module ResetCargoCapacity
; -----------------------------------------
; установка свободного места по типу грузового отсека
; In:
;   байт #D084, признак увеличенного трюма
; Out:
;   байт #D07C, вместимость в тоннах
; Corrupt:
;   BC, AF
; Note:
;   цикл прибавляет 15 к начальному значению 5 до переполнения B в ноль
;   обычный отсек #00 даёт 20 тонн, увеличенный #FF даёт 35 тонн
;   #80D1..#80D2 являются словом сохранённого SP диспетчера, не инструкцией
; -----------------------------------------
                ; проверка исходного размещения
                ASSERT $ == #80C1
                ; расчёт вместимости с исходным кодированием признака #00 или #FF
Entry:          LD A, (State.LargeCargo)
                LD B, A
                DEC B
                LD A, #05
SumCapacity:    ADD A, #0F
                INC B
                JR NZ, SumCapacity                                              ; переход, если счётчик ещё не обнулился

                LD (State.FreeCargo), A
                RET
MenuStack       EQU $                                                           ; начало сохранённых рабочих данных, исходное размещение
.SavedSP        DW #FFFC                                                        ; реальный стек, сохранённый перед вызовом меню
                ASSERT $ == #80D3
                endmodule
                endmodule
