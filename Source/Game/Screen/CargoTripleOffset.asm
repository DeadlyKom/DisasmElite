                module Screen
                module CargoTripleOffset
; -----------------------------------------
; расчёт смещения трёхбайтной записи для индекса товара
; In:
;   AF, A содержит индекс
; Out:
;   при A < 14 возвращается A * 3
;   иначе HL = LegacyPrice и A = 0
; Corrupt:
;   HL, BC, AF
; Note:
;   B используется для сложения 2*A + A
;   выбор LegacyPrice для старших индексов является поведением оригинала и не заменяется адресом RAM
; -----------------------------------------
                ; проверка исходного размещения
                ASSERT $ == #80B4
                ; проверка диапазона индексов с трёхбайтной записью
Entry:          CP #0E
                JR NC, SpecialCargo                                             ; переход, если индекс не меньше 14

                ; расчёт тройного смещения
                LD B, A
                ADD A, A
                ADD A, B
                RET

SpecialCargo:   LD HL, LegacyPrice                                              ; исходное обращение к ROM для индекса цены от 14
                XOR A
                RET

                ASSERT $ == #80C1
                endmodule
                endmodule
