                module Screen
                module RestoreCompassBackground
; -----------------------------------------
; восстановление фона компаса размером 24 на 23 пикселя
; In:
;   не требуются
; Out:
;   23 строки по 3 байта записаны начиная с #5035
; Corrupt:
;   HL, DE, BC, AF
; Note:
;   первые строки читаются последовательно из #8491
;   после перехода C через нуль источник каждой строки откатывается на шесть байтов
;   так нижняя часть получается повторным чтением 11 строк в обратном порядке
;   начальное B=24 уменьшается не только DJNZ, но и заёмом C при двенадцатой строке
;   поэтому число выведенных строк равно 23, а не 24
;   указатель экрана переходит через NextScanline, промежутки между строками не копируются
; -----------------------------------------
                ; проверка исходного размещения
                ASSERT $ == #84B5
                ; подготовка источника строк и адреса компаса
Entry:          LD HL, CompassBitmap
                LD DE, Memory.Screen + #1035                                    ; фон компаса, строка 136, байт 21
                LD BC, #1823
CopyBackRow:    LDI
                LDI
                LDI
                ; проверка перехода к зеркальному чтению строк фона
                BIT 7, C
                JR Z, NextScreenRow                                             ; переход, если источник ещё читается вперёд

                PUSH BC
                LD BC, #FFFA
                ADD HL, BC
                POP BC
                ; расчёт адреса следующей строки экрана
NextScreenRow:  DEC E
                DEC E
                DEC E
                EX DE, HL
                CALL Game.Screen.NextScanline.Entry
                EX DE, HL
                DJNZ CopyBackRow

                RET
                ASSERT $ == #84D9
                endmodule
                endmodule
