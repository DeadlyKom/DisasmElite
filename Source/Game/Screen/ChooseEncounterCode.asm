                module Screen
                module ChooseEncounterCode
; -----------------------------------------
; выбор кода события по миссии и старшему биту записи
; In:
;   HL, адрес проверяемого флага
; Out:
;   AF, A равен #D4 или #0D, либо снят один адрес возврата
; Corrupt:
;   HL, AF
; Note:
;   при State.Mission3=4 возвращается #D4
;   иначе при сброшенном бите 7 по HL возвращается #0D
;   при установленном бите 7 POP HL отменяет возврат в непосредственного вызывающего
; -----------------------------------------
                ; проверка исходного размещения
                ASSERT $ == #841A
                ; проверка специального состояния третьей миссии
                ; миссии 3, 7 INVASION, состояние 4 выбирает специальный код события
                ; описание в Docs/Manual.md, раздел mission-3, mission-7-invasion
Entry:          LD A, (State.Mission3)
                CP #04
                LD A, #D4
                RET Z                                                           ; выход, если состояние третьей миссии равно 4

                ; проверка разрешения обычного кода события
                BIT 7, (HL)
                LD A, #0D
                RET Z                                                           ; выход, если старший бит записи сброшен

                POP HL
                RET

                ASSERT $ == #8429
                endmodule
                endmodule
