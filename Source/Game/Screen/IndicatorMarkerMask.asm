                module Screen
                module IndicatorMarkerMask
; -----------------------------------------
; расчёт маски маркера внутри текущего байта шкалы
; In:
;   BC, B содержит остаток величины от деления на 8
; Out:
;   продолжение #857E с готовой маской в A
; Corrupt:
;   BC, AF
; Note:
;   для первых двух позиций формируются #80 и #C0
;   для следующих позиций пара единичных битов сдвигается вправо
;   вход используется только из общего построителя шкал с ненулевым остатком
; -----------------------------------------
                ; проверка исходного размещения
                ASSERT $ == #85F5
                ; расчёт однопиксельной или двухпиксельной маски позиции
Entry:          LD A, #80
                DEC B
                JR Z, MarkerReady                                               ; переход, если маркер находится на первой позиции

                SCF
                RRA
                DEC B
                JR Z, MarkerReady                                               ; переход, если маркер находится на второй позиции

ShiftMarker:    SRL A
                DJNZ ShiftMarker

MarkerReady:    JP Game.Screen.DrawIndicatorBar.StoreMask
                ASSERT $ == #8606
                endmodule
                endmodule
