; -----------------------------------------
; перекрывающийся вход оценки положения планеты
; In:
;   координаты планеты #7110
; Out:
;   результат общего хвоста #8402
; Corrupt:
;   HL, AF
; Note:
;   байты #83FE..#8400 образуют LD HL,#2E10
;   вход #8400 декодирует этот же старший байт как LD L,#07
;   путь #83FE продолжает LD H,#71 по #8402 с L=#10, путь #8400 с L=#07
;   промежуточный RLCA по #8401 не влияет на итог, A затем загружается заново
;   перекрытие сохранено байтами, замена обычной последовательностью изменила бы адреса
; -----------------------------------------
                ; проверка исходного размещения
                ASSERT $ == #83FE
; вариант исполнения #83FE, LD HL,#2E10
Entry:          DB #21, #10                                                     ; перекрывающиеся команды, байты сохранены буквально
                ASSERT $ == #8400
                endmodule
