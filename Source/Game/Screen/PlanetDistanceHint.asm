                module PlanetDistanceHint
; -----------------------------------------
; перекрывающийся вход оценки положения планеты
; In:
;   координаты планеты FlightState.Planet
; Out:
;   результат общей части Game.Screen.SunDistanceHint.Entry после выбора младшего байта адреса
; Corrupt:
;   HL, AF
; Note:
;   Entry использует первый байт Game.Screen.SunDistanceHint.Entry как старший операнд LD HL, #2E10
;   вход Game.Screen.SunDistanceHint.Entry декодирует этот же старший байт как LD L,#07
;   оба входа доходят до общей LD H, #71, планетный путь приносит L=#10, солнечный L=#07
;   при планетном входе операнд LD L, #07 исполняется как RLCA, результат A затем заменяется координатой
;   перекрытие сохранено байтами, замена обычной последовательностью изменила бы адреса
; -----------------------------------------
                ; проверка исходного размещения
                ASSERT $ == #83FE
; вариант исполнения Game.Screen.PlanetDistanceHint.Entry, LD HL,#2E10
Entry:          DB #21, #10                                                     ; перекрывающиеся команды, байты сохранены буквально
                ASSERT $ == #8400
                endmodule
                endmodule
