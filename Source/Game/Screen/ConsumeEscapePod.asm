                module Screen
                module ConsumeEscapePod
; -----------------------------------------
; расход спасательной капсулы и сброс ожидаемого счётчика вылета
; In:
;   HL, H=#D0 из обработчика спасательной капсулы
;   AF, A=0 из обработчика
; Out:
;   байт по H:#89 увеличен, LaunchPending получает A
; Corrupt:
;   HL, AF
; Note:
;   низкий байт HL принудительно заменяется на #89, изменяется поле EscapePod
;   при обычной капсуле #FF превращается в 0, расширенная комплектация расходует один заряд
;   A=0 отменяет отложенное увеличение счётчика вылетов в LaunchPending
;   далее CompassBitmap хранится сжатый по строкам фон компаса шириной три байта
;   фон читает Game.Screen.RestoreCompassBackground.Entry, его нельзя дизассемблировать как инструкции
; -----------------------------------------
                ; проверка исходного размещения
                ASSERT $ == #848A
                ; расход одного заряда капсулы и отмена обычного учёта вылета
Entry:          LD L, #89
                INC (HL)
                LD (LaunchPending), A
                RET

CompassBitmap   DB #00, #00, #01, #00, #7E, #01, #01, #81                       ; фон компаса, 12 строк по три байта
                DB #81, #02, #00, #41, #04, #00, #21, #08                       ; исходные байты #8499..#84A0
                DB #00, #11, #10, #00, #09, #10, #00, #09                       ; исходные байты #84A1..#84A8
                DB #20, #00, #05, #20, #00, #05, #20, #00                       ; исходные байты #84A9..#84B0
                DB #05, #20, #00, #05                                           ; исходные байты #84B1..#84B4
                ASSERT $ == #84B5
                endmodule
                endmodule
