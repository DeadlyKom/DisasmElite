                module ClearFlightBuffer
; -----------------------------------------
; очистка буфера вида и построение прямоугольной рамки
; In:
;   не требуются
; Out:
;   буфер #C000..#CFDF подготовлен для нового кадра
; Corrupt:
;   HL, DE, BC, AF
; Note:
;   сначала создаются образцы горизонтальной границы и пустой строки с боковыми границами
;   LDDR размножает образцы с перекрытием исходного и выходного диапазонов
;   видимые строки 0 и 119 содержат #FF в байтах 1..30
;   промежуточные строки содержат #80 в байте 1 и #01 в байте 30
;   крайние байты 0 и 31 обнулены, ширина рамки составляет 240 пикселей
;   DI защищает буфер во время заполнения, на выходе EI включается безусловно
; -----------------------------------------
                ; проверка исходного размещения
                ASSERT $ == #8080
Entry:          DI
                ; создание образца нижней горизонтальной границы
                LD BC, #001E
                LD HL, Memory.Frame + #0FDF                                     ; последний байт строки 119 буфера, начало обратного заполнения
                PUSH HL
                LD (HL), B
                DEC HL
                LD (HL), #FF
                LD D, H
                LD E, L
                DEC DE
                LDDR
                LD (HL), B
                DEC HL
                LD (HL), B
                ; создание образца пустой строки с двумя вертикальными границами
                PUSH HL
                DEC HL
                LD (HL), #01
                DEC HL
                LD (HL), B
                LD E, L
                DEC DE
                LD C, #1C
                LDDR
                LD (HL), #80
                DEC HL
                LD (HL), B
                EX DE, HL
                DEC DE
                POP HL
                ; размножение заполнения по буферу обратным перекрывающимся копированием
                LD BC, #0FA0
                LDDR
                ; восстановление верхней горизонтальной границы
                EX DE, HL
                POP HL
                LD C, #1F
                LDDR
                EI
                RET
                ASSERT $ == #80B4
                endmodule
                endmodule
