                module RepeatEnergyRecovery
; -----------------------------------------
; повторное восстановление энергии до переполнения счётчика A
; In:
;   AF, A задаёт 256-A повторений обработчика #9AE2
; Out:
;   AF, A равен нулю
; Corrupt:
;   HL, DE, BC, AF
; Note:
;   PUSH AF сохраняет счётчик через восстановление энергии #9AE2
;   обработчик увеличивает первый неполный банк, затем пополняет щиты
;   A=0 задаёт 256 повторений, а не нулевое число вызовов
;   вызывающий код #9ADB после возврата дополнительно проваливается в #9AE2
; -----------------------------------------
                ; проверка исходного размещения
                ASSERT $ == #8481
                ; восстановление очередной единицы энергии с сохранением счётчика
Entry:          PUSH AF
                CALL Game.Combat.RecoverOneEnergyUnit.Entry
                POP AF
                INC A
                JR NZ, Game.Screen.RepeatEnergyRecovery.Entry                   ; переход, если счётчик ещё не переполнился в ноль

                RET
                ASSERT $ == #848A
                endmodule
                endmodule
