                module PrintMissileStock
; -----------------------------------------
; совместимый вход печати запаса ракет
; исходный диапазон #9C18..#9C1B
; In:
;   память D083, количество ракет
; Out:
;   обновлены четыре позиции индикатора
; Corrupt:
;   HL, DE, BC, AF
; Note:
; Безусловный переход в 9B1B. Байт 9C1B после JP используется счётчиком спасательной капсулы.
; -----------------------------------------
                ; проверка исходного начала фрагмента
                ASSERT $ == #9C18
                ; переход к общему выводу запаса ракет
Entry:          JP @Game.Combat.SetIndicatorAndPrintMissileStock.PrintStock
                ; данные обратного отсчёта спасательной капсулы
MissileCount    DB #00                                                          ; сохранённое число ракет для обновления панели
                ; проверка исходного конца фрагмента
                ASSERT $ == #9C1C
                endmodule
                endmodule
