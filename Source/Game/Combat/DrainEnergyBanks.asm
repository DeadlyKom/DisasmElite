                module Combat
                module DrainEnergyBanks
; -----------------------------------------
; расход энергии по четырём банкам с обработкой гибели
; исходный диапазон #9A8D..#9AA6
; In:
;   BC, B число шагов, C расход за шаг
; Out:
;   банки 70F6/70F8/70FA/70FC уменьшены
;   711F получает 1 при исчерпании
; Corrupt:
;   HL, DE, BC, AF
; Note:
; Расход начинается с нижнего банка. При заёме банк обнуляется, следующий проверяется полным C.
; Счётчик B уменьшается только после успешного вычитания, остаток заёма отдельно не переносится.
; -----------------------------------------
                ; проверка исходного начала фрагмента
                ASSERT $ == #9A8D
                ; поиск первого банка и подготовка четырёх уровней
Entry:          LD HL, GaugeState + FGaugeState.Energy1.Current
                LD D, #04
                ; расчёт расхода с переходом к следующему банку при нехватке
DrainBank:      LD A, (HL)
                SUB C
                JR NC, StoreBank                                                ; переход, если текущий банк содержит достаточно энергии для полного расхода C

                LD (HL), #00
                INC HL
                INC HL
                DEC D
                JR NZ, DrainBank                                                ; переход, если после опустошения банка остались другие банки

                ; установка признака гибели после исчерпания всех банков
                LD A, #01
                LD (FlightState.PlayerDead), A
                RET

StoreBank:      LD (HL), A
                DJNZ DrainBank

                RET
                ; проверка исходного конца фрагмента
                ASSERT $ == #9AA7
                endmodule
                endmodule
