                module Combat
                module RecoverPlayerEnergy
; -----------------------------------------
; восстановление энергии с учётом установленного энергоблока
; исходный диапазон #9ADB..#9AE1
; In:
;   память D08B, код энергоблока
; Out:
;   энергия и щиты восстановлены общим обработчиком
; Corrupt:
;   HL, DE, BC, AF
; Note:
; При D08B=0 выполняется один проход через последующий 9AE2.
; При ненулевом D08B процедура 8481 делает 256-D08B проходов и возвращает сюда для ещё одного.
; Кодировка улучшенного блока использует переполнение восьмибитного счётчика.
; -----------------------------------------
                ; проверка исходного начала фрагмента
                ASSERT $ == #9ADB
                ; проверка энергоблока перед дополнительным восстановлением
Entry:          LD A, (State.EnergyUnit)
                AND A
                CALL NZ, Game.Screen.RepeatEnergyRecovery.Entry                 ; вызов процедуры, если установлен ненулевой код энергоблока и нужны дополнительные проходы
                ; проверка исходного конца фрагмента
                ASSERT $ == #9AE2
                endmodule
                endmodule
