                module Combat
                module CalculateFuelPurchasePrice
; -----------------------------------------
; расчёт цены недостающего топлива
; исходный диапазон #9B83..#9BA6
; In:
;   память State.Fuel, текущее топливо
;   память State.MarketRandom/State.SystemSeed, параметры цены
; Out:
;   HL, адрес State.MarketStock
;   память EquipmentTable.FuelPrice, рассчитанная цена
; Corrupt:
;   DE, BC, AF
; Note:
; Количество недостающего топлива равно #46-State.Fuel.
; Коэффициент равен (State.MarketRandom OR State.SystemSeed OR #80), цена берётся из старшего байта их произведения.
; При полном баке записывается ноль. Три хвостовых байта сохраняют данные старого образа.
; -----------------------------------------
                ; проверка исходного начала фрагмента
                ASSERT $ == #9B83
                ; расчёт недостающего топлива и коэффициента цены
Entry:          LD HL, State.Fuel
                LD A, #46
                SUB (HL)
                JR Z, StorePrice                                                ; переход, если бак полностью заправлен и цена равна нулю

                LD B, A
                LD A, (State.MarketRandom)
                LD L, #96
                OR (HL)
                OR #80
                LD E, A
                LD D, #00
                LD H, D
                LD L, D
                ; расчёт произведения количества и коэффициента
MultiplyPrice:  ADD HL, DE
                DJNZ MultiplyPrice

                LD A, H
StorePrice:     LD (EquipmentTable.FuelPrice), A
                LD HL, State.MarketStock
                RET

                ; сохранённые байты между процедурами

; -----------------------------------------
; сохранённое сложение указателя и смещения
; In:
;   HL, исходный указатель
;   DE, смещение
; Out:
;   HL, сумма по модулю 65536
;   AF, CY содержит перенос сложения
; Corrupt:
;   HL, AF
; Note:
;   сохранённая процедура, прямые входящие переходы не найдены
;   DE, BC, A, знаковый и нулевой флаги сохраняются
; -----------------------------------------
LegacyAdd:      ; сохранённое сложение указателя и смещения
                ADD HL, DE
                RET

                ; одиночный остаток кода #D4, CALL NC поглотил бы два байта следующей процедуры
                ; отдельный вход в эту сохранённую последовательность не подтверждён
                DB #D4
                ; проверка исходного конца фрагмента
                ASSERT $ == #9BA7
                endmodule
                endmodule
