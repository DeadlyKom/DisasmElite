                module Combat
                module SetIndicatorAndPrintMissileStock
; -----------------------------------------
; установка атрибута индикатора и отдельная печать запаса ракет
; исходный диапазон #9B14..#9B40
; In:
;   HL, адрес атрибута
;   AF, A содержит состояние для основного входа
;   память D083, запас ракет для отдельного 9B1B
; Out:
;   байт атрибута равен 7 при ненулевом состоянии, иначе 0
;   для 9B1B напечатаны четыре позиции ракет
; Corrupt:
;   AF, для 9B1B также HL, DE, BC
; Note:
; Первый RET завершает простой индикатор. 9B1B является отдельным входом печати запаса ракет.
; Устанавливает текстовую позицию (2,23), временно заменяет байт по D04B на 0, после печати пишет A9.
; Каждая из четырёх позиций получает символ #25 при наличии ракеты, иначе #40.
; -----------------------------------------
                ; проверка исходного начала фрагмента
                ASSERT $ == #9B14
                ; проверка состояния и запись атрибута индикатора
Entry:          AND A
                JR Z, StoreIndicator                                            ; переход, если состояние нулевое и атрибут остаётся чёрным

                LD A, #07
StoreIndicator: LD (HL), A
                RET

                ; отдельный вход печати четырёх позиций ракет
PrintStock:     LD HL, #1702
                LD (TextColumn), HL
                LD HL, (GlyphPatch)
                LD (HL), #00
                PUSH HL
                LD A, (State.Missiles)
                LD C, A
                LD B, #04
                ; проверка наличия очередной ракеты перед выбором символа
MissileSlot:    DEC C
                PUSH BC
                BIT 7, C
                LD A, #25
                JR Z, PrintMissile                                              ; переход, если счётчик оставшихся ракет ещё не отрицателен

                LD A, #40
PrintMissile:   CALL Game.Text.PrintMainToken.Entry
                POP BC
                DJNZ MissileSlot

                POP HL
                LD (HL), #A9
                RET
                ; проверка исходного конца фрагмента
                ASSERT $ == #9B41
                endmodule
                endmodule
