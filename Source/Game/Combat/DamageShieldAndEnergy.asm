                module Combat
                module DamageShieldAndEnergy
; -----------------------------------------
; применение урона к щиту с передачей расхода энергии
; исходный диапазон #9AA7..#9ADA
; In:
;   HL, адрес переднего либо заднего щита
;   AF, A величина урона
; Out:
;   щит и при необходимости банки энергии уменьшены
; Corrupt:
;   HL, DE, BC, AF
; Note:
; При нулевом уроне уменьшается накопитель пробитий #9ADA.
; Урон применяется четырьмя повторениями, при исчерпании щита оставшееся число повторений переходит на энергию.
; Урон не ниже #46 и накопленные пробития от #0D вызывают повреждение оборудования D0F3.
; #9ADA после хвостового перехода является рабочим счётчиком пробитий.
; -----------------------------------------
                ; проверка исходного начала фрагмента
                ASSERT $ == #9AA7
                ; проверка наличия урона и затухание накопителя пробитий
Entry:          LD C, A
                AND A
                JR NZ, DamageGear                                               ; переход, если величина урона ненулевая

                LD HL, ShieldHits
                LD A, (HL)
                AND A
                RET Z                                                           ; выход, если накопитель пробитий уже нулевой

                DEC (HL)
                RET

                ; проверка сильного попадания для повреждения оборудования
DamageGear:     PUSH BC
                PUSH HL
                CP #46
                CALL NC, Game.Missions.DispatchEquipmentDamage.Entry            ; вызов процедуры, если величина урона не меньше #46
                POP HL
                POP BC
                ; расчёт четырёх повторений урона щиту
                LD B, #04
DamageShield:   LD A, (HL)
                SUB C
                JR C, ShieldEmpty                                               ; переход, если щит исчерпан текущим вычитанием

                LD (HL), A
                DJNZ DamageShield

                RET

                ; передача оставшегося расхода на банки энергии
ShieldEmpty:    LD (HL), #00
                DEC B
                RET Z                                                           ; выход, если после пробития не осталось повторений расхода

                CALL Game.Combat.DrainEnergyBanks.Entry
                LD HL, ShieldHits
                LD A, (HL)
                ADD A, #05
                LD (HL), A
                CP #0D
                RET C                                                           ; выход, если накопитель пробитий ещё меньше #0D

                JP Game.Missions.DispatchEquipmentDamage.Entry
                ; данные накопленного пробития щитов
ShieldHits      DB #00                                                          ; накопитель пробитий щитов, прибавка 5, повреждение оборудования при значении от 13
                ; проверка исходного конца фрагмента
                ASSERT $ == #9ADB
                endmodule
                endmodule
