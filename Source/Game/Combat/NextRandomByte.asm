                module NextRandomByte
; -----------------------------------------
; обновление двухбайтового генератора псевдослучайных чисел
; исходный диапазон #B799..#B7AB
; In:
;   AF, входной перенос участвует в рекуррентном вычислении
;   память B7AA/B7AB, состояние генератора
; Out:
;   HL, BC, исходные значения
;   AF, A содержит новое случайное значение
; Corrupt:
;   нет дополнительных регистров
; Note:
; Пусть состояние H:L, тогда B=(2*H+перенос) mod256, H=(B+L+перенос_удвоения) mod256, L=B.
; Перенос второго сложения возвращается вызывающему коду и может влиять на следующий вызов.
; Начальное состояние хранится после RET как байты #47,#3D.
; -----------------------------------------
                ; проверка исходного начала фрагмента
                ASSERT $ == #B799
                ; расчёт нового состояния генератора с участием входного переноса
Entry:          PUSH HL
                PUSH BC
                LD HL, (RandomState)
                LD A, H
                ADC A, A
                LD B, A
                ADC A, L
                LD H, A
                LD L, B
                LD (RandomState), HL
                POP BC
                POP HL
                RET
                ; данные двухбайтового состояния генератора
RandomSeed      DW #3D47                                                        ; 16-битное состояние генератора NextRandomByte
                ; проверка исходного конца фрагмента
                ASSERT $ == #B7AC
                endmodule
                endmodule
