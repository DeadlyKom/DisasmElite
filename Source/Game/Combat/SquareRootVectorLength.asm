                module SquareRootVectorLength
; -----------------------------------------
; совместимый вход приближённого квадратного корня
; исходный диапазон #9C86..#9C88
; In:
;   HL, подкоренное значение
; Out:
;   HL, приближённый корень в формате игры
; Corrupt:
;   DE, BC, AF
; Note:
; Хвостовой переход в общий SquareRoot, сохраняет исходную приближённую арифметику.
; -----------------------------------------
                ; проверка исходного начала фрагмента
                ASSERT $ == #9C86
                ; переход к общей процедуре квадратного корня
Entry:          JP Game.Math.SquareRoot

                ; проверка исходного конца фрагмента
                ASSERT $ == #9C89
                endmodule
