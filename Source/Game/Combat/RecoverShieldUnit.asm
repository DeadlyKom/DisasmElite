                module Combat
                module RecoverShieldUnit
; -----------------------------------------
; увеличение одного щита с ограничением A0
; исходный диапазон #9AFB..#9B00
; In:
;   HL, адрес щита
; Out:
;   байт щита увеличен до предела A0
; Corrupt:
;   AF
; Note:
; Вызывается для переднего щита и достигается последовательным потоком для заднего.
; -----------------------------------------
                ; проверка исходного начала фрагмента
                ASSERT $ == #9AFB
                ; проверка предела заряда перед восстановлением щита
Entry:          LD A, (HL)
                CP #A0
                RET Z                                                           ; выход, если щит уже полностью заряжен

                INC (HL)
                RET

                ; проверка исходного конца фрагмента
                ASSERT $ == #9B01
                endmodule
                endmodule
