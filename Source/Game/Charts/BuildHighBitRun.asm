                module Charts
                module BuildHighBitRun
; -----------------------------------------
; Построение маски из старших единичных битов
; исходный диапазон #E611..#E618
; In:
;   DE, E = длина 1..8
; Out:
;   E = FF с обнулёнными младшими 8-длина битами, A=E
; Corrupt:
;   DE, AF
; Note:
;   Повторяет SCF/RRA, перед циклом A=0, вход 0 не является штатной длиной
; -----------------------------------------
                ; проверка исходного начала фрагмента
                ASSERT $ == #E611
                ; старшие E битов устанавливаются последовательными сдвигами с переносом 1
Entry:          XOR A
NextBit:        SCF
                RRA
                DEC E
                JR NZ, NextBit                                                  ; переход, если остались разряды маски старших битов, выполнить следующий сдвиг

                LD E, A
                RET
                ; проверка исходного конца фрагмента
                ASSERT $ == #E619
                endmodule
                endmodule
