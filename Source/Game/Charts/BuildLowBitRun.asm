                module BuildLowBitRun
; -----------------------------------------
; Построение маски из младших единичных битов
; исходный диапазон #E619..#E620
; In:
;   DE, D = длина 1..8
; Out:
;   D=(1<<длина)-1, A=D
; Corrupt:
;   DE, AF
; Note:
;   Повторяет SCF/RLA, остальные компоненты DE сохраняются
; -----------------------------------------
                ; проверка исходного начала фрагмента
                ASSERT $ == #E619
                ; младшие D битов устанавливаются последовательными сдвигами с переносом 1
Entry:          XOR A
NextBit:        SCF
                RLA
                DEC D
                JR NZ, NextBit                                                  ; переход, если остались разряды маски младших битов, выполнить следующий сдвиг

                LD D, A
                RET
                ; проверка исходного конца фрагмента
                ASSERT $ == #E621
                endmodule
                endmodule
