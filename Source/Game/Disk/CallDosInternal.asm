                module Disk
                module CallDosInternal
; -----------------------------------------
; Шлюз к внутренней процедуре TR-DOS
; исходный диапазон #DA1A..#DA20
; In:
;   IX = адрес в ROM TR-DOS, стек содержит адрес возврата
; Out:
;   Управление возвращает TR-DOS
; Corrupt:
;   По контракту ROM-процедуры
; Note:
;   PUSH IX перед переходом Rom.CallDosStack передаёт адрес ПЗУ через стек, после JP сохранены два байта данных
; -----------------------------------------
                ; проверка исходного начала фрагмента
                ASSERT $ == #DA1A
                ; вызов внутреннего адреса TR-DOS из IX с восстановлением контекста вызова
Entry:          PUSH IX
                JP Rom.CallDosStack

                ; сохранённые нулевые байты после шлюза TR-DOS
                DB #00, #00                                                     ; #DA1F..#DA20
                ; проверка исходного конца фрагмента
                ASSERT $ == #DA21
                endmodule
                endmodule
