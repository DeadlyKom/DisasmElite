                module ReactionOnPrivateStack
; -----------------------------------------
; Вызов реакции объекта на отдельном стеке
; исходный диапазон #DA21..#DA2E
; In:
;   Регистры по контракту A2C0
; Out:
;   Результат A2C0, исходный SP восстановлен
; Corrupt:
;   HL, DE, BC, AF, IX, IY
; Note:
;   Сохраняет SP в операнд DA2C, временно использует 4220, прерывания самостоятельно не
;   запрещает, не допускает повторного входа
; -----------------------------------------
                ; проверка исходного начала фрагмента
                ASSERT $ == #DA21
                ; переключение на отдельный стек вокруг реакции игрового объекта
Entry:          LD (ReactionStack), SP
                LD SP, Memory.Screen + #0220                                    ; частный стек реакции объекта в экранной памяти
                CALL Game.Motion.ProcessObjectEnergyAndTactics.Entry
SavedSP         EQU $ + 1                                                       ; сохранённый SP в операнде восстановления стека
                LD SP, #0000
                RET
                ; проверка исходного конца фрагмента
                ASSERT $ == #DA2F
                endmodule
                endmodule
