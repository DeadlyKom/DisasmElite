                module PrintInlineToken
; -----------------------------------------
; Печать токена, записанного непосредственно после CALL
; исходный диапазон #D421..#D424
; In:
;   Стек содержит адрес байта токена
; Out:
;   Адрес возврата увеличен на 1, токен обработан D425
; Corrupt:
;   HL, DE, BC, AF
; Note:
;   POP HL читает адрес возврата, байт передаётся в A и обновлённый адрес возвращается на стек,
;   обычный JP на этот вход недопустим без соответствующего стека
; -----------------------------------------
                ; проверка исходного начала фрагмента
                ASSERT $ == #D421
                ; адрес возврата снимается со стека, байт токена читается из потока, возврат увеличивается на
                ; один
Entry:          POP HL
                LD A, (HL)
                INC HL
                PUSH HL
                ; проверка исходного конца фрагмента
                ASSERT $ == #D425
                endmodule
                endmodule
