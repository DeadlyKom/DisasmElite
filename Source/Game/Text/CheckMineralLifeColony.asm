                module Text
                module CheckMineralLifeColony
; -----------------------------------------
; Проверка жизнеспособности колонии MINERAL LIFE
; исходный диапазон #D5B4..#D5CA
; In:
;   State.MineralLife = состояние колонии, State.Cargo + FGoods.Minerals = количество минералов в тоннах
; Out:
;   AF, A=0 и Z=1 для живой колонии, A=FF при отсутствии, A=FE после гибели малой колонии
; Corrupt:
;   AF
; Note:
;   встроенное руководство, миссия 4 MINERAL LIFE, сопоставлено с полями груза и ценой #2710
;   бит 7 State.MineralLife немедленно возвращает C=1, нулевое поле через DEC A возвращает FF, активная
;   колония требует не меньше трёх тонн в поле State.Cargo + FGoods.Minerals
;   при нехватке минералов State.MineralLife получает FF, уцелевшие 0..2 тонны становятся обычным товаром
; -----------------------------------------
                ; проверка исходного начала фрагмента
                ASSERT $ == #D5B4
                ; миссия 4 MINERAL LIFE, проверка жизнеспособности колонии
                ; описание в Docs/Manual.md, раздел mission-4
                ; проверка живой колонии минералов, старший бит состояния означает недоступность
Entry:          LD A, (State.MineralLife)
                RLC A                                                           ; перенос получает MIN_BLOCK_BIT, оставшаяся часть проверяется на нуль
                RET C                                                           ; выход, если бит 7 состояния MINERAL LIFE установлен, колония недоступна

                JR Z, AbsentResult                                              ; переход, если состояние MINERAL LIFE нулевое, вернуть FF без создания колонии

                ; колония сохраняется только при наличии не менее трёх тонн минералов
                LD A, (State.Cargo + FGoods.Minerals)
                CP #03
                JR C, KillColony                                                ; переход, если минералов меньше трёх тонн, уничтожить колонию и пометить отсеки

                XOR A
                RET

                ; уничтожение малой колонии, FF запрещает повторную колонизацию до замены отсеков
KillColony:     SBC A, A
                LD (State.MineralLife), A
AbsentResult:   DEC A
                RET

                ; проверка исходного конца фрагмента
                ASSERT $ == #D5CB
                endmodule
                endmodule
