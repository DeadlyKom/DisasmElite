                module Text
                module FillInnerAttributeRow
; -----------------------------------------
; Заполнение внутренней части строки атрибутов
; исходный диапазон #D554..#D55E
; In:
;   HL = начало 30 байтной области, AF, A = атрибут
; Out:
;   Записано 30 байт, HL увеличен на 32, B=0
; Corrupt:
;   HL, BC
; Note:
;   IgnoreToken содержит отдельный RET, после него сохранены два байта
; -----------------------------------------
                ; проверка исходного начала фрагмента
                ASSERT $ == #D554
                ; заполнение 30 внутренних атрибутов без изменения крайних рамочных ячеек
Entry:          LD B, #1E
                CALL Game.Text.FillBytes.Entry
                INC HL
                INC HL
                RET

                ; пустой обработчик управляющей команды текста
IgnoreToken:    RET

                ; сохранённые нулевые байты после пустого текстового обработчика
                DB #00, #00                                                     ; #D55D..#D55E
                ; проверка исходного конца фрагмента
                ASSERT $ == #D55F
                endmodule
                endmodule
