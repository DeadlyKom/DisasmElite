                module DrawFullWidthRule
; -----------------------------------------
; Горизонтальная сплошная линия шириной 256 пикселей
; исходный диапазон #D55F..#D562
; In:
;   HL = начало пиксельной строки
; Out:
;   32 байта заполнены FF, HL увеличен на 32
; Corrupt:
;   HL, BC, AF
; Note:
;   Инициализирует A=FF, B=32 и использует общий цикл D563
; -----------------------------------------
                ; проверка исходного начала фрагмента
                ASSERT $ == #D55F
                ; сплошная горизонталь использует тот же цикл заполнения с длиной 32 байта
Entry:          LD A, #FF
                LD B, #20
                ; проверка исходного конца фрагмента
                ASSERT $ == #D563
                endmodule
                endmodule
