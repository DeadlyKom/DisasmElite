                module Text
                module FillBytes
; -----------------------------------------
; Заполнение последовательной области памяти
; исходный диапазон #D563..#D567
; In:
;   HL = адрес, BC, B = длина от 1 до 256, AF, A = заполнитель
; Out:
;   HL увеличен на длину, B=0, A сохранён
; Corrupt:
;   HL, BC
; Note:
;   DJNZ при исходном B=0 выполняет 256 записей, флаги инструкция LD/INC HL/DJNZ не меняет
; -----------------------------------------
                ; проверка исходного начала фрагмента
                ASSERT $ == #D563
                ; общий цикл заполнения B байтов значением A с продвижением HL
Entry:          LD (HL), A
                INC HL
                DJNZ Game.Text.FillBytes.Entry

                RET

                ; проверка исходного конца фрагмента
                ASSERT $ == #D568
                endmodule
                endmodule
