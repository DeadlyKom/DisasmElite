                module Text
                module PrintMainToken
; -----------------------------------------
; Рекурсивное раскрытие токенов основной текстовой таблицы
; исходный диапазон #D425..#D45E
; In:
;   AF, A = символ, управляющий код или токен, F11A = адрес таблицы
; Out:
;   Текст выведен с обновлением курсора и регистра
; Corrupt:
;   HL, DE, BC, AF
; Note:
;   Коды 0..13 идут в диспетчер D7E2, 14..31 становятся индексами+72, 20..5F являются символами,
;   60..7F индексами сообщений, 80..9F слогами FDB3, A0..FF индексами A-A0, поиск сообщения
;   пропускает нулевые разделители CPIR, содержимое раскрывается рекурсивно
; -----------------------------------------
                ; проверка исходного начала фрагмента
                ASSERT $ == #D425
                ; коды 00..1F задают форматирование, 20..5F символы, остальные раскрывают токены и слоги
Entry:          CP #0E
                JP C, Game.Text.DrawProjectedSunAndTextDispatch.MainCommand     ; переход, если код меньше 0E, выполнить управляющую команду основной таблицы

                CP #20
                JP C, ExtendToken                                               ; переход, если код находится в диапазоне 0E..1F, преобразовать расширенный токен

                CP #60
                JP C, Game.Text.ApplyTextCase.Entry                             ; переход, если код находится в диапазоне 20..5F, вывести печатный символ

                CP #80
                JR C, FindToken                                                 ; переход, если код находится в диапазоне 60..7F, найти строку в таблице токенов

                CP #A0
                JP C, Game.Text.PrintTwoLetterSyllable.MainSyllable             ; переход, если код находится в диапазоне 80..9F, вывести пару букв из таблицы слогов

                SUB #A0
                JR FindToken

ExtendToken:    ADD A, #72
                ; поиск нужной строки в таблице с нулевыми разделителями
FindToken:      LD HL, (MessageTable.Main)
                LD D, A
                INC D
SkipToken:      DEC D
                JP Z, ExpandString                                              ; переход, если счётчик пропуска строк токенов обнулился, раскрыть найденную строку

                LD BC, #FFFF
                XOR A
                CPIR
                JR SkipToken

                ; посимвольное рекурсивное раскрытие выбранного токена с сохранением указателя строки
ExpandString:   LD A, (HL)
                AND A
                RET Z                                                           ; выход, если прочитан нулевой завершитель строки токена

                PUSH HL
                CALL Game.Text.PrintMainToken.Entry
                POP HL
                INC HL
                JR ExpandString
                ; проверка исходного конца фрагмента
                ASSERT $ == #D45F
                endmodule
                endmodule
