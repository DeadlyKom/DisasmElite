                module EquipmentMenuLimit
; -----------------------------------------
; Получение допустимого предела номера оборудования
; исходный диапазон #D8CE..#D8DC
; In:
;   AF, A = введённыйномер, EquipmentWork = обычныйпредел, State.Technology = технология
; Out:
;   A = предел, флаги от последнего сравнения
; Corrupt:
;   AF
; Note:
;   Для ввода 15 проверяет технологию+1 и разрешает особый пункт только при>=15, иначе
;   возвращает обычный EquipmentWork
; -----------------------------------------
                ; проверка исходного начала фрагмента
                ASSERT $ == #D8CE
                ; дополнительный пункт 15 разрешён только при достаточно высокой технологии
Entry:          CP #0F
OrdinaryLimit:  LD A, (EquipmentWork.ItemLimit)
                RET NZ                                                          ; выход, если запрошен не пункт 15, вернуть обычный предел оборудования

                LD A, (State.Technology)
                INC A
                CP #0F
                JR C, OrdinaryLimit                                             ; переход, если технологический уровень плюс один меньше 15, пункт 15 недоступен

                RET

                ; проверка исходного конца фрагмента
                ASSERT $ == #D8DD
                endmodule
                endmodule
