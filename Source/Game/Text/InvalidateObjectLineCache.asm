; -----------------------------------------
; Пометка двух частей кэша объекта недействительными
; исходный диапазон #D7AA..#D7B8
; In:
;   B452 = указатель записи
; Out:
;   Байты[указатель+1] и[указатель+4] равны FF, A=70E3
; Corrupt:
;   HL, AF
; Note:
;   Запись FF принуждает последующий потребитель заново получить соответствующую геометрию
; -----------------------------------------
                ; проверка исходного начала фрагмента
                ASSERT $ == #D7AA
                ; запись признаков недействительности в обе части кэша линий объекта
Entry:          LD HL, (ObjectEffects.Current)
                INC HL
                LD (HL), #FF
                INC HL
                INC HL
                INC HL
                LD (HL), #FF
                LD A, (FlightState.View)
                RET
                ; проверка исходного конца фрагмента
                ASSERT $ == #D7B9
                endmodule
                endmodule
