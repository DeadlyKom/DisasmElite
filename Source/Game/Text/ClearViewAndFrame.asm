                module ClearViewAndFrame
; -----------------------------------------
; Очистка обзорной области и восстановление её рамки
; исходный диапазон #D61D..#D645
; In:
;   Нет параметров
; Out:
;   Пиксели очищены, атрибуты 5820..5B1F равны 7, затем рамка и курсор
; Corrupt:
;   HL, DE, BC, AF, IX
; Note:
;   DI охватывает очистку bitmap и атрибутов, цикл начинается 4200 и движется по экранным
;   строкам через 8445, после EI исполнение продолжается D646, процедура не сохраняет прежнее
;   состояние IFF
; -----------------------------------------
                ; проверка исходного начала фрагмента
                ASSERT $ == #D61D
                ; очистка пикселей внутреннего окна с сохранением границы
Entry:          DI
                LD HL, Memory.Screen + #0200
ClearScanline:  PUSH HL
                LD BC, #2000
ClearByte:      LD (HL), C
                INC HL
                DJNZ ClearByte

                POP HL
                INC H
                LD A, H
                AND #07
                CALL Z, Game.Screen.NextCharacterRow.Entry                      ; вызов, если старшая часть адреса стала кратна восьми, перейти к следующей символьной строке
                LD A, H
                CP #58
                JR NZ, ClearScanline                                            ; переход, если старшая часть адреса ещё не достигла 58, продолжить очистку окна

                LD L, #20
                LD D, H
                LD E, L
                INC DE
                LD BC, #02FF
                LD (HL), #07
                ; заполнение атрибутов окна значением 7 из первого байта
                LDIR
                NOP
                NOP
                NOP
                EI
                ; проверка исходного конца фрагмента
                ASSERT $ == #D646
                endmodule
                endmodule
