                module CheckObjectRandomGate
; -----------------------------------------
; Вероятностный фильтр действия объекта
; исходный диапазон #D60B..#D61C
; In:
;   IX, основной слот объекта
;   IY, заголовок модели, переданный InitializeObject
;   State.Rating + 1, часть рейтинга
; Out:
;   A=0 при отказе либо маскированное значение
; Corrupt:
;   HL, DE, BC, AF
; Note:
;   два младших бита результата Game.Combat.NextRandomByte.Entry дают отказ при 0, иначе старший байт State.Rating объединяется через OR с байтом за записью по IX + FSpaceObject
;   результат ограничивается маской FModel.LaunchMask модели по IY, все операнды формулы являются прочитанными значениями байтов
;   IX+FSpaceObject читает байт за границей слота, его смысл зависит от положения слота
;   после RET сохранено отдельное слово #CFF8, подтверждённого потребителя не найдено
; -----------------------------------------
                ; проверка исходного начала фрагмента
                ASSERT $ == #D60B
                ; случайный двухбитовый фильтр допуска перед основной реакцией объекта
Entry:          CALL Game.Combat.NextRandomByte.Entry
                AND #03
                RET Z                                                           ; выход, если два младших случайных бита нулевые, действие объекта отменяется

                LD A, (State.Rating + 1)
                OR (IX+FSpaceObject)
                AND (IY+FModel.LaunchMask)
                RET

                ; сохранённое слово CFF8 после вероятностной проверки
                DB #F8, #CF                                                     ; #D61B..#D61C
                ; проверка исходного конца фрагмента
                ASSERT $ == #D61D
                endmodule
                endmodule
