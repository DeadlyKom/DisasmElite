                module Circles
                module CrossCircleCharacterRowUp
; -----------------------------------------
; переход вверх через границу восьмистрочного блока
; исходный диапазон #8DF3..#8E07
; смысловое имя CrossCircleCharacterRowUp
; In: H уже уменьшен, L/E — два края одной строки
; Out: L/E уменьшены на 32, H при необходимости увеличен на 8
; Corrupt: HL, DE — E, AF
; Заём L означает пересечение трети экрана, H=#BF завершает всю половину
; При достижении границы Game.Circles.CrossCircleCharacterRowDown.FinishHalf снимает адрес внутреннего вызова и восстанавливает общий SP
; -----------------------------------------
                ; проверка исходного начала фрагмента
                ASSERT $ == #8DF3
                ; расчёт адресов обоих краёв на предыдущей текстовой строке
Entry:          LD A, E
                SUB #20
                LD E, A
                LD A, L
                SUB #20
                LD L, A
                JR NC, SameThird                                                ; переход, если вычитание 32 из L не дало заёма, компенсировать H на 8

                ; проверка верхнего предела после заёма адреса
UpperLimit      EQU $ + 1                                                       ; верхний предел при переходе на предыдущее знакоместо
                LD A, #BF
                CP H
                JR Z, Game.Circles.CrossCircleCharacterRowDown.FinishHalf       ; переход, если H достиг верхнего предела #BF, завершить всю половину

                RET

                ; компенсация старшего байта без перехода между третями
SameThird:      LD A, H
                ADD A, #08
                LD H, A
                RET

                ; проверка исходного конца фрагмента
                ASSERT $ == #8E08
                endmodule
                endmodule
