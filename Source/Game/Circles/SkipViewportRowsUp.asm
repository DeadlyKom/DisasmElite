                module Circles
                module SkipViewportRowsUp
; -----------------------------------------
; пропуск строк вверх без заполнения пикселей
; исходный диапазон #9004..#9031
; смысловое имя SkipViewportRowsUp
; In: BC — B число строк, AF — A координата Y
; Out: HL — адрес строки после пропуска либо последней допустимой строки
; Corrupt: HL, AF и BC сохраняются
; Начальный X=#F7 нужен только для вычисления адреса, память экрана не меняется
; Переходы через 8 строк учитывают раскладку Spectrum и верхний предел #C0
; Нулевое число строк немедленно возвращает подготовленный адрес
; -----------------------------------------
                ; проверка исходного начала фрагмента
                ASSERT $ == #9004
                ; преобразование начальной строки без заполнения экрана
Entry:          PUSH AF
                PUSH BC
                LD B, A
                LD C, #F7
                CALL Rom.PixelFromA
                SET 7, H
                POP BC
                PUSH BC
                ; проверка числа строк перед пропуском вверх
                DEC B
                INC B
                JR Z, RestoreContext                                            ; переход, если число пропускаемых строк равно нулю

                ; переход на строку выше
StepUp:         LD A, H
                DEC H
                AND #07
                JR Z, CrossCharRow                                              ; переход, если переход вверх пересёк восьмистрочный блок

CountRow:       DJNZ StepUp

RestoreContext: POP BC
                POP AF
                RET

                ; коррекция адреса при пересечении восьмистрочного блока вверх
CrossCharRow:   LD A, L
                SUB #20
                LD L, A
                JR C, CheckTop                                                  ; переход, если вычитание 32 дало заём, проверить верхнюю треть экрана

                LD A, H
                ADD A, #08
                LD H, A
                JR CountRow

                ; проверка верхнего предела буфера
CheckTop:       LD A, H
                CP #C0
                JR NC, CountRow                                                 ; переход, если H не ниже #C0, продолжить пропуск строк

                JR RestoreContext

                ; проверка исходного конца фрагмента
                ASSERT $ == #9032
                endmodule
                endmodule
