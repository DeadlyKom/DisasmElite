                module Circles
                module DrawCornerLeftContour
; -----------------------------------------
; контур угловой дуги с отсечённым левым краем
; исходный диапазон #8FCC..#8FD9
; смысловое имя DrawCornerLeftContour
; In: HL — правый край, E — левый граничный адрес, CircleState.Flags — направление
; Out: B=#80 и выбрана верхняя либо нижняя половина
; Corrupt: HL, DE, BC, AF, HL', DE', BC', AF'
; Левая граница содержит единственный старший пиксель, сплошная маска не используется
; -----------------------------------------
                ; проверка исходного начала фрагмента
                ASSERT $ == #8FCC
                ; подготовка фиксированной левой маски контурной дуги
Entry:          LD B, #80
                LD A, (CircleState.Flags)
                BIT CIRC_UP_BIT, A
                CALL NZ, Game.Screen.LeftArcDown.Entry                          ; вызов, если признак верхнего положения центра установлен, рисовать левую дугу вниз
                CALL Z, Game.Screen.LeftArcUp.Entry                             ; вызов, если признак верхнего положения центра сброшен, рисовать левую дугу вверх
                RET

                ; проверка исходного конца фрагмента
                ASSERT $ == #8FDA
                endmodule
                endmodule
