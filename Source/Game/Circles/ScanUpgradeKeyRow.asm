                module Circles
                module ScanUpgradeKeyRow
; -----------------------------------------
; проверка пяти клавиш ряда для улучшенного корабля
; исходный диапазон #8B2A..#8B3E
; смысловое имя ScanUpgradeKeyRow
; In: HL — счётчик/состояние, BC — C содержит базовый индекс, AF — A задаёт старший байт порта
; Out: при нажатой клавише C увеличен на её позицию 1..5, C-флаг=0
; Corrupt: DE — E, BC — C, AF, AF'
; Опрос разрешён только при #D08E>=5, затем один IN считывает весь ряд
; RRCA последовательно проверяет активные нули пяти клавиш без повторных IN
; При отсутствии нажатия либо неподходящем улучшении A=(HL)+1, флаги результата задаёт INC
; -----------------------------------------
                ; проверка исходного начала фрагмента
                ASSERT $ == #8B2A
                ; проверка улучшения перед опросом дополнительного ряда клавиатуры
Entry:          LD E, #05
                EX AF, AF'
                LD A, (State.ShipUpgrade)
                CP E
                JR C, KeepKeyState                                              ; переход, если улучшение #D08E меньше 5, опрос дополнительного ряда запрещён

                EX AF, AF'
                ; однократное чтение ряда и поиск первой нажатой клавиши
                IN A, (#FE)
TestKey:        INC C
                RRCA
                RET NC                                                          ; выход, если очередной аппаратный бит равен 0, клавиша нажата

                DEC E
                JR NZ, TestKey                                                  ; переход, если ещё не проверены все пять клавиш считанного ряда

                ; резервный результат из состояния вызывающего, если клавиша не найдена
KeepKeyState:   LD A, (HL)
                INC A
                RET
                ; проверка исходного конца фрагмента
                ASSERT $ == #8B3F
                endmodule
                endmodule
