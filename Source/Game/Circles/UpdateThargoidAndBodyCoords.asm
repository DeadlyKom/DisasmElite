                module Circles
                module UpdateThargoidAndBodyCoords
; -----------------------------------------
; счётчик поражений Thargoid и координаты двух далёких тел
; исходный диапазон #8AA3..#8ACC
; смысловое имя ProcessThargoidCounterAndBodyCoordinates
; In: IX — поражённый объект, HL сохраняется вокруг изменения #D086
; Out: для модели с младшим байтом #25 поле #D086 увеличено на 2
; Corrupt: AF, при создании контейнера также HL, DE, BC, IY
; При переполнении #D086 в 0 слот заменяется грузовым контейнером типа 4
; После конструктора IX+26=0, DEC превращает его в#FF, сохраняя особый набор признаков
; #8ABA и #8AC3 содержат два вектора по 9 байтов, три знако-модульные координаты XYZ
; #9B68 вращает оба вектора через #9C83, временный RET по #A1AD исключает сдвиг по скорости
; #FD02 чередует эти два вектора в специальном режиме, #5FD5 читает старшие Z по #8AC2/#8ACB
; #8ACC — исходный резерв без установленного потребителя, сохраняется
; -----------------------------------------
                ; проверка исходного начала фрагмента
                ASSERT $ == #8AA3
                ; проверка модели Thargoid по младшему байту указателя
Entry:          LD A, (IX + FSpaceObject.Blueprint)
                CP #25
                RET NZ                                                          ; выход, если младший адрес модели отличается от#25, это не проверяемый Thargoid

                ; увеличение счётчика задания на 2 с сохранением HL
                PUSH HL
                LD HL, State.AlienComputer
                INC (HL)
                INC (HL)
                POP HL
                RET NZ                                                          ; выход, если прибавление 2 к#D086 не завершилось нулём

                ; создание особого контейнера после обнуления счётчика
                LD A, #04
                CALL Game.Objects.InitializeObject.Entry
                DEC (IX + FSpaceObject.Flags2)
                RET
                ; первый вектор далёкого тела, три знако-модульные координаты по 3 байта
DistantData     EQU $                                                           ; начало сохранённых рабочих данных, исходное размещение
.FirstX         DB #00, #00, #03                                                ; три байта координаты X далёкого тела First
.FirstY         DB #00, #00, #00                                                ; три байта координаты Y далёкого тела First
.FirstZ         DB #00, #00, #03                                                ; три байта координаты Z далёкого тела First
.SecondX        DB #00, #00, #83                                                ; три байта координаты X далёкого тела Second
.SecondY        DB #00, #00, #00                                                ; три байта координаты Y далёкого тела Second
.SecondZ        DB #00, #00, #03                                                ; три байта координаты Z далёкого тела Second
.Reserved       DB #03                                                          ; исходный байт после двух векторов, потребитель не установлен
                ; проверка исходного конца фрагмента
                ASSERT $ == #8ACD
                endmodule
                endmodule
