                module Circles
                module CrossCircleCharacterRowDown
; -----------------------------------------
; переход вниз через границу восьмистрочного блока
; исходный диапазон #8E0D..#8E28
; смысловое имя CrossCircleCharacterRowDown
; In: H уже увеличен, L/E — два края одной строки
; Out: L/E увеличены на 32, без переноса L значение H уменьшается на 8
; Corrupt: HL, DE — E, AF
; Перенос L означает новую треть экрана, H=#D0 завершает всю половину
; Game.Circles.CrossCircleCharacterRowDown.FinishHalf удаляет внутренний адрес возврата, восстанавливает SP из CircleState.SavedSP и снимает сохранённый AF
; Верхний/нижний предельный байт патчатся для карты и прямого экрана
; -----------------------------------------
                ; проверка исходного начала фрагмента
                ASSERT $ == #8E0D
                ; расчёт адресов обоих краёв на следующей текстовой строке
Entry:          LD A, E
                ADD A, #20
                LD E, A
                LD A, L
                ADD A, #20
                LD L, A
                JR NC, SameThird                                                ; переход, если прибавление 32 к L не дало переноса, компенсировать H на-8

                ; проверка нижнего предела после переноса адреса
LowerLimit      EQU $ + 1                                                       ; нижний предел при переходе на следующее знакоместо
                LD A, #D0
                CP H
                JR Z, FinishHalf                                                ; переход, если H достиг нижнего предела #D0, завершить всю половину

                RET

                ; компенсация старшего байта внутри той же трети
SameThird:      LD A, H
                SUB #08
                LD H, A
                RET

                ; нелокальное завершение половины после выхода за границу экрана
FinishHalf:     POP AF
                LD SP, (CircleState.SavedSP)
                POP AF
                RET

                ; проверка исходного конца фрагмента
                ASSERT $ == #8E29
                endmodule
                endmodule
