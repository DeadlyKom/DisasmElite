                module Circles
                module CheckSystemCoordinateBand
; -----------------------------------------
; проверка близости координат системы к диагональной полосе
; исходный диапазон #8D2B..#8D37
; смысловое имя CheckSystemCoordinateBand
; In: #D097=Y системы, #D099=X системы
; Out: A=((Y>=X)?Y-X:X-Y-1) AND #F8, Z=1 для разности Y-X от-8 до 7
; Corrupt: HL, AF
; При отрицательной разности применяется CPL без INC, это намеренная асимметрия границ
; После AND перенос сброшен, HL указывает на#D099
; -----------------------------------------
                ; проверка исходного начала фрагмента
                ASSERT $ == #8D2B
                ; расчёт знаковой разности координат системы с дополнением отрицательного случая
Entry:          LD HL, State.SystemSeed + FSystemSeed.Y
                LD A, (HL)
                INC HL
                INC HL
                SUB (HL)
                JR NC, TestBandWidth                                            ; переход, если Y системы не меньше X, отрицательный случай не нужен

                CPL
                ; проверка восьмиединичной диагональной полосы маской#F8
TestBandWidth:  AND #F8
                RET
                ; проверка исходного конца фрагмента
                ASSERT $ == #8D38
                endmodule
                endmodule
