                module Scanner
                module StepScannerStemDown
; -----------------------------------------
; Переход ножки сканера через нижнюю границу знакоместа
; исходный диапазон #986A..#987B
; In:
;   HL адрес после INC H при пересечении восьми пиксельных строк
; Out:
;   HL следующая строка либо переход Game.Scanner.DrawScannerObjects.NextObject после снятия адреса возврата
; Corrupt:
;   HL, AF
; Note:
;   При переносе L+32 и H=58 достигнута область атрибутов, POP AF удаляет адрес CALL и сразу
;   выбирается следующий объект
; -----------------------------------------
                ASSERT $ == #986A
                ; расчёт следующего ряда знакомест при движении ножки вниз
Entry:          LD A, L
                ADD A, #20
                LD L, A
                JR NC, AdjustHigh                                               ; переход, если младший байт строки не переполнился, вернуть H на восемь строк

                ; проверка попадания в атрибуты и удаление адреса возврата при отсечении
                LD A, #58
                CP H
                RET NZ                                                          ; выход, если при переносе младшего байта H не равен 58, адрес ещё внутри экрана

                POP AF
                JR Game.Scanner.DrawScannerObjects.NextObject

                ; коррекция старшего байта нового знакоместа
AdjustHigh:     LD A, H
                SUB #08
                LD H, A
                RET

                ASSERT $ == #987C
                endmodule
                endmodule
