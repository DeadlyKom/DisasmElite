                module Scanner
                module SetYellowFlightStatus
; -----------------------------------------
; выбор жёлтого индикатора при наличии обычного живого объекта
; исходный диапазон #988E..#98A1
; In:
;   9CAE содержит энергию последнего живого объекта без Flags2.bit2
; Out:
;   7104=6, если допускается замена текущего сигнала
; Corrupt:
;   AF
; Note:
;   Состояния 0x63 специального мигания и 2 опасности не заменяются, нулевой 9CAE оставляет индикатор
; -----------------------------------------
                ASSERT $ == #988E
                ; проверка присутствия обычных объектов и приоритетных сигналов 2/63
Entry:          LD A, (OrdinarySeen)
                AND A
                RET Z                                                           ; выход, если обычных живых объектов нет

                LD A, (FlightState.FlightStatus)
                CP #63
                RET Z                                                           ; выход, если включён специальный мигающий сигнал 63

                CP #02
                RET Z                                                           ; выход, если уже выставлен красный сигнал опасности 2

                ; установка жёлтого сигнала 6
                LD A, #06
                LD (FlightState.FlightStatus), A
                RET
                ASSERT $ == #98A2
                endmodule
                endmodule
