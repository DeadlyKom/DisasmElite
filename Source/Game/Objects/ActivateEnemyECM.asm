                module Objects
                module ActivateEnemyECM
; -----------------------------------------
; включение ECM по ненулевому запросу C и разрешающему биту 4 регистра B
; исходный диапазон #B82C..#B866
; In:
;   BC - C запрос, B разрешающие флаги
; Out:
;   AF - 0 при отсутствии запроса, иначе 10 после успешного включения
; Corrupt:
;   AF
; Note:
;   при успехе #D085 := C OR #80 и таймер #9C9B := 10
;   после RET файл содержит шаблон инициализации слота #B83E..#B85C, матрицу заставки #B85D..#B865 и переключатель #B866
; -----------------------------------------
                ; проверка исходного начала фрагмента
                ASSERT $ == #B82C
Entry:          LD A, C
                AND A
                RET Z                                                           ; выход, если C равен нулю и запрос ECM отсутствует

                BIT DEV_ECM_BIT, B
                RET Z                                                           ; выход, если бит 4 регистра B не разрешает ECM

                OR ECM_ON_MASK
                LD (State.ECM), A
                LD A, #0A
                LD (CombatState.EcmTimer), A
                RET
                DB #00                                                          ; сохранённая часть исходного блока
ObjectTemplate  DB #00, #32, #00, #00, #32, #00, #00                            ; шаблон первых 31 байта объекта, копируется в поля X..Pitch
                DB #32, #00, #00, #00, #00, #00, #FF, #FF                       ; исходные байты #B845..#B84C
                DB #00, #00, #FF, #7F, #00, #00, #FF, #FF                       ; исходные байты #B84D..#B854
                DB #00, #00, #00, #00, #00, #00, #00, #00                       ; исходные байты #B855..#B85C
IntroMatrix     DB #58, #44, #41, #98, #64, #CB, #5A, #A7                       ; девять старших байтов осей модели заставки
                DB #D1                                                          ; продолжение данных #B865..#B865
SpawnAxis       DB #00                                                          ; переключатель чередования осей при создании объекта
                ; проверка исходного конца фрагмента
                ASSERT $ == #B867
                endmodule
                endmodule
