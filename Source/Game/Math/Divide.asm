                ifndef _ELITE_MATH_DIVIDE_
                define _ELITE_MATH_DIVIDE_
                module Math

; -----------------------------------------
; шестнадцать двоичных разрядов беззнакового частного
; In:
;   HL, начальная целая часть остатка
;   DE, ненулевой делитель, для обычного деления требуется HL < DE
;   AF, A содержит восемь следующих разрядов делимого
; Out:
;   HL, остаток деления
;   BC, частное floor((HL_in * 65536 + A_in * 256) / DE)
;   AF, A равен нулю, перенос сброшен
; Corrupt:
;   HL, BC, AF
; Note:
;   формула частного и остатка применима при указанных входных условиях
;   делитель DE сохраняется
;   сначала в остаток поступают восемь битов A, затем восемь нулей
;   начальное BC содержит маркер окончания, нуль в младшем разряде
;   после шестнадцатого сдвига этот нуль выходит в перенос
;   проверки деления на нуль и переполнения частного в оригинале нет
; -----------------------------------------
                ; проверка исходного адреса процедуры в снимке игры
                ASSERT $ == #AFA8
Divide:         LD BC, #FFFE
.Next:          ; расчёт удвоенного остатка с очередным битом делимого
                ADD A, A
                RL L
                RL H
                JR C, .Overflow                                                 ; переход, если удвоенный остаток вышел за 16 битов

                ; проверка возможности вычесть делитель без отрицательного остатка
                SBC HL, DE
                JR NC, .One                                                     ; переход, если делитель вычтен, очередной бит равен единице

                ; восстановление остатка и добавление нулевого разряда частного
                ADD HL, DE
                SLA C
                RL B
                RET NC                                                          ; выход, если маркер завершил шестнадцатый разряд

                JR .Next

.Overflow:      ; вычитание делителя из остатка с учётом уже известного старшего бита
                AND A
                SBC HL, DE
.One:           ; добавление единичного разряда частного
                SCF
                RL C
                RL B
                RET NC                                                          ; выход, если маркер завершил шестнадцатый разряд

                JR .Next
                ; проверка исходной границы процедуры
                ASSERT $ == #AFC9

                endmodule
                endif
