                ifndef _ELITE_MATH_SQUARE_
                define _ELITE_MATH_SQUARE_
                module Math

; -----------------------------------------
; квадрат беззнакового восьмибитного числа
; In:
;   AF, A содержит число от 0 до 255
; Out:
;   DE, точное значение A * A
; Corrupt:
;   DE, AF, изменяются только флаги
; Note:
;   HL и A сохраняются
;   младшие байты квадратов находятся в странице #BE00
;   старшие байты находятся в странице #BF00
;   все 256 значений исходной таблицы проверены как A * A
; -----------------------------------------
SquareLo        EQU Game.Data.SquareTables.Entry

                ; проверка исходного адреса процедуры в снимке игры
                ASSERT $ == #87BF
Square:         PUSH HL
                ; расчёт адреса младшего байта квадрата по исходному числу
                LD H, HIGH SquareLo
                LD L, A
                LD E, (HL)
                ; переход к старшему байту того же элемента таблицы
                INC H
                LD D, (HL)
                POP HL
                RET
                ; проверка исходной границы процедуры
                ASSERT $ == #87C8

                endmodule
                endif
