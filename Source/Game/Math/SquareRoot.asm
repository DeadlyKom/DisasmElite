                ifndef _ELITE_MATH_SQUARE_ROOT_
                define _ELITE_MATH_SQUARE_ROOT_
                module Math

; -----------------------------------------
; приближённый квадратный корень беззнакового шестнадцатибитного числа
; In:
;   HL, исходное число N
; Out:
;   HL, приближение sqrt(N) в формате 8.8, H задаёт целую часть
;   AF, A равен нулю
; Corrupt:
;   HL, DE, BC, AF
; Note:
;   это исходное приближение игры, а не точный целочисленный корень
;   L содержит дробную часть приближения, а не остаток N - H * H
;   малые входы увеличиваются на чётное число двоичных разрядов
;   при N < 256 используется M = N * 256, результат делится на 16
;   при 256 <= N < 4096 используется M = N * 16, результат делится на 4
;   при N >= 4096 используется M = N
;   ядро выполняет три приближения метода Ньютона с целыми промежуточными значениями
;   контрольная арифметическая модель даёт #0200 для N = 0
;   и #422F для N = 4096, погрешность оригинала сохраняется
; -----------------------------------------
                ; проверка исходного адреса основного входа
                ASSERT $ == #9EF1
SquareRoot:     ; проверка необходимости масштабирования исходного числа
                LD A, H
                CP #10
                JR NC, SqrtCore                                                 ; переход, если N не меньше 4096, масштабирование не требуется

                AND A
                JR Z, .Small                                                    ; переход, если N меньше 256, нужен сдвиг на восемь разрядов

                ; расчёт M = N * 16 без переполнения шестнадцатибитного слова
                LD B, 4
.Scale:         ADD HL, HL
                DJNZ .Scale

                CALL SqrtCore
                ; восстановление масштаба корня делением приближения на четыре
                SRL H
                RR L
                SRL H
                RR L
                RET

.Small:         ; расчёт M = N * 256, при входе A равен нулю
                LD H, L
                LD L, A
                CALL SqrtCore
                ; восстановление масштаба корня делением приближения на шестнадцать
                LD B, 4
.Unscale:       SRL H
                RR L
                DJNZ .Unscale

                RET

; -----------------------------------------
; ядро приближённого корня в формате 8.8
; In:
;   HL, масштабированное число M
; Out:
;   HL, приближение sqrt(M) * 256
;   AF, A равен нулю
; Corrupt:
;   HL, DE, BC, AF
; Note:
;   две копии M на стеке используются двумя последующими уточнениями
;   первый результат равен #8000 + floor(M / 2)
;   следующие уточнения используют половину предыдущего приближения
;   как делитель, сохраняя оригинальные округления и поведение Divide
; -----------------------------------------
                ; проверка исходного адреса ядра приближения
                ASSERT $ == #9F18
SqrtCore:       XOR A
                PUSH HL
                PUSH HL
                ; расчёт M / 2 с переносом младшего бита в дробный байт A
                SRL H
                RR L
                RRA
                LD DE, #8000
                CALL SqrtMean
                POP DE
                CALL SqrtStep
                POP DE

; -----------------------------------------
; очередное уточнение корня
; In:
;   HL, предыдущее приближение в формате 8.8
;   DE, масштабированное число M
;   AF, A равен нулю, перенос от предыдущего сложения
; Out:
;   HL, новое приближение
;   AF, A равен нулю, перенос от сложения двух половин
; Corrupt:
;   HL, DE, BC, AF
; Note:
;   RR использует перенос от SqrtMean, логика оригинала сохраняется
; -----------------------------------------
                ; проверка исходного адреса шага уточнения
                ASSERT $ == #9F2B
SqrtStep:       ; расчёт половины предыдущего приближения для делителя
                RR H
                RR L
                EX DE, HL
                ; расчёт M / 2 с сохранением дробного бита в A
                SRL H
                RR L
                RRA

; -----------------------------------------
; сложение половины приближения с половиной результата деления
; In:
;   HL, целая часть M / 2
;   DE, половина предыдущего приближения
;   AF, A содержит дробный байт M / 2
; Out:
;   HL, DE_in + floor(частное / 2)
;   BC, половина частного Divide
;   AF, A равен нулю, перенос от итогового сложения
; Corrupt:
;   HL, BC, AF
; Note:
;   DE сохраняется
;   в вещественной арифметике этот шаг соответствует
;   x_next = x / 2 + M * 32768 / x, где x хранится в формате 8.8
;   реальные сдвиги и деление вносят округление, насыщение отдельно не добавляется
; -----------------------------------------
                ; проверка исходного адреса операции усреднения
                ASSERT $ == #9F35
SqrtMean:       PUSH DE
                CALL Divide
                ; расчёт половины частного и суммы двух слагаемых приближения
                SRL B
                RR C
                XOR A
                POP HL
                ADD HL, BC
                RET
                ; проверка исходной границы всего блока корня
                ASSERT $ == #9F41

                endmodule
                endif
