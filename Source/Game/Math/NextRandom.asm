                ifndef _ELITE_MATH_NEXT_RANDOM_
                define _ELITE_MATH_NEXT_RANDOM_
                module Math

; -----------------------------------------
; следующий шаг генератора из трёх слов, используемого при построении галактики
; In:
;   три последовательных слова состояния по адресам Memory.RandomSeed, GalaxyState.WorkingSeed + FSystemSeed.GovBits, GalaxyState.WorkingSeed + FSystemSeed.MixLow
; Out:
;   HL, новое третье слово состояния
;   DE, сумма прежних первого и второго слов по модулю 65536
; Corrupt:
;   HL, DE, AF, изменяются только флаги
; Note:
;   если исходное состояние равно (x, y, z), новое равно (y, z, x + y + z)
;   каждое сложение выполняется по модулю 65536
;   A и BC сохраняются
;   функция не использует таймер или регистр R, одинаковое состояние
;   всегда даёт одинаковую последовательность, необходимую для карты галактики
;   до входа в игру Loader.MutateMemory использует эту же процедуру
;   для выбора адресов побитового декодирования дискового файла
;   начальные шесть байтов являются состоянием последовательности, не паролем
;   каждый вызов меняет состояние, один XOR загрузчика также попадает в GalaxyState.WorkingSeed + FSystemSeed.GovBits
;   потому состояние после загрузки отличается от исходных дисковых семян
; -----------------------------------------
Seed:           EQU #DEC0

                ; проверка исходного адреса процедуры в снимке игры
                ASSERT $ == #E063
NextRandom:     ; расчёт суммы первых двух слов прежнего состояния
                LD HL, (Seed)
                LD DE, (Seed + 2)
                ADD HL, DE
                EX DE, HL
                ; обновление первых двух слов сдвигом прежнего состояния
                LD (Seed), HL
                LD HL, (Seed + 4)
                LD (Seed + 2), HL
                ; расчёт и сохранение нового третьего слова
                ADD HL, DE
                LD (Seed + 4), HL
                RET

                ; проверка исходной границы процедуры
                ASSERT $ == #E07A

                endmodule
                endif
