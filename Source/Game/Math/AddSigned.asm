                ifndef _ELITE_MATH_ADD_SIGNED_
                define _ELITE_MATH_ADD_SIGNED_
                module Math

; -----------------------------------------
; половина разности координат в формате знак и модуль
; In:
;   HL, первая координата, бит 15 задаёт знак, биты 14..0 задают модуль
;   DE, вторая координата в том же формате
; Out:
;   HL, половина разности HL_in - DE_in в формате знак и модуль
;   AF, перенос содержит отброшенный младший бит модуля
; Corrupt:
;   HL, DE, BC, AF
; Note:
;   инверсия знака второго аргумента превращает вычитание в сложение
;   результат округляется по модулю вниз, отрицательный нуль допустим
; -----------------------------------------
                ; проверка исходного адреса входа для разности координат
                ASSERT $ == #AFC9
HalfDelta:      LD A, D
                XOR #80
                LD D, A

; -----------------------------------------
; половина суммы координат в формате знак и модуль
; In:
;   HL, первое слагаемое, бит 15 задаёт знак, биты 14..0 задают модуль
;   DE, второе слагаемое в том же формате
; Out:
;   HL, знак суммы и floor(abs(HL_in + DE_in) / 2)
;   AF, перенос содержит младший бит модуля до деления на два
; Corrupt:
;   HL, DE, BC, AF
; Note:
;   при одинаковых знаках складываются модули
;   при разных знаках меньший модуль вычитается из большего
;   знак берётся от аргумента с большим модулем
;   при равных противоположных модулях сохраняется знак первого аргумента
;   сумма модулей не превосходит #FFFE, после сдвига помещается в 15 битов
;   BIT и SET в конце сохраняют перенос от сдвига младшего байта
; -----------------------------------------
                ; проверка исходного адреса входа для суммы координат
                ASSERT $ == #AFCD
AddSigned:      ; сохранение исходных знаков до выделения модулей
                LD A, H
                XOR D
                LD B, H
                LD C, D
                RES 7, H
                RES 7, D
                ; проверка совпадения знаков исходных слагаемых
                AND #80
                JR NZ, .Different                                               ; переход, если знаки различаются, требуется разность модулей

                ; расчёт суммы модулей при одинаковых знаках
                ADD HL, DE
                JR .Half

.Different:     ; расчёт разности модулей с нулевым входным переносом
                SBC HL, DE
                JR NC, .Half                                                    ; переход, если первый модуль не меньше второго

                ; расчёт положительного модуля разности и выбор знака второго аргумента
                ADD HL, DE
                EX DE, HL
                AND A
                SBC HL, DE
                LD B, C
.Half:          ; расчёт половины модуля с сохранением отброшенного бита в переносе
                SRL H
                RR L
                ; проверка знака выбранного аргумента
                BIT 7, B
                RET Z                                                           ; выход, если результат имеет положительный знак

                SET 7, H
                RET
                ; проверка исходной границы обеих процедур
                ASSERT $ == #AFF0

                endmodule
                endif
