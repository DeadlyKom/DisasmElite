                module Universe
                module ApplyEnhancedFlightControl
; -----------------------------------------
; усиление углов и скорости по дополнительной клавише
; исходный диапазон #7F81..#7FBD
; In:
;   память D08E, оборудование
;   клавиша J, строка BF bit3
; Out:
;   AF, A содержит актуальный угол DU
;   70E4..70E6 при нажатии преобразованы
; Corrupt:
;   HL
; Note:
; Для каждого из углов LR/DU и скорости вычисляет (2*x OR x) AND BF.
; Три байта обходятся до L с установленным битом 1.
; Вход #7FA1 вызывается отдельно из #E8B7 для проверки доставки беженцев.
; -----------------------------------------
                ; проверка исходного начала фрагмента
                ASSERT $ == #7F81
                ; проверка оборудования и дополнительной клавиши
Entry:          LD A, (State.ShipUpgrade)
                AND A
                JR Z, ReturnPitch                                               ; переход, если дополнительное оборудование отсутствует
DirectKeyRead   EQU $                                                           ; начало прямого чтения клавиши, демо подставляет виртуальную строку
                LD A, #BF
                IN A, (#FE)
                BIT 3, A
                JR NZ, ReturnPitch                                              ; переход, если клавиша J не нажата

                LD HL, FlightState.Roll
                ; расчёт усиленных углов и скорости
AmplifyAxis:    LD A, (HL)
                ADD A, A
                OR (HL)
                AND #BF
                LD (HL), A
                BIT 1, L
                INC HL
                JR Z, AmplifyAxis                                               ; переход, если ещё не обработан третий байт скорости

                ; возврат актуального угла DU
ReturnPitch:    LD A, (FlightState.Pitch)
                RET

                ; сохранённые машинные байты прежнего обработчика

; -----------------------------------------
; проверка разрешения высадить беженцев по флагу и условиям вторжения
; In:
;   HL, адрес флагов, действующий вызов передаёт #D0B0
; Out:
;   HL, исходный адрес
;   AF, Z запрещает операцию, NZ разрешает при H=#D0
;   бит 0 по HL устанавливается при разрешении через проверку области
; Corrupt:
;   DE, BC, AF
; Note:
;   действующий CALL #E8B7 перед расходом бита 5 по #D0B0
;   без бита 5 возвращает Z, при #D08F<2 сразу разрешает операцию через RET C
;   при #D08F>=2 значение #D062>=#84 запрещает операцию
;   для меньшего #D062 перенос #EC40 запрещает, отсутствие переноса разрешает операцию
;   INC H и DEC H восстанавливают HL и формируют NZ для страницы #D0
; -----------------------------------------
CheckRefugees:  ; проверка разрешения высадить беженцев по флагу и условиям вторжения
                ; миссии 1 и 7+1, проверка груза, военного состояния и места высадки
                ; описание в Docs/Manual.md, раздел mission-1 и mission-7-1
                ; проверка наличия особого груза по биту 5
                BIT MS_CARGO_BIT, (HL)
                RET Z                                                           ; выход, если бит 5 проверяемого поля сброшен

                ; проверка необходимости ограничений активного вторжения
                LD A, (State.Invasion)
                SUB INV_ACTIVE_MIN
                RET C                                                           ; выход, если фаза вторжения меньше 2, ограничение не требуется

                ; проверка военного кода и специальной области
                LD A, (State.RankState)
                CP RANK_CAPT_CODE
                CCF
                PUSH HL
InvasionCall    EQU $ + 1                                                       ; операнд CALL проверки области вторжения, демо подставляет перенесённую копию
                CALL NC, Game.Menus.CheckMissionRegionBand.Entry                ; вызов процедуры, если военный код меньше #84
                POP HL
                JR NC, MarkResult                                               ; переход, если проверка области разрешила операцию

                XOR A
                RET

                ; обновление флага результата и формирование ненулевого признака для страницы D0
MarkResult:     SET MS_MARK1_BIT, (HL)
                INC H
                DEC H
                RET
                ; проверка исходного конца фрагмента
                ASSERT $ == #7FBE
                endmodule
                endmodule
