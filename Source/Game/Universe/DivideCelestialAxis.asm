                module Universe
                module DivideCelestialAxis
; -----------------------------------------
; нормализация и деление одной координаты проекции светила
; исходный диапазон #77A0..#783A
; In:
;   HL, старшие байты модуля боковой координаты
;   DE, старшие байты глубины
;   BC, C/B содержат младшие байты координаты и глубины
;   BC', состояние признаков текущей оси
; Out:
;   DE, D содержит восьмибитную проекцию
;   BC', уточнены признаки положения
; Corrupt:
;   HL, DE, BC, AF, HL', DE'
; Note:
; Сравнивает старшие слова, при равенстве сравнивает младшие байты, выбирая режим нормализации.
; Разные пути сдвигают сначала 24-битные значения, затем 16-битные и старшие байты до выделения делителя.
; Для малого числителя используется перепаковка 7799, для переполнений общий масштаб восстанавливается через RR.
; При недопустимом отношении вход 7828 снимает сохранённое HL и адрес возврата внутреннего CALL.
; Тем самым возвращает A=0 непосредственно вызывающему ProjectCelestialBody коду, пропуская его продолжение.
; 782A также отдельный общий выход отказа, используемый без лишнего снятия стека.
; Успех продолжается в дробное деление 783B/783D, функция привязана к стековому контексту проекции.
; -----------------------------------------
                ; проверка исходного начала фрагмента
                ASSERT $ == #77A0
                ; сравнение координаты и глубины перед выбором нормализации
Entry:          PUSH HL
                EXX
                DEC C
                EXX
                AND A
                SBC HL, DE
                JP C, MarkOutside                                               ; переход, если старшее слово боковой координаты меньше глубины

                JP Z, CompareLow                                                ; переход, если старшие слова равны и нужно сравнить младшие байты

                ; нормализация случая с большим числителем
Normalize:      POP HL
                LD A, H
                AND A
                JR Z, Game.Universe.ShiftSmallBodyProjectionOperands.Entry      ; переход, если старший байт числителя нулевой и можно перегруппировать младшие байты

                LD A, #08
ShiftTriple:    SLA C
                ADC HL, HL
                JP C, AlignDivisor                                              ; переход, если нормализуемый числитель переполнил слово

                SLA B
                RL E
                RL D
                DEC A
                JR NZ, ShiftTriple                                              ; переход, если остались сдвиги трёхбайтовой нормализации

                ; нормализация двухбайтового диапазона
WordScale:      LD A, #08
ShiftWords:     ADD HL, HL
                JP C, AlignDivisor                                              ; переход, если числитель переполнил слово во второй стадии

                EX DE, HL
                ADD HL, HL
                EX DE, HL
                DEC A
                JR NZ, ShiftWords                                               ; переход, если остались сдвиги двухбайтовой нормализации

                LD A, #08
ShiftHigh:      SLA H
                JP C, AlignDivisor                                              ; переход, если старший байт числителя достиг старшего разряда

                SLA D
                DEC A
                JR NZ, ShiftHigh                                                ; переход, если остались сдвиги старшего байта

                RET

                ; сравнение младших разрядов при равных старших словах
CompareLow:     PUSH BC
                LD A, C
                SUB B
                POP BC
                JR C, MarkOutside                                               ; переход, если при равных словах младший числитель меньше младшего делителя

                JR Z, MarkOutside                                               ; переход, если все три байта числителя и делителя равны

                JP Normalize

                ; обновление дополнительных признаков положения
FirstOutside:   SET CIRC_XRANGE_BIT, B
                JP SmallNumerator

MarkOutside:    EXX
                DEC C
                JR NZ, FirstOutside                                             ; переход, если вспомогательный счётчик выбирает первый признак положения

                SET CIRC_YRANGE_BIT, B
                ; нормализация случая с меньшим числителем
SmallNumerator: INC C
                EXX
                POP HL
                LD A, #17
ShiftFraction:  SLA C
                ADC HL, HL
                PUSH AF
                SLA B
                RL E
                RL D
                JR C, FinishScale                                               ; переход, если нормализуемый делитель переполнил слово

                POP AF
                DEC A
                JR NZ, ShiftFraction                                            ; переход, если остались сдвиги выбранной нормализации

                RET

                ; согласование масштаба после переполнения
AlignDivisor:   SLA B
                RL E
                RL D
                PUSH AF
                SCF
                RR H
                RR L
                POP AF
                JR C, SubtractAxis                                              ; переход, если согласование масштаба делителя потребовало дополнительного переноса

                PUSH HL
                AND A
                SBC HL, DE
                JR NC, RejectDivide                                             ; переход, если нормализованный числитель не меньше делителя и проекция отвергается

                POP HL
SubtractAxis:   SCF
                RR D
                AND A
                SBC HL, DE
                JR SetupFraction

                ; отказ со снятием сохранённого слова и внутреннего адреса возврата
RejectDivide:   POP HL
                POP AF
                ; общий выход недопустимой проекции
RejectBody:     XOR A
                RET

CarryScale:     SCF
                RR H
                JR ScaleDivisor

                ; завершение нормализации и подготовка дробного деления
FinishScale:    POP AF
                JR C, CarryScale                                                ; переход, если перенос сохранённой стадии требует отдельного выхода со сдвигом

                RR H
ScaleDivisor:   SCF
                RR D
SetupFraction:  LD A, H
                LD B, D
                ; проверка исходного конца фрагмента
                ASSERT $ == #783B
                endmodule
                endmodule
