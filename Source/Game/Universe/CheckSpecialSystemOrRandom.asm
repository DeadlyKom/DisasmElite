                module Universe
                module CheckSpecialSystemOrRandom
; -----------------------------------------
; особая инициализация станционного слота либо получение случайного байта
; исходный диапазон #7F64..#7F80
; In:
;   состояние системы для проверки FCEA
; Out:
;   при NZ от #FCEA A содержит случайное значение
;   при Z от #FCEA настроены координаты станции и режим 4
; Corrupt:
;   HL, DE, BC, AF
; Note:
; Решение использует фактический Z от #FCEA, а не только совпадение координат.
; Полный путь #FCEA возвращает Z для Y=#5C,X=#03.
; Ранний выход при CY=0 также возвращает Z для Y=#FF, координата X тогда не проверяется.
; При Z очищает #6048..#604F, задаёт #6050=1, энергию #606A=#F0 и #D0AF=4.
; POP HL удаляет адрес возврата вызывающего помощника, RET выходит уровнем выше.
; -----------------------------------------
                ; проверка исходного начала фрагмента
                ASSERT $ == #7F64
                ; миссия 7+4, размещение особой станции по результату проверки системы
                ; описание в Docs/Manual.md, раздел mission-7-4
                ; проверка особой системы
Entry:          CALL Game.Input.CheckMissionSystem.Entry
                JP NZ, Game.Combat.NextRandomByte.Entry                         ; переход, если #FCEA вернула NZ, требуется обычный случайный байт

                ; создание специального положения станции
                LD HL, Memory.Station
                LD B, #08
ClearStation:   LD (HL), #00
                INC HL
                DJNZ ClearStation

                LD (HL), #01
                LD L, #6A
                LD (HL), #F0
                LD A, #04
                LD (State.Mission3), A
                POP HL
                RET
                ; проверка исходного конца фрагмента
                ASSERT $ == #7F81
                endmodule
                endmodule
