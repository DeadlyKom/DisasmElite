                module Universe
                module CompareObjectAxisDistance
; -----------------------------------------
; проверка разности одной целой координаты двух объектов
; исходный диапазон #7B4A..#7B69
; In:
;   IX, координатная тройка первого объекта
;   IY, координатная тройка второго объекта
; Out:
;   DE, E содержит целый байт первой координаты
;   AF, A содержит модуль суммы либо разности, перенос при A<24
;   IX, следующая координата
;   IY, следующая координата
; Corrupt:
;   нет дополнительных регистров
; Note:
; Указатели сначала увеличиваются на 3, затем читаются предыдущие байты -1 и -2.
; При одинаковых старших байтах берётся модуль разности, иначе сумма. Дробные части не учитываются.
; -----------------------------------------
                ; смещения описывают исходные данные, память не выделяется
PrevSign:       EQU FCoordinate-FCoordinate.SignHigh                            ; отступ назад к знаку и старшему модулю предыдущей координаты
PrevLow:        EQU FCoordinate-FCoordinate.Low                                 ; отступ назад к целому младшему байту предыдущей координаты

                ; проверка исходного начала фрагмента
                ASSERT $ == #7B4A
                ; переход к следующей координате и проверка старших байтов
Entry:          LD DE, #0003
                ADD IX, DE
                ADD IY, DE
                LD A, (IX-PrevSign)
                XOR (IY-PrevSign)
                LD E, (IX-PrevLow)
                LD A, (IY-PrevLow)
                JR Z, SameSign                                                  ; переход, если старшие байты координат одинаковы и нужно вычитать модули

                ; расчёт суммарного расстояния при разных направлениях
                ADD A, E
CheckRange:     CP #24
                RET

                ; расчёт модуля разности при одинаковых направлениях
SameSign:       SUB E
                JR NC, CheckRange                                               ; переход, если вторая целая координата не меньше первой

                NEG
                JR CheckRange
                ; проверка исходного конца фрагмента
                ASSERT $ == #7B6A
                endmodule
                endmodule
