                module Universe
                module ShiftSmallBodyProjectionOperands
; -----------------------------------------
; перегруппировка младших координат перед проекцией светила
; исходный диапазон #7799..#779F
; In:
;   HL, младший значащий байт числителя в L
;   DE, младший значащий байт знаменателя в E
;   BC, C/B содержат следующие младшие байты
; Out:
;   HL, DE, нормализованные пары для общего хвоста Game.Universe.DivideCelestialAxis.WordScale
; Corrupt:
;   нет дополнительных регистров
; Note:
; Внутренний вход из Game.Universe.DivideCelestialAxis.Entry при нулевом H. Самостоятельного RET нет.
; Стек и альтернативные регистры должны соответствовать расчёту одной оси светила.
; -----------------------------------------
                ; проверка исходного начала фрагмента
                ASSERT $ == #7799
                ; перенос младших значащих разрядов в рабочие слова проекции
Entry:          LD H, L
                LD L, C
                LD D, E
                LD E, B
                JP @Game.Universe.DivideCelestialAxis.WordScale

                ; проверка исходного конца фрагмента
                ASSERT $ == #77A0
                endmodule
                endmodule
