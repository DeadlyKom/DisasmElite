                module Universe
                module CheckLinkedObjectInteraction
; -----------------------------------------
; поиск объекта по упакованному номеру и проверка взаимодействия
; исходный диапазон #7B6A..#7B80
; In:
;   BC, C содержит признаки источника
;   AF, low4 A содержит номер цели 1..8
;   IX, объект-источник
; Out:
;   HL, адрес цели
;   AF, перенос при выполненном взаимодействии
;   IY, запись цели
; Corrupt:
;   DE, BC
; Note:
; Нулевой номер возвращает Z без поиска. Адрес основного слота 6048+(8-номер)*39.
; Параллельно выбирается запись B457+(8-номер)*10, затем поток продолжается в 7B81.
; -----------------------------------------
                ; проверка исходного начала фрагмента
                ASSERT $ == #7B6A
                ; проверка номера и поиск основного слота с расширенной записью
Entry:          AND FX_LINK_MASK
                RET Z                                                           ; выход, если номер цели нулевой

                LD HL, Memory.Station - FSpaceObject                            ; позиция перед станцией, цикл прибавляет размер слота до первого доступа
                LD IY, ObjectEffects.Records - FEffectRecord10
FindLink:       LD DE, FSpaceObject
                ADD HL, DE
                LD E, #0A
                ADD IY, DE
                INC A
                CP #09
                JR NZ, FindLink                                                 ; переход, если ещё не достигнут заданный обратный номер слота
                ; проверка исходного конца фрагмента
                ASSERT $ == #7B81
                endmodule
                endmodule
