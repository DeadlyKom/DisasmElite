                module Universe
                module ApplyEcmToStandardMissile
; -----------------------------------------
; проверка типа ракеты и установка запроса уничтожения от ECM
; исходный диапазон #7D3E..#7D4C
; In:
;   IX, ракета
; Out:
;   AF, Z если младший адрес модели равен E3
;   IX+20.6 сброшен и IX+20.4 установлен для этого типа
; Corrupt:
;   нет дополнительных регистров
; Note:
; Модель распознаётся по младшему байту указателя, а не по отдельному идентификатору.
; -----------------------------------------
                ; проверка исходного начала фрагмента
                ASSERT $ == #7D3E
                ; проверка типа ракеты перед снятием управления и уничтожением
Entry:          LD A, (IX+FSpaceObject.Blueprint)
                CP #E3
                RET NZ                                                          ; выход, если младший адрес модели отличается от E3 и ракета не обрабатывается

                RES OBJ_ACTIVE_BIT, (IX+FSpaceObject.Flags)
                SET OBJ_DESTROY_BIT, (IX+FSpaceObject.Flags)
                RET
                ; проверка исходного конца фрагмента
                ASSERT $ == #7D4D
                endmodule
                endmodule
