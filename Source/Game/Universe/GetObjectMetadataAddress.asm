                module Universe
                module GetObjectMetadataAddress
; -----------------------------------------
; вычисление адреса расширенной записи по адресу основного слота
; исходный диапазон #7EC8..#7EDD
; In:
;   HL, допустимый адрес одного из восьми объектов
; Out:
;   HL, доведён до адреса станции Memory.Station
;   IX, соответствующая десятибайтовая запись
; Corrupt:
;   DE, AF
; Note:
; Начинает с ObjectEffects.Records и вычитает из HL39, пока младший байт не станет 48.
; Для допустимого пула это точный индекс, произвольные адреса не поддерживаются.
; 7EDB/7EDC сохранены как данные, FastTravel является флагом ускоренного звёздного прохода.
; -----------------------------------------
                ; проверка исходного начала фрагмента
                ASSERT $ == #7EC8
                ; поиск соответствующей записи шагами 39 и 10
Entry:          LD IX, ObjectEffects.Records
                LD A, #48
FindSlot:       CP L
                RET Z                                                           ; выход, если младший байт адреса дошёл до начала станционного слота

                LD DE, -FSpaceObject
                ADD HL, DE
                LD DE, #000A
                ADD IX, DE
                JR FindSlot

                ; данные перед флагом ускоренного звёздного прохода
                DB #F3, #F3                                                     ; продолжение данных #7EDB..#7EDC
FastTravel      DB #00                                                          ; флаг, выполнен ускоренный перенос звёздного поля
                ; проверка исходного конца фрагмента
                ASSERT $ == #7EDE
                endmodule
                endmodule
