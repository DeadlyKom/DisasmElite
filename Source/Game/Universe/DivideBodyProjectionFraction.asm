                module Universe
                module DivideBodyProjectionFraction
; -----------------------------------------
; восемь разрядов дробного деления для светила
; исходный диапазон #783D..#7852
; In:
;   DE, E содержит младшие разряды числителя
;   BC, B содержит ненулевой делитель
;   AF, A содержит остаток меньше делителя
; Out:
;   DE, D содержит восьмибитное частное
; Corrupt:
;   AF
; Note:
; Старшие единицы начального D=FE служат счётчиком разрядов.
; На каждом шаге остаток удваивается, при необходимости вычитается делитель и добавляется бит частного.
; -----------------------------------------
                ; проверка исходного начала фрагмента
                ASSERT $ == #783D
                ; подготовка счётчика и расчёт дробных разрядов
Entry:          LD D, #FE
QuotientBit:    SLA E
                RLA
                JR C, SubDivisor                                                ; переход, если удвоенный остаток переполнил байт

                CP B
                JR NC, SubDivisor                                               ; переход, если остаток не меньше делителя

                SLA D
                RET NC                                                          ; выход, если все восемь разрядов частного обработаны

                JR QuotientBit

SubDivisor:     SUB B
                SCF
                RL D
                RET NC                                                          ; выход, если все восемь разрядов частного обработаны

                JR QuotientBit
                ; проверка исходного конца фрагмента
                ASSERT $ == #7853
                endmodule
                endmodule
