; .. [7] - клавиша этой картой не назначена, назначение отдельного флага не установлено
; R [6] - флаг, клавиша R, пара карты KeyAssignments + 58
; D [5] - флаг, клавиша D, пара карты KeyAssignments + 44
; B [4] - флаг, клавиша B, пара карты KeyAssignments + 64
; .. [3] - клавиша этой картой не назначена, назначение отдельного флага не установлено
; .. [2] - клавиша этой картой не назначена, назначение отдельного флага не установлено
