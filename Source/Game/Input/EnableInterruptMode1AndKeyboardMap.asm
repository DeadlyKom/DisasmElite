; .. [7] - клавиша этой картой не назначена, назначение отдельного флага не установлено
; .. [6] - клавиша этой картой не назначена, назначение отдельного флага не установлено
; .. [5] - клавиша этой картой не назначена, назначение отдельного флага не установлено
; 7 [4] - флаг, клавиша 7, пара карты KeyAssignments + 54
; 6 [3] - флаг, клавиша 6, пара карты KeyAssignments + 70
; 8 [2] - флаг, клавиша 8, пара карты KeyAssignments + 38
; 5 [1] - флаг, клавиша 5, пара карты KeyAssignments + 72
; 9 [0] - флаг, клавиша 9, пара карты KeyAssignments + 22
