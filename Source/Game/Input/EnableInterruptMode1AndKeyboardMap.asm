;   общий хвост Game.Input.ResetDemoAndNormalizeControls.MergeControls проверяет клавишу 0 по SYS_0_BIT, снимает её и проверяет InputState.ViewJumpKeys.7
;   при комбинации 0+CAPS SHIFT записывается специальный код #FE в InputState.LastKey
;
; InputState.FlightKeys
;       7    6    5    4    3    2    1    0
;     +----+----+----+----+----+----+----+----+
;     | .. | .. | SS | SP | S  | X  | M  | N  |
;     +----+----+----+----+----+----+----+----+
; .. [7] - клавиша этой картой не назначена, назначение отдельного флага не установлено
; .. [6] - клавиша этой картой не назначена, назначение отдельного флага не установлено
; SS [5] - флаг, клавиша SYMBOL SHIFT, пара карты KeyAssignments + 16
; SP [4] - флаг, клавиша SPACE, пара карты KeyAssignments
; S [3] - флаг, клавиша S, пара карты KeyAssignments + 28
; X [2] - флаг, клавиша X, пара карты KeyAssignments + 46
; M [1] - флаг, клавиша M, пара карты KeyAssignments + 32
; N [0] - флаг, клавиша N, пара карты KeyAssignments + 48
;   после Game.Input.ResetDemoAndNormalizeControls.SwapAxisPairs младшая тетрада содержит нормализованные направления из выбранного источника
;   N [0] задаёт отрицательный крен, M [1] положительный, X [2] отрицательный тангаж, S [3] положительный
;   SP [4] увеличивает скорость, SS [5] уменьшает её, потребитель Game.Input.IntegrateFlightControls.Entry
;   настройки InputState.Config меняют назначение направлений, поэтому подписи букв относятся к исходной карте
;
; InputState.ViewJumpKeys
;       7    6    5    4    3    2    1    0
;     +----+----+----+----+----+----+----+----+
