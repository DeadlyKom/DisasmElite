; Game.Input.SetPressedKeyAssignment.Entry вычисляет индекс (5-E)*8+D-1, читает пару смещение/маска и выполняет OR
; имена CAPS SHIFT и SYMBOL SHIFT определяются положением в аппаратной матрице
; оба символа имеют код #FF в таблице KeyCharacters, по одному этому коду их различить нельзя
; прямых записей в KeyAssignments или загрузки новой карты назначений клавиш
; в разобранном игровом коде не найдено, штатная процедура Game.Input.SetPressedKeyAssignment.Entry только читает таблицу
; Game.Input.ScanKeyboardMatrix.Entry перед каждым опросом обнуляет InputState.NumberKeys, остальные маски накапливаются до обработки
