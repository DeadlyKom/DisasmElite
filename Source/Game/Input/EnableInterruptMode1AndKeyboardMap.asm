;     +----+----+----+----+----+----+----+----+
; CS [7] - флаг, клавиша CAPS SHIFT, пара карты KeyAssignments + 14
; J [6] - флаг, клавиша J, пара карты KeyAssignments + 50
; G [5] - флаг, клавиша G, пара карты KeyAssignments + 76
; H [4] - флаг, клавиша H, пара карты KeyAssignments + 66
; 4 [3] - флаг, клавиша 4, пара карты KeyAssignments + 56
; 3 [2] - флаг, клавиша 3, пара карты KeyAssignments + 40
; 2 [1] - флаг, клавиша 2, пара карты KeyAssignments + 24
; 1 [0] - флаг, клавиша 1, пара карты KeyAssignments + 8
;   CS [7] запрашивает паузу в Game.Flight.HandlePauseMenu.Entry, это CAPS SHIFT, не SYMBOL SHIFT
;
; InputState.DeviceKeys
;       7    6    5    4    3    2    1    0
;     +----+----+----+----+----+----+----+----+
;     | C  | Q  | W  | E  | U  | F  | T  | A  |
;     +----+----+----+----+----+----+----+----+
; C [7] - флаг, клавиша C, пара карты KeyAssignments + 62
; Q [6] - флаг, клавиша Q, пара карты KeyAssignments + 10
; W [5] - флаг, клавиша W, пара карты KeyAssignments + 26
