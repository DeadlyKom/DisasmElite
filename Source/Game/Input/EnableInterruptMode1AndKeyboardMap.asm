                DB #03, #04                                                     ; данные #FF94..#FF95
                ; клавиша C, индекс 31, смещение #03 и маска #80
                DB #03, #80                                                     ; данные #FF96..#FF97
                ; клавиша B, индекс 32, смещение #04 и маска #10
                DB #04, #10                                                     ; данные #FF98..#FF99
                ; клавиша H, индекс 33, смещение #02 и маска #10
                DB #02, #10                                                     ; данные #FF9A..#FF9B
