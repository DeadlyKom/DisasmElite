                ; клавиша 4, индекс 28, смещение #02 и маска #08
                DB #02, #08                                                     ; данные #FF90..#FF91
                ; клавиша R, индекс 29, смещение #04 и маска #40
                DB #04, #40                                                     ; данные #FF92..#FF93
