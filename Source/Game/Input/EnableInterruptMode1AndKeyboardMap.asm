                module Input
                module EnableInterruptMode1AndKeyboardMap
; -----------------------------------------
; возврат в IM1, сохранённый SP и карта назначений клавиш
; исходный диапазон #FF53..#FFFF
; смысловое имя EnableInterruptMode1AndKeyboardMap
; In: нет для #FF53
; Out: процессор в IM1, IFF остаётся прежним
; Corrupt: нет
; #FF56 — слово исходного SP обработчика прерывания
; #FF58..#FFA7 — сорок пар смещение/маска для #FCBA
; Смещение прибавляется к #FC08, маска объединяется OR с состоянием команды
; #FFA8..#FFFF — сохранённый хвост снимка, верхние 48 байтов используются #F8E4 как временная копия стека
; -----------------------------------------
; -----------------------------------------
; маски клавиш по оригинальной карте #FF58, единица означает зарегистрированное нажатие
; #FCBA вычисляет индекс (5-E)*8+D-1, читает пару смещение/маска и выполняет OR
; имена CAPS SHIFT и SYMBOL SHIFT определяются положением в аппаратной матрице
; оба символа имеют код #FF в таблице #FD41, по одному этому коду их различить нельзя
; прямых записей в #FF58..#FFA7 и загрузки этого диапазона для изменения карты
; в разобранном игровом коде не найдено, штатная процедура #FCBA только читает таблицу
; #FD69 перед каждым опросом обнуляет FC0F, остальные маски накапливаются до обработки
;
; #FC08
;       7    6    5    4    3    2    1    0
;     +----+----+----+----+----+----+----+----+
;     | Y  | 0  | I  | O  | P  | K  | L  | EN |
;     +----+----+----+----+----+----+----+----+
; Y [7] - флаг, клавиша Y, пара карты #FF9C
; 0 [6] - флаг, клавиша 0, пара карты #FF5E
; I [5] - флаг, клавиша I, пара карты #FF7C
; O [4] - флаг, клавиша O, пара карты #FF6C
; P [3] - флаг, клавиша P, пара карты #FF5C
; K [2] - флаг, клавиша K, пара карты #FF7A
; L [1] - флаг, клавиша L, пара карты #FF6A
; EN [0] - флаг, клавиша ENTER, пара карты #FF5A
;   в цифровом режиме #FC57 также переносит нажатие 0 [6] в FC0B.0, команду A
;   общий хвост #FCA6 проверяет именно 0 [6], снимает его и проверяет FC0A.7
;   при комбинации 0+CAPS SHIFT записывается специальный код #FE в FC0D
;
; #FC09
;       7    6    5    4    3    2    1    0
;     +----+----+----+----+----+----+----+----+
;     | .. | .. | SS | SP | S  | X  | M  | N  |
;     +----+----+----+----+----+----+----+----+
; .. [7] - клавиша этой картой не назначена, назначение отдельного флага не установлено
; .. [6] - клавиша этой картой не назначена, назначение отдельного флага не установлено
; SS [5] - флаг, клавиша SYMBOL SHIFT, пара карты #FF68
; SP [4] - флаг, клавиша SPACE, пара карты #FF58
; S [3] - флаг, клавиша S, пара карты #FF74
; X [2] - флаг, клавиша X, пара карты #FF86
; M [1] - флаг, клавиша M, пара карты #FF78
; N [0] - флаг, клавиша N, пара карты #FF88
;   после #FC63 младшая тетрада содержит нормализованные направления из выбранного источника
;   N [0] задаёт отрицательный крен, M [1] положительный, X [2] отрицательный тангаж, S [3] положительный
;   SP [4] увеличивает скорость, SS [5] уменьшает её, потребитель #FE01
;   настройки FC0E меняют назначение направлений, поэтому подписи букв относятся к исходной карте
;
; #FC0A
;       7    6    5    4    3    2    1    0
;     +----+----+----+----+----+----+----+----+
;     | CS | J  | G  | H  | 4  | 3  | 2  | 1  |
;     +----+----+----+----+----+----+----+----+
; CS [7] - флаг, клавиша CAPS SHIFT, пара карты #FF66
; J [6] - флаг, клавиша J, пара карты #FF8A
; G [5] - флаг, клавиша G, пара карты #FFA4
; H [4] - флаг, клавиша H, пара карты #FF9A
; 4 [3] - флаг, клавиша 4, пара карты #FF90
; 3 [2] - флаг, клавиша 3, пара карты #FF80
; 2 [1] - флаг, клавиша 2, пара карты #FF70
; 1 [0] - флаг, клавиша 1, пара карты #FF60
;   CS [7] запрашивает паузу в #72A3, это CAPS SHIFT, не SYMBOL SHIFT
;
; #FC0B
;       7    6    5    4    3    2    1    0
;     +----+----+----+----+----+----+----+----+
;     | C  | Q  | W  | E  | U  | F  | T  | A  |
;     +----+----+----+----+----+----+----+----+
; C [7] - флаг, клавиша C, пара карты #FF96
; Q [6] - флаг, клавиша Q, пара карты #FF62
; W [5] - флаг, клавиша W, пара карты #FF72
; E [4] - флаг, клавиша E, пара карты #FF82
; U [3] - флаг, клавиша U, пара карты #FF8C
; F [2] - флаг, клавиша F, пара карты #FF94
; T [1] - флаг, клавиша T, пара карты #FFA2
; A [0] - флаг, клавиша A, пара карты #FF64
;
; #FC0C
;       7    6    5    4    3    2    1    0
;     +----+----+----+----+----+----+----+----+
;     | .. | R  | D  | B  | .. | .. | .. | .. |
;     +----+----+----+----+----+----+----+----+
; .. [7] - клавиша этой картой не назначена, назначение отдельного флага не установлено
; R [6] - флаг, клавиша R, пара карты #FF92
; D [5] - флаг, клавиша D, пара карты #FF84
; B [4] - флаг, клавиша B, пара карты #FF98
; .. [3] - клавиша этой картой не назначена, назначение отдельного флага не установлено
; .. [2] - клавиша этой картой не назначена, назначение отдельного флага не установлено
; .. [1] - клавиша этой картой не назначена, назначение отдельного флага не установлено
; .. [0] - клавиша этой картой не назначена, назначение отдельного флага не установлено
;
; #FC0F
;       7    6    5    4    3    2    1    0
;     +----+----+----+----+----+----+----+----+
;     | .. | .. | .. | 7  | 6  | 8  | 5  | 9  |
;     +----+----+----+----+----+----+----+----+
; .. [7] - клавиша этой картой не назначена, назначение отдельного флага не установлено
; .. [6] - клавиша этой картой не назначена, назначение отдельного флага не установлено
; .. [5] - клавиша этой картой не назначена, назначение отдельного флага не установлено
; 7 [4] - флаг, клавиша 7, пара карты #FF8E
; 6 [3] - флаг, клавиша 6, пара карты #FF9E
; 8 [2] - флаг, клавиша 8, пара карты #FF7E
; 5 [1] - флаг, клавиша 5, пара карты #FFA0
; 9 [0] - флаг, клавиша 9, пара карты #FF6E
;
; FC0D содержит код символа целиком, это не набор флагов
; значение #FF означает отсутствие символа, #FE формируется комбинацией 0+CAPS SHIFT
; нулевые маски Z и V не ставят команду, но обновляют код символа
; -----------------------------------------

                ; проверка исходного начала фрагмента
                ASSERT $ == #FF53
                ; выбор IM1 без дополнительного разрешения прерываний
Entry:          IM 1
                RET
                ; сохранённый SP обработчика IM2, начальное значение #FFFC
SavedStack      DW #FFFC                                                        ; сохранённый SP для обработчика клавиатуры и IM1
                ; клавиша SPACE, индекс 0, смещение #01 и маска #10
KeyAssignments  DB #01, #10                                                     ; 40 пар смещение и маска, назначение клавиш в InputState
                ; клавиша ENTER, индекс 1, смещение #00 и маска #01
                DB #00, #01                                                     ; данные #FF5A..#FF5B
                ; клавиша P, индекс 2, смещение #00 и маска #08
                DB #00, #08                                                     ; данные #FF5C..#FF5D
                ; клавиша 0, индекс 3, смещение #00 и маска #40
                DB #00, #40                                                     ; данные #FF5E..#FF5F
                ; клавиша 1, индекс 4, смещение #02 и маска #01
                DB #02, #01                                                     ; данные #FF60..#FF61
                ; клавиша Q, индекс 5, смещение #03 и маска #40
                DB #03, #40                                                     ; данные #FF62..#FF63
                ; клавиша A, индекс 6, смещение #03 и маска #01
                DB #03, #01                                                     ; данные #FF64..#FF65
                ; клавиша CAPS SHIFT, индекс 7, смещение #02 и маска #80
                DB #02, #80                                                     ; данные #FF66..#FF67
                ; клавиша SYMBOL SHIFT, индекс 8, смещение #01 и маска #20
                DB #01, #20                                                     ; данные #FF68..#FF69
                ; клавиша L, индекс 9, смещение #00 и маска #02
                DB #00, #02                                                     ; данные #FF6A..#FF6B
                ; клавиша O, индекс 10, смещение #00 и маска #10
                DB #00, #10                                                     ; данные #FF6C..#FF6D
                ; клавиша 9, индекс 11, смещение #07 и маска #01
                DB #07, #01                                                     ; данные #FF6E..#FF6F
                ; клавиша 2, индекс 12, смещение #02 и маска #02
                DB #02, #02                                                     ; данные #FF70..#FF71
                ; клавиша W, индекс 13, смещение #03 и маска #20
                DB #03, #20                                                     ; данные #FF72..#FF73
                ; клавиша S, индекс 14, смещение #01 и маска #08
                DB #01, #08                                                     ; данные #FF74..#FF75
                ; клавиша Z, индекс 15, смещение #00 и маска #00
                DB #00, #00                                                     ; данные #FF76..#FF77
                ; клавиша M, индекс 16, смещение #01 и маска #02
                DB #01, #02                                                     ; данные #FF78..#FF79
                ; клавиша K, индекс 17, смещение #00 и маска #04
                DB #00, #04                                                     ; данные #FF7A..#FF7B
                ; клавиша I, индекс 18, смещение #00 и маска #20
                DB #00, #20                                                     ; данные #FF7C..#FF7D
                ; клавиша 8, индекс 19, смещение #07 и маска #04
                DB #07, #04                                                     ; данные #FF7E..#FF7F
                ; клавиша 3, индекс 20, смещение #02 и маска #04
                DB #02, #04                                                     ; данные #FF80..#FF81
                ; клавиша E, индекс 21, смещение #03 и маска #10
                DB #03, #10                                                     ; данные #FF82..#FF83
                ; клавиша D, индекс 22, смещение #04 и маска #20
                DB #04, #20                                                     ; данные #FF84..#FF85
                ; клавиша X, индекс 23, смещение #01 и маска #04
                DB #01, #04                                                     ; данные #FF86..#FF87
                ; клавиша N, индекс 24, смещение #01 и маска #01
                DB #01, #01                                                     ; данные #FF88..#FF89
                ; клавиша J, индекс 25, смещение #02 и маска #40
                DB #02, #40                                                     ; данные #FF8A..#FF8B
                ; клавиша U, индекс 26, смещение #03 и маска #08
                DB #03, #08                                                     ; данные #FF8C..#FF8D
                ; клавиша 7, индекс 27, смещение #07 и маска #10
