; P [3] - флаг, клавиша P, пара карты KeyAssignments + 4
; K [2] - флаг, клавиша K, пара карты KeyAssignments + 34
; L [1] - флаг, клавиша L, пара карты KeyAssignments + 18
; EN [0] - флаг, клавиша ENTER, пара карты KeyAssignments + 2
