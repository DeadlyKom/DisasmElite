                module Input
                module MarkModelVisibilityMask
; -----------------------------------------
; добавление маски видимости для особой модели
; исходный диапазон #FC25..#FC32
; смысловое имя MarkModelVisibilityMask
; In: HL — байт маски, IX — объект с указателем модели в +23/+24
; Out: (HL) и A дополнены маской #7F при младшем байте указателя #84, иначе #40
; Corrupt: AF
; Старший байт указателя не проверяется, это точное условие оригинального кода
; -----------------------------------------
                ; проверка исходного начала фрагмента
                ASSERT $ == #FC25
                ; проверка младшего байта модели перед выбором маски видимости
Entry:          LD A, (IX+FSpaceObject.Blueprint)
                CP #84
                LD A, #40
                JR NZ, MergeMask                                                ; переход, если младший байт модели отличается от #84, использовать маску #40

                LD A, #7F
MergeMask:      OR (HL)
                LD (HL), A
                RET

                ; проверка исходного конца фрагмента
                ASSERT $ == #FC33
                endmodule
                endmodule
