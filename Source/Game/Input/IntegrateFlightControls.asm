                module Input
                module IntegrateFlightControls
; -----------------------------------------
; интегрирование поворота, тангажа и скорости по клавишам
; исходный диапазон #FE01..#FEFD
; смысловое имя IntegrateFlightControls
; In: #FC09 — направления и скорость, #FC0E — настройки, #70E3 — текущий экран
; Out: слова #FF08/#FF0A/#FF0C обновлены, #FC09 обнулён на общем выходе
; Corrupt: HL, DE, BC, AF
; При экране >=4 управление и очистка #FC09 пропускаются
; Углы хранят знак в H.7 и модуль в остальных битах, это не дополнительный код
; Шаг крена #00FF, шаг тангажа #0066, предел достигается при H.4
; При настройке C.3 отпущенная ось замедляется на #003C либо #0024, отрицательный модуль обнуляется
; При смене направления C.2=1 немедленно обнуляет угол, C.2=0 тормозит на полный шаг
; Шаг скорости #00A0, нижний предел ноль, верхний ограничен H.5
; Часть скорости после #FEFE разделена трамплином IM2 и данными, переходы связывают фрагменты
; -----------------------------------------
                ; проверка исходного начала фрагмента
                ASSERT $ == #FE01
                ; проверка применимости управления к текущему экрану
Entry:          LD A, (FlightState.View)
                CP #04
                RET NC                                                          ; выход, если номер экрана не меньше 4, управление не изменять

                ; получение команд и настроек управления
                LD A, (InputState.FlightKeys)
                LD B, A
                LD A, (InputState.Config)
                LD C, A
                ; проверка пары команд крена
                LD HL, (InputMotion.Roll)
                BIT FLY_ROLL_N_BIT, B
                JR NZ, NegativeRoll                                             ; переход, если нажато отрицательное направление крена

                BIT FLY_ROLL_P_BIT, B
                JR NZ, PositiveRoll                                             ; переход, если нажато положительное направление крена

                ; проверка автоматического торможения отпущенного крена
                BIT INPUT_BRAKE_BIT, C
                JR Z, StoreRoll                                                 ; переход, если автоматическое торможение выключено, сохранить крен

                ; расчёт затухания модуля крена с ограничением в нуле
                LD DE, #003C
                AND A
                SBC HL, DE
                BIT 6, H
                JR Z, StoreRoll                                                 ; переход, если уменьшение не перешло через ноль, сохранить крен

                LD HL, #0000
                JP StoreRoll

                ; проверка нулевого крена перед первым положительным шагом
PositiveRoll:   LD A, H
                AND #7F
                OR L
                JR NZ, RollSign                                                 ; переход, если модуль крена ненулевой, проверить текущий знак

                LD HL, #00FF
                JP StoreRoll

                ; проверка знака для разгона либо смены направления крена
RollSign:       BIT 7, H
                JR Z, IncreaseRoll                                              ; переход, если крен положительный, увеличить его модуль

                JP ReverseRoll

                ; проверка противоположной команды и нулевого модуля крена
NegativeRoll:   BIT FLY_ROLL_P_BIT, B
                JR NZ, StoreRoll                                                ; переход, если нажаты оба направления крена, сохранить прежнее значение

                LD A, H
                AND #7F
                OR L
                JR NZ, RollNegative                                             ; переход, если модуль крена ненулевой, проверить текущий знак

                LD HL, #80FF                                                    ; отрицательный крен с модулем #00FF в знако-модульном формате
                JP StoreRoll

                ; проверка знака отрицательного направления крена
RollNegative:   BIT 7, H
                JR Z, ReverseRoll                                               ; переход, если крен положительный, требуется смена направления

                ; расчёт увеличения модуля крена с ограничением по биту 4
IncreaseRoll:   LD DE, #00FF
                ADD HL, DE
                BIT 4, H
                JR Z, StoreRoll                                                 ; переход, если предел крена по H.4 не достигнут, сохранить увеличение

                AND A
                SBC HL, DE
                JP StoreRoll

                ; проверка режима мгновенной остановки при смене направления
ReverseRoll:    BIT INPUT_STOP_BIT, C
                JR Z, BrakeRoll                                                 ; переход, если мгновенная остановка выключена, тормозить полным шагом

                LD HL, #0000
                JP StoreRoll

                ; расчёт торможения крена полным шагом перед сменой знака
BrakeRoll:      LD DE, #00FF
                AND A
                SBC HL, DE
                BIT 6, H
                JR Z, StoreRoll                                                 ; переход, если торможение не перешло через ноль, сохранить крен

                LD HL, #0000
                ; сохранение крена и переход к аналогичному расчёту тангажа
StoreRoll:      LD (InputMotion.Roll), HL
                LD HL, (InputMotion.Pitch)
                BIT FLY_PITCH_N_BIT, B
                JR NZ, NegativePitch                                            ; переход, если нажато отрицательное направление тангажа

                BIT FLY_PITCH_P_BIT, B
                JR NZ, PositivePitch                                            ; переход, если нажато положительное направление тангажа

                ; проверка автоматического торможения отпущенного тангажа
                BIT INPUT_BRAKE_BIT, C
                JR Z, StorePitch                                                ; переход, если автоматическое торможение выключено, сохранить тангаж

                ; расчёт затухания модуля тангажа с ограничением в нуле
                LD DE, #0024
                AND A
                SBC HL, DE
                BIT 6, H
                JR Z, StorePitch                                                ; переход, если уменьшение не перешло через ноль, сохранить тангаж

                LD HL, #0000
                JP StorePitch

                ; проверка нулевого тангажа перед первым положительным шагом
PositivePitch:  LD A, H
                AND #7F
                OR L
                JR NZ, PitchSign                                                ; переход, если модуль тангажа ненулевой, проверить текущий знак

                LD HL, #0066
                JP StorePitch

                ; проверка знака для разгона либо смены направления тангажа
PitchSign:      BIT 7, H
                JR Z, IncreasePitch                                             ; переход, если тангаж положительный, увеличить его модуль

                JP ReversePitch

                ; проверка противоположной команды и нулевого модуля тангажа
NegativePitch:  BIT FLY_PITCH_P_BIT, B
                JR NZ, StorePitch                                               ; переход, если нажаты оба направления тангажа, сохранить прежнее значение

                LD A, H
                AND #7F
                OR L
                JR NZ, PitchNegative                                            ; переход, если модуль тангажа ненулевой, проверить текущий знак

                LD HL, #8066                                                    ; отрицательный тангаж с модулем #0066 в знако-модульном формате
                JP StorePitch

                ; проверка знака отрицательного направления тангажа
PitchNegative:  BIT 7, H
                JR Z, ReversePitch                                              ; переход, если тангаж положительный, требуется смена направления

                ; расчёт увеличения модуля тангажа с ограничением по биту 4
IncreasePitch:  LD DE, #0066
                ADD HL, DE
                BIT 4, H
                JR Z, StorePitch                                                ; переход, если предел тангажа по H.4 не достигнут, сохранить увеличение

                AND A
                SBC HL, DE
                JP StorePitch

                ; проверка режима мгновенной остановки при смене направления
ReversePitch:   BIT INPUT_STOP_BIT, C
                JR Z, BrakePitch                                                ; переход, если мгновенная остановка выключена, тормозить полным шагом

                LD HL, #0000
                JP StorePitch

                ; расчёт торможения тангажа полным шагом перед сменой знака
BrakePitch:     LD DE, #0066
                AND A
                SBC HL, DE
                BIT 6, H
                JR Z, StorePitch                                                ; переход, если торможение не перешло через ноль, сохранить тангаж

                LD HL, #0000
                ; сохранение тангажа и проверка двух команд скорости
StorePitch:     LD (InputMotion.Pitch), HL
                LD HL, (InputMotion.Speed)
                LD DE, #00A0
                BIT FLY_SPEED_BIT, B
                JR NZ, @Game.Input.InterruptGateAndAcceleration.Accelerate      ; переход, если нажата команда увеличения скорости

                BIT FLY_BRAKE_BIT, B
                JR Z, @Game.Input.ClampAndStoreFlightSpeed.StoreSpeed           ; переход, если команда уменьшения скорости отсутствует, сохранить скорость

                ; расчёт уменьшения скорости и переход к проверке нижнего предела
                AND A
                SBC HL, DE
                JR Game.Input.ClampAndStoreFlightSpeed.Entry
                ; проверка исходного конца фрагмента
                ASSERT $ == #FEFE
                endmodule
                endmodule
