                module Input
                module ScanKeyboardMatrix
; -----------------------------------------
; опрос восьми рядов клавиатуры Spectrum
; исходный диапазон #FD69..#FE00
; смысловое имя ScanKeyboardMatrix
; In: нет, аппаратные порты клавиатуры #xxFE
; Out: InputState.LastKey — последний по порядку сканирования символ либо #FF, поля клавиш дополнены масками
; Corrupt: HL, DE, BC, AF
; InputState.NumberKeys обнуляется перед опросом цифровых направлений, InputState.SystemKeys..InputState.ChartKeys целиком не очищаются
; B циклически переносит нулевой бит выбора ряда, каждый IN читает пять младших битов
; RRA переносит состояние одной клавиши в C, Game.Input.SetPressedKeyAssignment.Entry устанавливает её назначение
; После восьми рядов Game.Input.FinishKeyboardRowAndSelectJoystick.Entry/Game.Input.ResetDemoAndNormalizeControls.DigitalAxes нормализуют управление
; с LaserTariffs размещены параметры и таблицы слогов, три байта #FE после GalaxyFormat поддерживают IM2
; -----------------------------------------
                ; проверка исходного начала фрагмента
                ASSERT $ == #FD69
                ; очистка цифрового регистра и установка отсутствующего символа #FF
Entry:          XOR A
                LD (InputState.NumberKeys), A
                DEC A
                LD (InputState.LastKey), A
                ; подготовка восьми рядов матрицы клавиатуры
RowPort         EQU $ + 1                                                       ; операнд LD BC, демо заменяет порт адресом восьми виртуальных рядов
                LD BC, #7FFE
                LD D, #08
                ; выбор очередного ряда и преобразование активного нуля в единицу
ScanRow:        RLC B
KeyReadTail     EQU $                                                           ; первые два байта чтения ряда, демо заменяет их CPL и INC BC
                IN A, (C)
                AND #1F
                XOR #1F
                LD E, #05
                ; проверка одной клавиши переносом в C и обработка назначения
ScanKey:        RRA
                CALL C, Game.Input.SetPressedKeyAssignment.Entry                ; вызов, если клавиша нажата, установить её назначение
                DEC E
                JR NZ, ScanKey                                                  ; переход, если в ряду остались непроверенные клавиши

                JP Game.Input.FinishKeyboardRowAndSelectJoystick.Entry

                ; четыре табличных байта перед параметрами информационных экранов
LaserTariffs    DB #05, #06, #0D, #0E                                           ; четыре номера тарифов оборудования для лазеров типов 1..4
                ; параметры экрана пилота, адрес передаётся из Game.Menus.OpenCommanderStatus.Entry
StatusFormat    DB #CA, #71, #89, #21, #21, #61, #31, #20                       ; параметры атрибутов экрана командира
                ; параметры дополнительного экрана, адрес передаётся из Game.Menus.PrintStatusFieldAndCargoScreen.Entry
CargoFormat     DB #79, #21, #20                                                ; параметры атрибутов дополнительного экрана
                ; двухсимвольные слоги для токенов от #D7, область далее пересекается с базой NameSyllables
TextSyllables   DB #40, #40, #41, #42, #4F, #55, #53, #45                       ; двухсимвольные слоги описаний, начало перед общей таблицей имён
                DB #49, #54, #49, #4C, #45, #54, #53, #54                       ; данные #FDA1..#FDA8
                DB #4F, #4E, #4C, #4F, #4E, #55, #54, #48                       ; данные #FDA9..#FDB0
                DB #4E, #4F                                                     ; данные #FDB1..#FDB2
                ; 32 двухсимвольных слога для имён планет и токенов #80..#9F
NameSyllables   DB #41, #4C, #4C, #45, #58, #45, #47, #45                       ; 32 пары символов для генератора имён и текстовых токенов
                DB #5A, #41, #43, #45, #42, #49, #53, #4F                       ; данные #FDBB..#FDC2
                DB #55, #53, #45, #53, #41, #52, #4D, #41                       ; данные #FDC3..#FDCA
                DB #49, #4E, #44, #49, #52, #45, #41, #3F                       ; данные #FDCB..#FDD2
                DB #45, #52, #41, #54, #45, #4E, #42, #45                       ; данные #FDD3..#FDDA
                DB #52, #41, #4C, #41, #56, #45, #54, #49                       ; данные #FDDB..#FDE2
                DB #45, #44, #4F, #52, #51, #55, #41, #4E                       ; данные #FDE3..#FDEA
                DB #54, #45, #49, #53, #52, #49, #4F, #4E                       ; данные #FDEB..#FDF2
                ; сохранённые табличные байты между слогами и параметрами сравнения галактики
CaptionFormat   DB #B1, #42, #3A, #52, #52, #54, #92, #70                       ; параметры атрибутов строки подписи
                ; данные сравнения галактики, адрес используется Game.Menus.CompareSystemSeedToGalaxyBase.Entry
GalaxyFormat    DB #D9, #F1, #F0                                                ; параметры атрибутов строки сравнения семени галактики
                ; три байта #FE после GalaxyFormat, последние два дают адрес InterruptGate при байте шины #FF
                DB #FE, #FE, #FE                                                ; данные #FDFE..#FE00
                ; проверка исходного конца фрагмента
                ASSERT $ == #FE01
                endmodule
                endmodule
