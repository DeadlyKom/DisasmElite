                ifndef _LOADER_BOOTSTRAP_
                define _LOADER_BOOTSTRAP_
; -----------------------------------------
; перенос загрузчика из строки REM в исходную область #C800
; In:
;   BC - адрес этой процедуры, вычисленный BASIC как PROG + 5
; Out:
;   управление передаётся Load, при отсутствии файла возможен возврат в BASIC
; Corrupt:
;   HL, DE, BC, AF
; Note:
;   15 байт до копируемых данных, затем 266 байт по адресу #C800
;   BC получает адрес операнда USR по соглашению Spectrum ROM
; -----------------------------------------
Bootstrap:      ; расчёт адреса переносимых данных относительно точки входа
                LD HL, #000F
                ADD HL, BC
                ; копирование блока загрузки выше основной области BASIC
                LD DE, CODE_BASE
                LD BC, CODE_SIZE
                LDIR
                JP Load

                endif                                                           ; ~_LOADER_BOOTSTRAP_
