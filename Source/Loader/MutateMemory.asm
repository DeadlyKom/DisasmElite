                ifndef _LOADER_MUTATE_MEMORY_
                define _LOADER_MUTATE_MEMORY_
; -----------------------------------------
; снятие побитового кодирования файла игры перед входом по адресу Loader.GAME_START
; на диске отдельные биты команд и данных изменены, эта процедура возвращает их
; например, команда записи FSpaceObject.Y.Fraction в Game.Objects.InitializeIntroModel.Entry
; на диске представлена байтами CD 77 03, при прямом исполнении это CALL #0377
; маска #10 возвращает DD 77 03, действующую команду LD (IX + FSpaceObject.Y.Fraction), A
; по действию это маскировка содержимого, размер файла при этом не меняется
; сама процедура не проверяет подлинность диска или контрольную сумму
; назначение именно защиты от копирования из этих команд не установлено
; In:
;   загруженное дисковое представление игры и неизменный генератор по Loader.GAME_RANDOM
;   начальное состояние генератора в трёх словах GalaxyState.WorkingSeed, (GalaxyState.WorkingSeed + FSystemSeed.GovBits), (GalaxyState.WorkingSeed + FSystemSeed.MixLow)
;   для этого образа шесть байтов состояния равны BC 57 82 0A 63 AD
; Out:
;   изменены выбранные байты #5B00..#FFFF, кроме #C800..#CFFF
;   BC = #00xx, где C содержит последнюю циклическую битовую маску
;   шесть байтов состояния GalaxyState.WorkingSeed равно D1 AD 4D A7 CC 45 для этого образа
; Corrupt:
;   HL, DE, BC, AF
; Note:
;   B начинает с нуля, DJNZ меняет его от 0 к 255 и далее до 0 за 256 итераций
;   C начинает с #01, перед каждой попыткой маска вращается, начиная с #80
;   генератор выдаёт следующее слово и обновляет собственные три слова
;   адреса с переполнением HL + Loader.MUTATE_BASE отбрасываются без уменьшения B
;   при таком повторе маска и состояние генератора уже изменены
;   попадание в #C800..#CFFF уменьшает B, но память не изменяет
;   исключённая область содержит работающий загрузчик и обменный блок
;   для данного образа 398 вызовов состоят из 142 повторов и 256 итераций
;   из 256 итераций 11 пропускают исключённую область, 245 выполняют XOR
;   все 245 изменяемых адресов в этой последовательности различны
;
;   одна из 245 записей меняет текущее состояние генератора по (GalaxyState.WorkingSeed + FSystemSeed.GovBits)
;   в 134-й завершённой итерации #06 XOR #20 даёт #26
;   следующие вызовы генератора учитывают это изменение
;   это текущий байт состояния, исходный дисковый байт по (GalaxyState.WorkingSeed + FSystemSeed.GovBits) равен #82
;
;   XOR обратим при тех же адресах и масках, #DD XOR #10 снова даёт #CD
;   повторный вызов на RAM после загрузки начинает с другого состояния
;   восстановление начальных семян позволяет повторить выбор адресов и масок
;   однако процедура снова оставляет конечные семена вместо дисковых
;   сборка использует 244 сохранённые поправки остальных байтов
;   все шесть исходных байтов генератора уже сохранены в исходниках игры
;   таблица описана в Tools/Disasm/Disk/Keys/GameEncoding.lua
;   её применение при сборке описано в Tools/pack.lua
; -----------------------------------------
MutateMemory:   LD BC, #0001
.Choose         ; обновление одноразрядной маски перед каждой попыткой выбора
                RRC C
                ; обновление генератора и получение следующего слова в HL
                CALL GAME_RANDOM
                ; расчёт адреса в области снимка, начиная с Loader.MUTATE_BASE
                LD DE, MUTATE_BASE
                ADD HL, DE
                JR C, .Choose                                                   ; переход, если адрес вышел за #FFFF

                ; проверка исключённой области загрузчика и обменного блока
                LD A, H
                AND #F8
                XOR #C8
                JR Z, .Next                                                     ; переход, если адрес находится в #C800..#CFFF

                ; изменение выбранного бита без затрагивания остальных битов
                LD A, C
                XOR (HL)
                LD (HL), A
.Next           DJNZ .Choose

                RET

                endif                                                           ; ~_LOADER_MUTATE_MEMORY_
