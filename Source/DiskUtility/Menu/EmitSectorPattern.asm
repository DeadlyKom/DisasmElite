; -----------------------------------------
; развёртывание шаблона дорожки из пар количество/байт
; исходный диапазон #CE42..#CE54
; In:
;   IX, выходной указатель
;   шаблон DiskUtility.Menu.FormatPattern, пары количество и значение
; Out:
;   HL, байт после завершителя #99,#99
;   IX, конец развёрнутого сектора либо граница Memory.Attributes
; Corrupt:
;   HL, DE, BC, AF, IX
; Note:
;   B получает количество, D значение, нулевое количество означает 256 повторов.
;   Завершителем служит только пара #99,#99, пара с количеством #99 и другим байтом допустима.
;   EmitFillByte ограничивает запись, но весь шаблон всё равно просматривается до завершителя.
; -----------------------------------------
EmitSectorData: LD HL, FormatPattern
ReadPatternRun: LD B, (HL)
                INC HL
                LD D, (HL)
                INC HL
                LD A, B
                CP #99
                JR NZ, EmitPatternRun                                           ; переход, если количество отличается от #99 и пару требуется вывести

                CP D
                RET Z                                                           ; выход, если количество и значение одновременно равны #99 и шаблон завершён

EmitPatternRun: CALL EmitFillByte
                JR ReadPatternRun
