TrackByte       EQU 0                                                           ; нулевое смещение выходного байта, IX является курсором потока дорожки
; -----------------------------------------
; повторение байта до исчерпания счётчика либо достижения #5800
; исходный диапазон #CE35..#CE41
; In:
;   DE, D содержит повторяемый байт
;   BC, B содержит количество, 0 означает 256
;   IX, указатель буфера ниже #5800
; Out:
;   IX, первый незаписанный адрес
;   B, остаток количества
;   HL, DE, C сохранены
; Corrupt:
;   BC, AF, IX
; Note:
;   Проверяется точное равенство IXH=#58, значения выше #58 отдельно не отсекаются.
;   При достижении границы B сохраняет остаток, при обычном окончании B=0.
;   Кроме обычных CALL это непосредственное продолжение BuildTrackData после его последнего CALL.
; -----------------------------------------
EmitFillByte:   LD A, IXH
                CP #58
                RET Z                                                           ; выход, если IX достиг страницы #5800 и дальнейшая запись запрещена

                LD (IX + TrackByte), D
                INC IX
                DJNZ EmitFillByte

                RET
