; -----------------------------------------
; обмен одним сектором с проверкой фактически переданных 256 байтов
; исходный диапазон #C8B6..#C8DE
; In:
;   HL, адрес буфера
;   DE, адрес обработчика потока
;   стек, адрес возврата указывает на номер сектора
;   #C8CB, команда #84 либо #A4
; Out:
;   HL, исходный адрес буфера
;   DE, исходный адрес буфера
;   AF, Z=1, C=0 при буфере без перехода через #FFFF
;   возврат увеличен на один
; Corrupt:
;   DE, BC, AF
; Note:
;   EX (SP),HL извлекает встроенный номер сектора и сдвигает адрес возврата за него.
;   Порт #5F получает номер, порт #1F получает выбранную ранее команду.
;   Сначала из конечного HL вычитается #0100, затем сохранённое начало буфера.
;   Повторяется вся команда, пока разность не станет нулевой, лимита повторов нет.
;   Заимствование первого SBC не сбрасывается перед вторым, нужен обычный непереходящий буфер.
;   Регистры внешнего шлюза TR-DOS не объявлены сохранёнными без его конкретного ПЗУ.
; -----------------------------------------
                ; обновление адреса обработчика и извлечение номера сектора из потока вызова
SectorTransfer: LD (TransferCall), DE
                EX (SP), HL
                LD A, (HL)
                INC HL
                EX (SP), HL
                LD (TransferID), A
                ; повтор команды с восстановлением исходного адреса буфера
RetryTransfer:  PUSH HL
                CALL @Game.Disk.LoadDiskMenuOverlay.CallDosInline               ; передача встроенной пары порт/значение через шлюз ПЗУ TR-DOS
                DB #5F                                                          ; порт номера сектора
TransferID      DB #01                                                          ; номер сектора, извлекается из потока после CALL
                CALL @Game.Disk.LoadDiskMenuOverlay.CallDosInline               ; передача встроенной пары порт/значение через шлюз ПЗУ TR-DOS
                DB #1F                                                          ; порт команды контроллера
TransferCmd     DB #84                                                          ; команда #84 чтение либо #A4 запись
                POP HL
                PUSH HL
TransferCall    EQU $ + 1                                                       ; адрес обработчика потока в операнде следующего CALL
                CALL @Game.Disk.LoadDiskMenuOverlay.ReadTrackBytes              ; приём потока контроллера через ПЗУ TR-DOS
                LD DE, #0100
                AND A
                SBC HL, DE
                POP DE
                PUSH DE
                SBC HL, DE
                POP HL
                JR NZ, RetryTransfer                                            ; переход, если обработчик потока завершился с длиной, отличной от 256 байтов

                RET
