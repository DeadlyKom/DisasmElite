; -----------------------------------------
; вывод сообщения об отсутствии места и ожидание подтверждения
; исходный диапазон #CD8E..#CD9E
; In:
;   режим #D420=1 для строки NO SPACE!
; Out:
;   AF, A=0/Z=1 после клавиши
; Corrupt:
;   HL, DE, BC, AF
; Note:
;   Основной вход задаёт курсор в строке 3 и строку #C859.
;   Вход #CD97 печатает произвольную строку HL, затем продолжает ожидание.
;   Вход #CD9A только ждёт клавишу и возвращает XOR A, используется также CopyMenu.
; -----------------------------------------
ShowNoSpace:    LD HL, #0300
                LD (TextPosition), HL
                LD HL, LegacyNoSpace
                ; вывод строки с последующим ожиданием клавиши
PrintAndWait:   CALL @Game.Text.PrintDescriptionString.Entry                    ; вывод строки HL до нулевого байта штатным обработчиком игры
                ; возврат нулевого результата после подтверждения
WaitAndReturn:  CALL WaitMenuKey
                XOR A
                RET
