; -----------------------------------------
; выбор команды записи сектора и обработчика выходного потока
; исходный диапазон #C8A1..#C8AA
; In:
;   HL, адрес 256-байтового буфера
;   поток после CALL, номер сектора
; Out:
;   HL, исходный адрес буфера
;   DE, исходный адрес буфера
;   AF, Z=1 при полном обмене
; Corrupt:
;   DE, BC, AF
; Note:
;   #C8CB получает команду #A4, #C8CF получает адрес WriteFdcStream (#CA3B).
;   Переход SectorTransfer сохраняет исходный адрес буфера и повторяет обмен до длины 256 байтов.
;   Отдельного ограничения числа повторов и возврата ошибки здесь нет.
; -----------------------------------------
WriteSector:    LD A, #A4
                LD (TransferCmd), A
                LD DE, WriteFdcStream
                JR SectorTransfer
