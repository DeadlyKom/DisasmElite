; изменяемые сообщения служебного меню копирования
; исходный диапазон #CEB0..#CF1D
; In:
;   #CF1E и #CF9C заполняют числовые поля и печатают строки
; Out:
;   110 байтов данных
; Corrupt:
;   нет
; Note:
;   Первая строка по #CEB0 дополняется цифрами с #CEB1 и завершается токеном #D3/нулём.
;   #CECF начинает сообщение о недостающем количестве, трёхзначное поле находится в #CEEC.
;   #CEFA содержит запрос подтверждения Y/N.
;   Байты выше ASCII являются токенами штатного текстового обработчика игры.
; -----------------------------------------
