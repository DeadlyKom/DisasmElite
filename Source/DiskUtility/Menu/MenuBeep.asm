; -----------------------------------------
; короткий звуковой сигнал 65 переключениями бита динамика
; исходный диапазон #CC30..#CC40
; In:
;   BC, исходный B задаёт первую задержку, B=0 означает 256 шагов
; Out:
;   все регистры и флаги сохранены
; Corrupt:
;   нет
; Note:
;   AF и BC сохраняются, C=#41 задаёт 65 переключений бита #10 порта #FE.
;   После первой задержки B=0, все последующие DJNZ выполняют по 256 итераций.
;   Другие биты выходного A равны нулю, сигнал также устанавливает чёрный бордюр.
;   Последнее нечётное переключение оставляет бит #10 единичным.
; -----------------------------------------
MenuBeep:       PUSH AF
                PUSH BC
                XOR A
                LD C, #41
ToneDelay:      DJNZ ToneDelay

                XOR BEEP_SPK_MASK
                OUT (#FE), A
                DEC C
                JR NZ, ToneDelay                                                ; переход, если счётчик 65 переключений ещё не исчерпан

                POP BC
                POP AF
                RET
