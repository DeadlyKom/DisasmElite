; -----------------------------------------
; сохранённые десять байтов после конечного RET служебной подготовки
; исходный диапазон #CFF6..#CFFF
; In:
;   входящие переходы и чтения этого хвоста в проверенном коде не обнаружены
; Out:
;   байты #36,#36,#36,#36,0,#41,#41,#41,#45,#F1 сохранены
; Corrupt:
;   нет
; Note:
;   RET по #CFF5 переходит в #C500, последовательное исполнение этого хвоста из ConfirmCopy отсутствует.
;   Статического основания выбрать конкретный машинный вход в этих десяти байтах нет.
;   Поэтому данные сохраняются DB без утверждения о глобальной недостижимости или историческом назначении.
; -----------------------------------------
PreservedTail   DB #36, #36, #36, #36, #00, #41, #41, #41, #45, #F1
