; -----------------------------------------
; строка NO SPACE! с перекрывающейся сохранённой последовательностью чтения сектора
; исходный диапазон #C859..#C87C
; In:
;   HL=#C859, режим вывода #D420=1 для подтверждённого текстового пути
;   для машинного прочтения #C860 отдельный вход не найден
; Out:
;   строка заканчивается нулём #C861
;   условный машинный путь читает сектор в #4800 и переходит JP (HL)
; Corrupt:
;   для текстовых данных нет, при машинном прочтении HL, DE, BC, AF
; Note:
;   #D470 переводит #E9 через таблицу диграмм #FD99, пара #FDBD содержит CE.
;   В режиме #D420=1 байты #C859..#C861 выводят NO SPACE! и завершают строку.
;   При #D420=0 тот же #E9 относится к другой таблице, поэтому режим является частью контракта.
;   Байт #C85F одновременно допускает JP (HL), #C860..#C862 допускают LD HL,0.
;   Прямые входящие переходы на #C85F/#C860 в проверенном коде не обнаружены.
;   Следующий связный машинный фрагмент читает дорожку #0E, сектор 4 в #4800.
;   Цикл XOR использует #BE00, #BEFF, #BEFE ... #BE01 и 256 байтов #4800..#48FF.
;   После оборота младших байтов HL=#4800, DE=#BE00, JP (HL) передаёт управление в буфер.
;   Это описание операций сохранённых байтов, оно не доказывает вызов этого пути или пригодность сектора.
;   DB в начале необходим из-за доказанного текстового чтения и перекрытия границ инструкций.
; -----------------------------------------
LegacyNoSpace   DB #4E, #4F, #20, #53, #50, #41, #E9, #21, #00, #00
                ; сохранённый машинный фрагмент после перекрывающейся строки, вход не установлен
LegacyRead:     CALL @Game.Disk.BlackAttributesAndOverlayState.Entry            ; очистка 768 атрибутных байтов, на выходе HL=#5B00 и BC=0
                LD A, #0E
                CALL SetTrackSide
                LD HL, DiskBuffer.Blank
                CALL ReadSector
                DB #04                                                          ; номер сектора после CALL, SectorTransfer изменяет адрес возврата
                LD DE, Game.Math.SquareLo
                ; преобразование страницы экрана с обратным обходом таблицы
LegacyXor:      LD A, (DE)
                XOR (HL)
                LD (HL), A
                INC L
                DEC E
                JR NZ, LegacyXor                                                ; переход, если младший байт источника ещё не обошёл все 256 значений

                JP (HL)
