DigitByte       EQU 0                                                           ; нулевое смещение текущей цифры, IX является курсором строки
; -----------------------------------------
; выделение одной десятичной цифры повторным вычитанием веса
; исходный диапазон #CEA0..#CEAF
; In:
;   HL, текущий остаток числа
;   DE, ненулевой десятичный вес
;   IX, адрес выходного символа
; Out:
;   HL, остаток меньше DE
;   DE и BC сохранены
;   AF, A сохранён
;   IX увеличен на 1
; Corrupt:
;   HL, AF, IX
; Note:
;   Символ начинается с '/', перед каждым вычитанием увеличивается.
;   Вычитание продолжается до заимствования, затем последний вес возвращается ADD HL,DE.
;   При обычном десятичном вызове получается ASCII '0'..'9', отдельного ограничения цифры нет.
;   Нулевой вес привёл бы к бесконечному циклу, все штатные входы задают ненулевой.
; -----------------------------------------
DecimalDigit:   LD (IX + DigitByte), #2F
SubtractWeight: INC (IX + DigitByte)                                            ; ASCII-цифра, число вычитаний текущего десятичного веса
                AND A
                SBC HL, DE
                JR NC, SubtractWeight                                           ; переход, если текущий остаток ещё не меньше десятичного веса

                INC IX
                ADD HL, DE
                RET
