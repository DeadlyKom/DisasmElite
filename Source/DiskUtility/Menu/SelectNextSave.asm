; -----------------------------------------
; выбор следующего командира с проверкой конца списка
; исходный диапазон #CB79..#CB95
; In:
;   #DA70/#DA71, выбранная запись и начало страницы
; Out:
;   B сохранён, C получает новый номер при успешном перемещении
;   выбор увеличен, при необходимости список перерисован
; Corrupt:
;   HL, DE, BC, AF
; Note:
;   GetSaveRecord вызывается для текущей и следующей записи, нулевое имя запрещает движение.
;   Порог прокрутки равен начало+24, RET NC включает равенство выбранного номера порогу.
;   Таким образом исходный код прокручивает только при выбранном номере больше начало+24.
;   При прокрутке новое начало равно старому+8, общий хвост #CB95 доступен из PreviousSave.
; -----------------------------------------
NextSave:       LD HL, SaveSelection
                LD A, (HL)
                PUSH HL
                CALL GetSaveRecord
                POP HL
                RET Z                                                           ; выход, если текущая запись пуста

                LD A, (HL)
                INC A
                PUSH HL
                CALL GetSaveRecord
                POP HL
                RET Z                                                           ; выход, если следующая запись пуста и достигнут конец списка

                INC (HL)
                LD C, (HL)
                INC HL
                LD A, (HL)
                ADD A, #18
                CP C
                RET NC                                                          ; выход, если новый индекс не больше начала страницы плюс 24

                SUB #10
StorePage:      LD (HL), A
