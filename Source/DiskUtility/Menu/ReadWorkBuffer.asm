; -----------------------------------------
; чтение сектора в общий буфер DiskBuffer.Work
; исходный диапазон #C8AB..#C8AD
; In:
;   поток после CALL, однобайтовый номер сектора
;   контроллер, выбранная дорожка
; Out:
;   HL=DiskBuffer.Work после штатного завершения, возврат пропускает номер сектора
; Corrupt:
;   HL, DE, BC, AF
; Note:
;   Задаёт только HL и без RET продолжает ReadSector, общий контракт SectorTransfer действует полностью.
; -----------------------------------------
ReadWork:       LD HL, DiskBuffer.Work
                ; JP ReadSector, продолжение в ReadSector.asm
