; -----------------------------------------
; запись сектора из общего буфера DiskBuffer.Work
; исходный диапазон #C89E..#C8A0
; In:
;   поток после CALL, однобайтовый номер сектора
;   контроллер, выбранная дорожка
; Out:
;   HL=DiskBuffer.Work после штатного завершения, возврат пропускает номер сектора
; Corrupt:
;   HL, DE, BC, AF
; Note:
;   Задаёт только HL и без RET продолжает WriteSector, общий контракт SectorTransfer действует полностью.
; -----------------------------------------
WriteWork:      LD HL, DiskBuffer.Work
                ; JP WriteSector, продолжение в WriteSector.asm
