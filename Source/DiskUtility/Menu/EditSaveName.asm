; -----------------------------------------
; ввод имени сохранения и удаление конечных пробелов либо нулей
; исходный диапазон #CC72..#CCB1
; In:
;   текущий командир #D054, клавиатура
; Out:
;   при SPACE переход #CC65
;   иначе переход SaveCommander с C=#20
; Corrupt:
;   HL, DE, BC, AF
; Note:
;   Курсор устанавливается в строку 3, выводится запрос имени.
;   #DED0..#DED7 предварительно заполнены пробелами, #E3CC получает предел 8 символов.
;   После ввода отдельно проверяется SPACE, его флаги сохраняются до обработки окончания.
;   #DED8 получает расширение C, указатель движется назад по завершающим пробелам.
;   Ветвь пробелов не уменьшает B, отдельного восьмибайтового предела для неё в оригинале нет.
;   Нулевые байты заменяются пробелами с уменьшением B, первый ненулевой непробельный байт завершает поиск.
; -----------------------------------------
EditSaveName:   LD HL, #0300
                LD (TextPosition), HL
                LD HL, NamePrompt
                CALL @Game.Text.PrintDescriptionString.Entry                    ; вывод строки HL до нулевого байта штатным обработчиком игры
                LD HL, SaveName.Extension
                LD BC, #0820
PadName:        DEC HL
                LD (HL), C
                DJNZ PadName

                LD B, #08
                LD A, #20
                CALL @Game.Charts.BeginTextInput.Entry                          ; редактирование имени в буфере с ограничением восьми символов
                LD A, #7F
                IN A, (#FE)
                AND 1 << KEYBOARD_SP_BIT
                PUSH AF
                CALL @Game.Text.PrintInlineToken.Entry                          ; обработка следующего байта как встроенного управляющего кода
                DB #08                                                          ; управляющий код текста, адрес возврата пропускает этот байт
                LD BC, #0820
                LD HL, SaveName.Extension
                LD (HL), #43
TrimName:       DEC HL
                LD A, (HL)
                CP C
                JR Z, TrimName                                                  ; переход, если предыдущий байт является пробелом и поиск окончания продолжается

                AND A
                JR NZ, CheckNameAbort                                           ; переход, если найден ненулевой байт, отличный от пробела

                LD (HL), C
                DJNZ TrimName

CheckNameAbort: POP AF
                JR Z, BackupPilot                                               ; переход, если во время проверки SPACE был нажат и ввод отменяется

                JR SaveCommander
