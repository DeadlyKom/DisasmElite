; -----------------------------------------
; выбор предыдущего командира с прокруткой страницы на восемь записей
; исходный диапазон #CB69..#CB78
; In:
;   #DA70/#DA71, выбранная запись и начало страницы
; Out:
;   выбор уменьшен, при необходимости список перерисован
;   BC сохранён
; Corrupt:
;   HL, DE, AF
; Note:
;   INC/DEC проверяют исходный ноль без изменения выбранного номера.
;   Если новый номер меньше начала страницы, из начала вычитается 8.
;   Общий хвост #CB95 записывает начало страницы и продолжает DrawSaveNames.
; -----------------------------------------
PreviousSave:   LD HL, SaveSelection
                INC (HL)
                DEC (HL)
                RET Z                                                           ; выход, если уже выбрана первая запись и уменьшать индекс нельзя

                DEC (HL)
                LD A, (HL)
                INC HL
                CP (HL)
                RET NC                                                          ; выход, если новая выбранная запись не предшествует началу страницы

                LD A, (HL)
                SUB #08
                JR StorePage
