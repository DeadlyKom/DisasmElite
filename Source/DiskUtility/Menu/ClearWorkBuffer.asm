; -----------------------------------------
; очистка рабочего буфера и области непосредственно под текущим стеком
; исходный диапазон #CA48..#CA5E
; In:
;   BC, число байтов после первого, значение должно быть ненулевым
; Out:
;   BC=0
;   область DiskStream длиной исходный BC + 1 обнулена
;   2049 байтов SP-#801..SP-1 обнулены
; Corrupt:
;   HL, DE, BC, AF
; Note:
;   Первый ноль распространяется вперёд LDIR, фактический объём равен исходному BC+1.
;   После LDIR B=C=0, первый байт SP-1 получает B.
;   LD B,8 при C=0 задаёт #800 копирований LDDR, ещё один ноль уже записан.
;   Текущий адрес возврата по SP и выше не затрагивается.
;   BuildSaveList очищает от DiskStream до DiskBuffer.Catalog - 1
;   CopyMenu включает также восемь секторов DiskBuffer.Catalog
; -----------------------------------------
                ; очистка буфера с распространением первого нулевого байта
ClearWorkArea:  LD HL, DiskStream
                LD DE, DiskStream + 1
                LD (HL), #00
                LDIR
                LD HL, #FFFF
                ADD HL, SP
                LD E, L
                LD D, H
                DEC DE
                LD (HL), B
                LD B, #08
                LDDR
                RET
