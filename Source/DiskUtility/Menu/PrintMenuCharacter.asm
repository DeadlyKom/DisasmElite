; -----------------------------------------
; вывод одного символа с сохранением указателя списка и счётчиков
; исходный диапазон #CBD3..#CBDA
; In:
;   AF, A содержит символ либо управляющий код
; Out:
;   HL и BC сохранены
; Corrupt:
;   DE, AF
; Note:
;   Обёртка #D425 сохраняет HL и BC на стеке, DE и AF обработчиком не восстанавливаются.
;   Используется через CALL, а также как общий хвост DrawSaveNames.
; -----------------------------------------
PrintMenuChar:  PUSH BC
                PUSH HL
                CALL @Game.Text.PrintMainToken.Entry                            ; вывод символа или управляющего кода из A
                POP HL
                POP BC
                RET
