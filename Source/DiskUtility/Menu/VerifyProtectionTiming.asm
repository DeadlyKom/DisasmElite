; -----------------------------------------
; проверка измеренного маркера случайной дорожки по сохранённой таблице
; исходный диапазон #C8DF..#C929
; In:
;   #4861..#4878, двенадцать слов ожидаемого измерения
;   #E07D/#E07F, состояние предыдущей проверки
; Out:
;   #E07D/#E07E=0 и #E07F=#FF при допуске
;   при повторном нарушении переход на #0000
; Corrupt:
;   HL, DE, BC, AF
; Note:
;   После задержки R сводится по модулю 12 и увеличивается, выбирается дорожка 1..12.
;   Табличный адрес равен #485F+2*дорожка, сравнивается только старший байт слова.
;   Допускается абсолютная разность измеренного и табличного старшего байта меньше 3.
;   При нарушении звучит MenuBeep, флаг #E07F очищается, счётчик #E07D увеличивается.
;   Если прежний счётчик был нулём, выбирается новая дорожка, иначе выполняется JP #0000.
;   Прямой вызывающий переход этого входа в проверенном коде не обнаружен.
; -----------------------------------------
                ; расчёт номера дорожки из регистра регенерации
VerifyTiming:   LD A, #C0
                LD B, A
RandomDelay:    DJNZ RandomDelay

                LD A, R
ReduceTrack:    SUB #0C
                JR NC, ReduceTrack                                              ; переход, если после вычитания 12 остаток ещё не стал отрицательным

                ADD A, #0D
                LD (DiskBuffer.TimingTrack), A
                PUSH AF
                ADD A, A
                ADD A, #5F
                LD L, A
                LD H, #48
                LD E, (HL)
                INC HL
                LD D, (HL)
                POP AF
                PUSH DE
                CALL SetTrackSide
                CALL ReadTrackMark
                POP HL
                LD A, H
                SUB D
                JR NC, CheckDrift                                               ; переход, если табличное значение не меньше измеренного и модуль разности уже получен

                NEG
CheckDrift:     CP #03
                JR C, AcceptMark                                                ; переход, если абсолютная разность старших байтов меньше 3 и маркер допустим

                CALL MenuBeep
                LD HL, ProtectPassed
                LD (HL), #00
                DEC HL
                DEC HL
                LD A, (HL)
                INC (HL)
                AND A
                JR Z, VerifyTiming                                              ; переход, если прежний счётчик нарушений нулевой и разрешена повторная проверка

                JP @DiskUtility.ResetRom

                ; обновление состояния успешной проверки
AcceptMark:     LD HL, #0000
                LD (TimingFailures), HL
                LD A, #FF
                LD (ProtectPassed), A
                RET
