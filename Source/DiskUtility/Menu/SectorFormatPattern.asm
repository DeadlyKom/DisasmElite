; -----------------------------------------
; шаблон байтовых серий для команды форматирования дорожки
; исходный диапазон #CE55..#CE76
; In:
;   EmitSectorData читает пары количество/значение
; Out:
;   34 байта данных, 17 пар с завершителем
; Corrupt:
;   нет
; Note:
;   Поток содержит промежуток #4E, синхронизацию 0/#F5, маркер адреса #FE и маркер данных #FB.
;   Серии #F7 передаются контроллеру как специальные маркеры формирования CRC.
;   Изменяемые поля #CE5E дорожка, #CE62 номер сектора, #CE64 код размера.
;   #CE6F задаёт заполнитель серии данных из 256 байтов, #CE73 длину последнего промежутка.
;   Пара #99,#99 завершает шаблон и в выходной поток не попадает.
; -----------------------------------------
FormatPattern   DB #0A, #4E, #0C, #00, #03, #F5, #01, #FE                       ; пары количество и значение, начало шаблона дорожки
                DB #01
TrackID         DB #40                                                          ; байт дорожки внутри серии идентификатора
SidePattern     DB #01, #00, #01                                                ; серии стороны и количества байтов номера сектора
SectorID        DB #00                                                          ; байт номера сектора внутри серии идентификатора
SizePattern     DB #01                                                          ; длина серии кода размера сектора
SectorSize      DB #01                                                          ; код размера сектора в идентификаторе
DataPattern     DB #01, #F7, #16, #4E, #0C, #00, #03, #F5                       ; серии CRC, промежутка, синхронизации и маркера данных
                DB #01, #FB
SectorFill      DB #00                                                          ; значение заполнителя 256 байтов данных
CrcPattern      DB #00, #01, #F7                                                ; серия завершения CRC
GapCount        DB #32                                                          ; число байтов промежутка после сектора
PatternEnd      DB #4E, #99, #99                                                ; заполнитель промежутка и пара завершителя
