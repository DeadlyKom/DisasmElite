; -----------------------------------------
; расчёт адреса 16-байтовой каталожной записи и проверка её наличия
; исходный диапазон #CBF4..#CC01
; In:
;   AF, A содержит номер записи
; Out:
;   HL=DiskBuffer.Catalog+16*A
;   AF, A содержит первый байт имени, Z=1 для пустой записи
; Corrupt:
;   HL, AF
; Note:
;   Четыре удвоения HL задают шаг 16, затем к старшему байту прибавляется #50.
;   Граница каталога не проверяется, наличие определяется только нулевым первым байтом.
; -----------------------------------------
GetSaveRecord:  LD L, A
                LD H, #00
                ADD HL, HL
                ADD HL, HL
                ADD HL, HL
                ADD HL, HL
                LD A, H
                ADD A, #50
                LD H, A
                LD A, (HL)
                AND A
                RET
