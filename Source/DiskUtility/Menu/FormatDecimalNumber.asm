; -----------------------------------------
; вывод беззнакового слова пятью десятичными цифрами
; исходный диапазон #CE87..#CE9F
; In:
;   HL, число 0..65535
;   IX, адрес пяти выходных байтов
; Out:
;   HL=0, DE=1, IX увеличен на 5
;   BC сохранён
; Corrupt:
;   HL, DE, AF, IX
; Note:
;   Последовательно вызывается DecimalDigit с весами 10000, 1000, 100, 10 и 1.
;   Вход #CE93 начинает с веса 100 и формирует три символа, нормальный диапазон 0..999.
;   Ведущие нули сохраняются, при числе выше диапазона трёхзначного входа первый символ может выйти за '9'.
;   Последний вес 1 непосредственно продолжает физический фрагмент DecimalDigit.
; -----------------------------------------
FormatDecimal:  LD DE, #2710
                CALL DecimalDigit
                LD DE, #03E8
                CALL DecimalDigit
ThreeDigits:    LD DE, #0064
                CALL DecimalDigit
                LD E, #0A
                CALL DecimalDigit
                LD E, #01
