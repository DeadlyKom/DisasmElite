; -----------------------------------------
; передача буфера в выходной обработчик ПЗУ TR-DOS
; исходный диапазон #CA3B..#CA47
; In:
;   HL, исходный адрес выходного потока
;   контроллер, заранее выданная команда записи
; Out:
;   возврат через обработчик ПЗУ ROM_FDC_WRITE
; Corrupt:
;   HL, DE, BC, AF
; Note:
;   DE обнуляется, C=#7F задаёт порт потока, ROM_FDC_WRITE помещается на стек.
;   EX (SP), HL сохраняет исходный адрес потока в HL, JP DiskUtility.DosGateway включает ПЗУ.
;   Контракт ПЗУ здесь внешняя зависимость, инструкции самого оверлея не скрыты.
; -----------------------------------------
WriteFdcStream: LD DE, #0000
                LD C, #7F
                PUSH HL
                LD HL, ROM_FDC_WRITE
                EX (SP), HL
                JP @DiskUtility.DosGateway
