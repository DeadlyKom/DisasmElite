; -----------------------------------------
; Допуск объекта к боевому преследованию
; исходный диапазон #EBA9..#EBC9
; In:
;   IY слот объекта
; Out:
;   C=1 цель допустима, C=0 отказ
; Corrupt:
;   AF
; Note:
;   Значения Flags2=#0C и Flags2=1..3 исключены, затем требуется бит 7 кешированного флага
;   При бите 6=1 допускаетбит 1 либо враждебность IY21.2
;   При бите 6=0 общий EBDB допускает цель только при сброшенном бите 4, это инверсия критерия груза
; -----------------------------------------
                ; исключение полных сочетаний Flags2=#0C и 1..3 до проверки метаданных
AllowAttack:    LD A, (IY + FSpaceObject.Flags2)
                CP OBJ_STATION_FL
                RET Z                                                           ; выход, если Flags2=#0C, объект исключён из преследования

                DEC A
                CP #03
                CCF
                RET NC                                                          ; выход, если полный байт Flags2 равен 1..3, объект исключён из преследования

                ; проверка старшего бита и ветви класса 6
                CALL ReadSlotFlags
                AND A
                BIT 7, A
                RET Z                                                           ; выход, если бит 7 кешированного классификатора сброшен

                BIT 6, A
                JR Z, TestCollectBit                                            ; переход, если бит 6 классификатора сброшен, применить общий критерий бита 4

                ; для класса 6 достаточно группы bit1 либо враждебности объекта
                BIT 1, A
                JR NZ, ReturnCarry                                              ; переход, если бит 1 группы взаимодействий установлен, допустить цель

                BIT OBJ_HOSTILE_BIT, (IY + FSpaceObject.Hostility)
                RET Z                                                           ; выход, если бит 2 враждебности объекта сброшен

                ; общий успешный допуск цели либо отказ подбора возвращает перенос 1
ReturnCarry:    SCF
                RET
