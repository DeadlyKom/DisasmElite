; -----------------------------------------
; Проверка остановки игрового потока на HALT
; исходный диапазон #EC9F..#ECAE
; In:
;   InputStack прерванный SP с сохранённым PC
; Out:
;   HL, DE сохраняются, Z=1 если байт по PC-1 равен 76, A этот байт
; Corrupt:
;   AF
; Note:
;   Адрес PC читается little-endian с прерванного стека, после HALT он указывает следующий байт
;   Второй RET после IsGameHalted сохранён отдельно, штатный путь завершён предыдущим RET
; -----------------------------------------
                ; чтение сохранённого PC с прерванного стека
IsGameHalted:   PUSH HL
                LD HL, (InputStack)
                PUSH DE
                LD E, (HL)
                INC HL
                LD D, (HL)
                DEC DE
                ; проверка байта по PC-1 на код HALT76
                LD A, (DE)
                CP #76
                POP DE
                POP HL
                RET

                RET
