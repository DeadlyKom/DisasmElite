; -----------------------------------------
; Беззнаковое сравнение суммы с порогом без изменения HL
; исходный диапазон #E78F..#E794
; In:
;   HL сумма, DE порог
; Out:
;   C=1 при HL<DE, Z=1 при равенстве, HL/DE сохранены
; Corrupt:
;   AF
; Note:
;   AND A сбрасывает входной перенос, PUSH/POP HL сохраняет сумму вокруг SBC
; -----------------------------------------
                ; сравнение 16-битных беззнаковых величин с сохранением исходной суммы
CompareWords:   PUSH HL
                AND A
                SBC HL, DE
                POP HL
                RET
