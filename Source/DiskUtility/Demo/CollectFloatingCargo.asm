; -----------------------------------------
; Наведение для подбора допустимого груза
; исходный диапазон #EB52..#EB7C
; In:
;    D088 AND D07C ненулевой
; Out:
;   к выбранному объекту применяются AimAtObject/CollectNear до отказа
; Corrupt:
;   HL, DE, BC, AF, IY
; Note:
;   Выбирается следующий слот, RejectCargo возвращает C=0 для доступного груза
;   При угрозах допускается не больше 2 и прежний нагрев кабины 70ED>=64, при нуле угроз температурная
;   проверка обходится
;   Читается именно 70ED, то есть сохранённое отображённое значение прибора, а не текущее 70EE
; -----------------------------------------
                ; проверка ковша и свободного трюма перед выбором следующего объекта
CollectCargo:   LD A, (State.FuelScoops)
                LD HL, State.FreeCargo
                AND (HL)
                RET Z                                                           ; выход, если побитовое сочетание свободного трюма и ковша нулевое

                CALL NextObject
                ; во время сбора проверяются угрозы и отображённый нагрев кабины
CheckScoopRisk: CALL CheckRestart
                CALL CountHostiles
                JR Z, SteerToCargo                                              ; переход, если враждебных целей нет, пропустить проверку температуры

                CP #03
                RET NC                                                          ; выход, если враждебных целей не меньше 3, прекратить сбор

                LD A, (GaugeState + FGaugeState.CabinHeat.Previous)
                CP #40
                RET C                                                           ; выход, если отображённый нагрев кабины меньше 64 при наличии угроз, прекратить сбор

                ; проверка признаков подбираемого объекта и точное доведение
SteerToCargo:   CALL RejectCargo
                RET C                                                           ; выход, если объект не подходит для подбора

                CALL AimAtObject
                CALL CollectNear
                CALL YieldWithBrake
                JR CheckScoopRisk
