; -----------------------------------------
; Перезапуск сценария при сброшенном маркере
; исходный диапазон #E81A..#E824
; In:
;   LaunchPending состояние текущего полёта
; Out:
;   ненулевой маркер возвращает, нулевой сбрасывает SP и идёт DiskUtility.Demo.RestartFlight
; Corrupt:
;   AF, SP только при перезапуске
; Note:
;   Использует тот же маркер, который сбрасывается посадкой и патчем гибели
; -----------------------------------------
                ; нулевой маркер после посадки или гибели отменяет весь стек сценария
CheckRestart:   LD A, (LaunchPending)
                AND A
                RET NZ                                                          ; выход, если маркер полёта не сброшен, перезапуск не требуется

                LD SP, StackTop
                JP RestartFlight
