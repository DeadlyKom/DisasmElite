; -----------------------------------------
; Поиск подходящей цели за девять проверок
; исходный диапазон #EB9C..#EBA8
; In:
;   пул объектов и текущий DiskUtility.Demo.ObjectCursor
; Out:
;   C=1 и IY цель при успехе, C=0 после 9 отказов
; Corrupt:
;   HL, DE, BC, AF, IY
; Note:
;   Кольцо имеет 7 слотов, поэтому при неудаче первые 2 просматриваются повторно
; -----------------------------------------
                ; девять проверок через кольцо из семи слотов
FindTarget:     LD B, #09
TryTargetSlot:  CALL NextObject
                CALL AllowAttack
                RET C                                                           ; выход, если объект допускается к боевому преследованию

                XOR A
                DJNZ TryTargetSlot

                RET
