; -----------------------------------------
; Пауза сценария с временным графическим знаком
; исходный диапазон #ECAF..#ECC6
; In:
;   рабочий стек корутины
; Out:
;   100 уступок кадра, знак нарисован и стёрт XOR
; Corrupt:
;   HL, DE, BC, AF
; Note:
;   После 100Yield XorDemoMark наносит знак, программная задержка выполняет 3072 вычитания единицы
;   При штатном терминаторе XorDemoMark возвращает B=8, затем DJNZ выполняется 8 раз в первом обороте и 256 в
;   остальных
;   После окончания падение ECC7 повторно наносит XOR и возвращает первоначальному вызывающему
; -----------------------------------------
                ; сто уступок кадра со сохранением счётчика цикла
PauseWithMark:  LD B, #64
WaitDemoFrames: PUSH BC
                CALL YieldToGame
                POP BC
                DJNZ WaitDemoFrames

                ; первый XOR-проход рисует знак, затем начинается программная задержка
                CALL XorDemoMark
                LD C, #01
                LD HL, #0C00
                ; 3072 итерации вычитания единицы, внутренний DJNZ замедляет каждый шаг
MarkDelay:      DJNZ MarkDelay

                AND A
                SBC HL, BC
                JR NZ, MarkDelay                                                ; переход, если не закончились 3072 шага программной задержки, продолжить ожидание
