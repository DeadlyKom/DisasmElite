; -----------------------------------------
; Кеш восьми флагов объектных метаданных
; исходный диапазон #EBE1..#EBE8
; In:
;   ReadSlotFlags обновляет из B457+10*n
; Out:
;   по одному байту на слот 6048+39*n
; Corrupt:
;   нет, восемь байтов данных
; Note:
;   Кеш изначально нулевой, обновляется только если прерывание застало HALT
;   Скопировано поле FEffectRecord10.TypeFlags, полный формат описан в Includes/Structs/EffectRecord.inc
;   Ниже отмечены только биты, которые проверяет демонстрационный алгоритм
; -----------------------------------------
; -----------------------------------------
;      7    6    5    4    3    2    1    0
;   +----+----+----+----+----+----+----+----+
;   | AC | GM | .. | SR | .. | .. | GP | .. |
;   +----+----+----+----+----+----+----+----+
;
;   метаданные, используемые демонстрацией:
;   AC      [7]     - флаг, запись допускается к расширенному взаимодействию
;   GM      [6]     - флаг, взаимодействие проверяется по группам
;   SR      [4]     - флаг, разрешён поиск резервной цели
;   GP      [1]     - старший бит двухбитной группы взаимодействий
;   ..      [5,3,2,0] - демонстрационные проверки эти биты не читают
;
;   AllowAttack требует AC, при GM достаточно GP либо враждебности объекта
;   при GM=0 AllowAttack требует SR=0, а RejectCargo требует SR=1
;   это критерии выбора демо, исходное назначение SR в игре не меняется
; -----------------------------------------
SlotFlagCache   DB #00, #00, #00, #00, #00, #00, #00, #00                       ; данные #EBE1..#EBE8
