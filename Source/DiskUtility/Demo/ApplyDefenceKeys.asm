; -----------------------------------------
; Решение об энергетической бомбе и маскировке
; исходный диапазон #E993..#E9D0
; In:
;   IX, Keyboard, начало восьми полурядов виртуальной клавиатуры
;    счётчики угроз и энергия
; Out:
;   при условиях выставлены W и Y
; Corrupt:
;   HL, AF
; Note:
;   Каждое уменьшение 8-битного DiskUtility.Demo.BombDelay до 0 допускает W, если четвёртый банк не 160, начальный 0 даёт 256
;   вызовов
;   При>=3 угрозах и полном третьем банке требуется маскировка, при прочих условиях она снимается
;   Первый банк<50 также приводит к Y, цвет PAPER=1 по DiskUtility.Demo.CloakAttribute отражает видимую активность маскировки,
;   проверяется фактический атрибут
; -----------------------------------------
                ; делитель команды W срабатывает при переходе счётчика к нулю
DefenceKeys:    LD HL, BombDelay
                DEC (HL)
                JR NZ, CheckCloaking                                            ; переход, если период команды W ещё не истёк, перейти к проверке маскировки

                ; неполный четвёртый банк энергии разрешает энергетическую бомбу
                LD A, (GaugeState + FGaugeState.Energy4.Current)
                CP #A0
                JR Z, CheckCloaking                                             ; переход, если четвёртый банк энергии полон, не применять W

                SET KEYBOARD_W_BIT, (IX + FKeyboardRows.RowQWERT)
                ; проверка количества враждебных целей и полного третьего банка
CheckCloaking:  CALL CountHostiles
                CP #03
                JR C, DisableCloak                                              ; переход, если враждебных целей меньше 3, проверять отключение маскировки

                LD HL, GaugeState + FGaugeState.Energy3.Current
                LD A, (HL)
                CP #A0
                JR NZ, DisableCloak                                             ; переход, если третий банк энергии не полон, проверять отключение маскировки

                ; проверка первого банка энергии и видимого состояния маскировки
                LD L, LOW GaugeState + FGaugeState.Energy1.Current              ; HL, текущая энергия первого банка, H уже равен HIGH GaugeState + FGaugeState.Energy1.Current
                LD A, (HL)
                CP #32
                JR C, ToggleCloak                                               ; переход, если первый банк энергии меньше 50, выставить Y

                LD A, (CloakAttribute)
                AND #38
                CP #08
                RET Z                                                           ; выход, если бумага обзорного окна уже имеет цвет 1, маскировка включена

                JR ToggleCloak

                ; без условий включения проверяется необходимость выключить маскировку
DisableCloak:   LD A, (CloakAttribute)
                AND #38
                CP #08
                RET NZ                                                          ; выход, если бумага обзорного окна не имеет цвета 1, отключать маскировку не требуется

                ; виртуальная Y переключает маскировку в игровом обработчике
ToggleCloak:    SET KEYBOARD_Y_BIT, (IX + FKeyboardRows.RowPOIUY)
                RET
