; -----------------------------------------
; Очистка семи строк виртуальной клавиатуры
; исходный диапазон #EC92..#EC9E
; In:
;   4700..4706
; Out:
;   семь байтов 0, строка скорости 4707 и маркер 4708 сохранены
; Corrupt:
;   HL
; Note:
;   LD/DJNZ/INC HL не изменяют флаги, AF сохраняется
; -----------------------------------------
                ; семь строк очищаются, строка скорости 4707 остаётся для общего управления
ClearMainKeys:  PUSH BC
                LD BC, #0700
                LD HL, Keyboard
ClearKeyRow:    LD (HL), C
                INC HL
                DJNZ ClearKeyRow

                POP BC
                RET
