; -----------------------------------------
; Порог суммы модулей трёх целых координат
; исходный диапазон #E769..#E78E
; In:
;   DE порог, IY тройка координат
; Out:
;   HL частичная либо полная сумма, DE сохранён, C=1 если полная сумма меньше DE
; Corrupt:
;   HL, BC, AF
; Note:
;   X/Y/Z совпадают в первых девяти байтах объекта, солнца и планеты
;   Берутся слова по 1/2,4/5,7/8, знак старшего байта снимается, младшая дробная часть пропускается
;   После X и X+Y сумма сразу проверяется, поэтому ранний отказ не читает оставшиеся оси
;   Сложение 16-битное, отдельного контроля переполнения ADD нет
; -----------------------------------------
                ; модуль целой X проверяется до чтения остальных координат
CompareRange:   LD L, (IY + FSpaceObject.X.Low)
                LD H, (IY + FSpaceObject.X.SignHigh)
                RES 7, H
                CALL CompareWords
                RET NC                                                          ; выход, если модуль целой X не меньше порога, прекратить суммирование

                ; прибавление модуля Y и ранняя проверка суммы
                LD C, (IY + FSpaceObject.Y.Low)
                LD B, (IY + FSpaceObject.Y.SignHigh)
                RES 7, B
                ADD HL, BC
                CALL CompareWords
                RET NC                                                          ; выход, если сумма модулей X и Y не меньше порога, не читать Z

                ; прибавление модуля Z и окончательное сравнение
                LD C, (IY + FSpaceObject.Z.Low)
                LD B, (IY + FSpaceObject.Z.SignHigh)
                RES 7, B
                ADD HL, BC
                CALL CompareWords
                RET
