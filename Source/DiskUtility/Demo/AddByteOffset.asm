; -----------------------------------------
; Прибавление беззнакового индекса к указателю
; исходный диапазон #E6BD..#E6C1
; In:
;   HL база, AF, A индекс 0..255
; Out:
;   HL=HL+A, DE=A, A сохранён
; Corrupt:
;   HL, DE, AF только флаги
; Note:
;   Восстанавливает необходимый вызов EB3E, перекрытый новым оверлеем
; -----------------------------------------
                ; преобразование A в беззнаковое слово и сложение с указателем
AddByteOffset:  LD D, #00
                LD E, A
                ADD HL, DE
                RET
