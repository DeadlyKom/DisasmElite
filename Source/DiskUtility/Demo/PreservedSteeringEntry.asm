; -----------------------------------------
; Совместимый вход крена и сохранённый старый выбор тангажа
; исходный диапазон #E963..#E96D
; In:
;   IY, цель с общим положением FSpaceObject.X/Y/Z
;   IX, Keyboard, начало восьми полурядов виртуальной клавиатуры
; Out:
;   основной вход безусловно идёт ApplyRoll
; Corrupt:
;   AF
; Note:
;   X/Y/Z совпадают в первых девяти байтах объекта, солнца и планеты
;   JP ApplyRoll делает следующие BIT7,IY5/JR недостижимыми при обычном входе, байты старого фрагмента
;   сохранены
; -----------------------------------------
                ; действующий вход безусловно передаёт управление ApplyRoll
LegacySteer:    JP ApplyRoll

                ; сохранённый прежний выбор тангажа после JP, прямых входов в него не найдено
                BIT 7, (IY + FSpaceObject.Y.SignHigh)
                JR Z, PressPitchS                                               ; переход, если Y цели неотрицательна в сохранённом хвосте, выбрать S

                JR PressPitchX
