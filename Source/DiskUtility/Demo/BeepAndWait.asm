; -----------------------------------------
; Звуковое действие с задержкой
; исходный диапазон #E832..#E83B
; In:
;   вызов игрового E1E8 и E35E
; Out:
;   A=1,C=1 после сигнала и 36 HALT
; Corrupt:
;   HL, BC, AF по вызовам
; Note:
;   Сохранённая процедура, прямых вызовов из демо не найдено, внутри активного IM2 применять HALT без
;   разрешения прерываний нельзя
; -----------------------------------------
                ; сохранённый сигнал и задержка завершаются A=1 ипереносом
BeepAndWait:    CALL @Game.Trade.OptionalBeep.Entry
                CALL @Game.Trade.Wait36Interrupts.Entry
                LD A, #01
                SCF
                RET
