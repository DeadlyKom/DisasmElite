; -----------------------------------------
; Торможение по старшим разрядам удаления Z
; исходный диапазон #E9D1..#E9DC
; In:
;   IY, цель с общим положением FSpaceObject.X/Y/Z
;   IX, Keyboard, начало восьми полурядов виртуальной клавиатуры
; Out:
;   Brake только если (IY8&7F)!=0 и(IY7&FC)!=0
; Corrupt:
;   AF
; Note:
;   X/Y/Z совпадают в первых девяти байтах объекта, солнца и планеты
;   При провале любой проверки возврат, иначе линейное падение Brake
; -----------------------------------------
                ; торможение требует одновременно двух ненулевых частей Z
BrakeWhenFar:   LD A, (IY + FSpaceObject.Z.SignHigh)
                AND #7F
                RET Z                                                           ; выход, если старший модуль Z нулевой, дальнее торможение не требуется

                LD A, (IY + FSpaceObject.Z.Low)
                AND #FC
                RET Z                                                           ; выход, если средний байт Z меньше 4, дальнее торможение не требуется
