; -----------------------------------------
; Точное доведение близкой цели
; исходный диапазон #E93A..#E962
; In:
;   IX, Keyboard, начало восьми полурядов виртуальной клавиатуры
;   IY, цель с общим положением FSpaceObject.X/Y/Z
; Out:
;   при цели впереди и без S/X выбираются торможение либо M/N/X
; Corrupt:
;   HL, DE, BC, AF
; Note:
;   X/Y/Z совпадают в первых девяти байтах объекта, солнца и планеты
;   Если сумма координат<1, случайный бит 1 допускает Brake, затем всегда включается X через DiskUtility.Demo.PressPitchX
;   При большей сумме знак X выбирает M/N, существующие повороты S/X не изменяются
; -----------------------------------------
                ; точное доведение разрешено только впереди и без уже нажатых S/X
CollectNear:    BIT 7, (IY + FSpaceObject.Z.SignHigh)
                RET NZ                                                          ; выход, если цель сзади, точное доведение не выполняется

                BIT KEYBOARD_X_BIT, (IX + FKeyboardRows.RowShiftZXCV)
                RET NZ                                                          ; выход, если уже выставлена клавиша X

                BIT KEYBOARD_S_BIT, (IX + FKeyboardRows.RowASDFG)
                RET NZ                                                          ; выход, если уже выставлена клавиша S

                ; проверка суммы целых координат меньше 1
                LD DE, #0001
                CALL CompareRange
                JR NC, RollByTargetX                                            ; переход, если сумма координат не меньше 1, выбрать крен по знаку X

                ; случайное торможение очень близкой цели, после него всегда включается X
                CALL @Game.Combat.NextRandomByte.Entry
                AND #02
                CALL Z, Brake                                                   ; вызов, если случайный бит 1 сброшен, затормозить перед близкой целью
                JR PressPitchX

                ; при ненулевом удалении направление крена определяется знаком X
RollByTargetX:  BIT 7, (IY + FSpaceObject.X.SignHigh)
                JR Z, PressRollN                                                ; переход, если X цели неотрицательна, выбрать N

                JR PressRollM
