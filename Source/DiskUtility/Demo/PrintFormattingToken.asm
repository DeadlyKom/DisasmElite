; -----------------------------------------
; Совместимая подстановка форматирующего токена
; исходный диапазон #E6CD..#E6D1
; In:
;   текстовый вывод D45F
; Out:
;   выведен токен 96 вторичной таблицы, байты 09,0B,01,08
; Corrupt:
;   HL, DE, BC, AF
; Note:
;   Подменяет EF8C и F0BD, код 96 передаётся как номер вторичной таблицы
;   Точная копия исходного E8E5, который перекрыт оверлеем, токен содержит управляющие коды
;   форматирования и сигнала
; -----------------------------------------
                ; сохранённая копия E8E5 раскрывает форматирующий токен 96
FormatToken:    LD A, #96
                JP @Game.Text.PrintDescriptionToken.Entry
