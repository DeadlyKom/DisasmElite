; -----------------------------------------
; Последний индекс фигуры и сохранённый хвост оверлея
; исходный диапазон #EDCE..#EDD7
; In:
;   нет
; Out:
;   восемь нулей и A5,52 сохранены
; Corrupt:
;   нет,10 байтов данных
; Note:
;   Дальнейшие 0128 байтов переноса берутся из основной игры, не входят в cl.C и здесь не дублируются
;   DiskUtility.Demo.MarkTail является 115-м индексом фигуры и реально читается XorDemoMark, остальные 9 байтов графический
;   проход не использует
; -----------------------------------------
MarkTail        DB #00, #00, #00, #00, #00, #00, #00, #00                       ; данные #EDCE..#EDD5
                DB #A5, #52                                                     ; данные #EDD6..#EDD7
