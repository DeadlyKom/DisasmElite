; -----------------------------------------
; Проверка полосы вторжения с двумя порогами
; исходный диапазон #E6C2..#E6CC
; In:
;   поля текущей системы и вторжения для Game.Text.CheckMissionRegion.Entry
; Out:
;   штатно при Galaxy=3 возвращает C=0, структурно повторяет проверку полосы
; Corrupt:
;   HL, DE, BC, AF
; Note:
;   байт #3C после первого CALL является его встроенным порогом либо INC A при раннем возврате
;   байт #00 после второго CALL является его встроенным порогом либо NOP, последний CCF инвертирует результат
;   Подменяет вызовы Game.Menus.CheckMissionRegionBand.Entry, занятого демонстрационным кодом
;   ROBOT использует Galaxy=3, поэтому Game.Text.CheckMissionRegion.Entry возвращается до геометрии, его вызов метрики Game.Trade.MissionRegionMetric.Entry уже
;   перекрыт оверлеем и полноценная геометрия Galaxy=0 здесь не гарантируется
; -----------------------------------------
                ; две проверки фронта используют встроенные байты 3C и 00 после CALL
CheckInvasion:  CALL @Game.Text.CheckMissionRegion.Entry
                ; INC A служит также порогом 3C, ранний возврат Game.Text.CheckMissionRegion.Entry оставляет его в потоке команд
                INC A
                RET NC                                                          ; выход, если первая граница не охватывает систему либо геометрия выключена галактикой

                ; вторая проверка вызывается только при переносе первой, её результат инвертируется
                CALL @Game.Text.CheckMissionRegion.Entry
                NOP
                CCF
                RET
