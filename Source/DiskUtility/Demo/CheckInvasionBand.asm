; -----------------------------------------
; Проверка полосы вторжения с двумя порогами
; исходный диапазон #E6C2..#E6CC
; In:
;   поля текущей системы и вторжения для D67A
; Out:
;   штатно при Galaxy=3 возвращает C=0, структурно повторяет проверку полосы
; Corrupt:
;   HL, DE, BC, AF
; Note:
;   3C по E6C5 является порогом первого CALL либо INC A при раннем возврате
;   00 по E6CA является порогом второго CALL либо NOP, последний CCF инвертирует результат
;   Подменяет вызовы EC40, занятого демонстрационным кодом
;   ROBOT использует Galaxy=3, поэтому D67A возвращается до геометрии, его вызов метрики E6C6 уже
;   перекрыт оверлеем и полноценная геометрия Galaxy=0 здесь не гарантируется
; -----------------------------------------
                ; две проверки фронта используют встроенные байты 3C и 00 после CALL
CheckInvasion:  CALL @Game.Text.CheckMissionRegion.Entry
                ; INC A служит также порогом 3C, ранний возврат D67A оставляет его в потоке команд
                INC A
                RET NC                                                          ; выход, если первая граница не охватывает систему либо геометрия выключена галактикой

                ; вторая проверка вызывается только при переносе первой, её результат инвертируется
                CALL @Game.Text.CheckMissionRegion.Entry
                NOP
                CCF
                RET
