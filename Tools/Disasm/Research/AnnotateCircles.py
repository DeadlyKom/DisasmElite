def resource_note(addr):
    if addr==0x8ABA:return "первый вектор далёкого тела, три знако-модульные координаты по3 байта"
    if addr==0x8AC3:return "второй вектор далёкого тела в том же формате, переключатель #FD02 добавляет9 к базе"
    if addr==0x8ACC:return "исходный резерв после двух векторов без установленного потребителя, сохраняется"
    if addr==0x8FB4:return "два исходных резервных байта без установленного потребителя, сохраняются"
    if addr==0x8FB6:return "образец#FFFF, POP AF загружает его для серии парных экранных записей"
    if addr==0x928B:return "исходный резерв после безусловного перехода, сохраняется"
    if 0x8E8D<=addr<0x8ECD:
        base=0x8E8D if addr<0x8EAD else 0x8EAD;i=addr-base
        target=int.from_bytes(MEM[0x8ECD+2*i:0x8ECF+2*i],"little")
        return f"патч {i}, {'карта' if base==0x8E8D else 'обзор'}, значение#{MEM[addr]:02X} записывается по#{target:04X}"
    if 0x8ECD<=addr<0x8F0D and (addr-0x8ECD)%2==0:
        i=(addr-0x8ECD)//2;target=int.from_bytes(MEM[addr:addr+2],"little")
        return f"адрес патча {i}, #{target:04X}, карта#{MEM[0x8E8D+i]:02X}, обзор#{MEM[0x8EAD+i]:02X}"
    return ""

