def operation_stream(text):
    result = []
    for raw in text.splitlines():
        code = raw.split(";", 1)[0].strip()
        if code and not code.upper().startswith(("MODULE ", "ENDMODULE", "ASSERT ")):
            result.append(re.sub(r"\s+", " ", code))
    return "\n".join(result)


def main():
    coverage = json.loads((ROOT / "Tools/Disasm/Reports/SourceCoverage.json").read_text("utf-8"))
    memory = memory_for("decoded")
    disassembler = decoder(memory)
    output = []
    for fragment in coverage["fragments"]:
        item = REVIEWS.get(fragment["start"])
        if not item:
            continue
        path = ROOT / fragment["file"]
        original = path.read_text("utf-8")
        lines = original.splitlines()
        beginning = next(i for i, raw in enumerate(lines) if "ASSERT $ ==" in raw)
        module_lines = [raw for raw in lines[:beginning] if raw.strip().lower().startswith("module ")]
        rendered = module_lines + [
            "; -----------------------------------------",
            "; " + item["summary"],
            "; In:", *[";   " + s for s in item["in"].split("\n")],
            "; Out:", *[";   " + s for s in item["out"].split("\n")],
            "; Corrupt:", ";   " + item["corrupt"], "; Note:",
            *[";   " + s for s in item["notes"]],
            "; -----------------------------------------",
            "                ; проверка исходного размещения",
        ]
        address = fragment["start"]
        for raw in lines[beginning:]:
            code = raw.split(";", 1)[0].rstrip()
            stripped = code.strip()
            if not stripped:
                # Сохранение пояснений перекрывающегося кода, но не прежних шаблонов.
                if "перекры" in raw or "вариант" in raw:
                    rendered.append(raw)
                continue
            instruction = re.sub(r"^\w+:\s*", "", stripped)
            if instruction.upper().startswith(("MODULE ", "ENDMODULE", "ASSERT ")):
                rendered.append(code)
                continue
            if address in item["blocks"]:
                rendered.append("                ; " + item["blocks"][address])
            if address in item["branches"]:
                rendered.append(code.ljust(80) + "; " + item["branches"][address])
            elif ";" in raw:
                rendered.append(code.ljust(80) + ";" + raw.split(";", 1)[1])
            else:
                rendered.append(code)
            if instruction.upper().startswith("DB "):
                address += len(instruction[3:].split(","))
            else:
                address += len(disassembler.disassemble(address, address + 1, "h")[0].bytes)
        result = "\n".join(rendered) + "\n"
        if operation_stream(original) != operation_stream(result):
            raise ValueError(f"Изменился поток инструкций {path}")
        if address != fragment["end"]:
            raise ValueError(f"Не совпала граница {path} {address:04X}")
        path.write_text(result, "utf-8")
        output.append({
            **fragment, **item,
            "operation_sha256": hashlib.sha256(operation_stream(result).encode()).hexdigest(),
        })
    destination = ROOT / "Tools/Disasm/Reports/Semantics"
    destination.mkdir(exist_ok=True)
    (destination / "ScreenCircles.json").write_text(
        json.dumps(output, ensure_ascii=False, indent=2) + "\n", "utf-8")
    print(f"Reviewed graphics fragments: {len(output)}")


if __name__ == "__main__":
    main()
