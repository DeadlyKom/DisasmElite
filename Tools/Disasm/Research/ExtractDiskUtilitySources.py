def write(path, lines):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def source_line(code="", comment=None, label=None):
    prefix = (label + ":" if label else "").ljust(16)
    if not code:
        return prefix + ("; " + comment if comment else "")
    line = prefix + code
    if comment:
        assert len(line) < 80, line
        line = line.ljust(80) + "; " + comment
    return line


def data_records(memory, start, end, description):
    while start < end:
        stop = min(start + 12, end)
        yield (start, "DB " + ", ".join(f"#{v:02X}" for v in memory[start:stop]),
               bytes(memory[start:stop]), description, True)
        start = stop


def collect(memory, start, end, data_ranges, inline):
    ranges = sorted(data_ranges)
    out = []
    while start < end:
        current = next(((s, e) for s, e in ranges if s <= start < e), None)
        if current:
            finish = min(current[1], end)
            out.extend(data_records(memory, start, finish, "исходные данные"))
            start = finish
            continue
        instruction = decoder(memory).disassemble(start, start + 1, "h")[0]
        if start + len(instruction.bytes) > end:
            raise ValueError(("boundary", hex(start), hex(end)))
        out.append((start, instruction.operation.replace("$", "#").replace("IYl", "IYL").replace("IYh", "IYH").replace("IXl", "IXL").replace("IXh", "IXH"),
                    instruction.bytes, "", False))
        start += len(instruction.bytes)
        call = re.fullmatch(r"CALL \$([0-9A-F]{4})", instruction.operation)
        if call and int(call[1], 16) in inline:
            size, description = inline[int(call[1], 16)]
            out.extend(data_records(memory, start, start + size, description))
            start += size
    return out


def emit_group(name, raw, address, metadata, data_ranges, inline, comment_overrides=None):
    memory = bytearray(65536)
    memory[address:address + len(raw)] = raw
    end = address + len(raw)
    # Разбор выполняется отдельно по подтверждённым границам функций и данных.
    records = []
    for index, item in enumerate(metadata):
        limit = metadata[index + 1][0] if index + 1 < len(metadata) else end
        records.extend(collect(memory, item[0], limit, data_ranges, inline))
    assert b"".join(item[2] for item in records) == raw
    labels = {entry[0]: entry[1] for entry in metadata}
    addresses = {r[0] for r in records}
    for position, operation, data, comment, is_data in records:
        if not is_data:
            target = re.fullmatch(r"(?:JP|JR|CALL|DJNZ) (?:(?:NZ|Z|NC|C|PO|PE|P|M),)?#([0-9A-F]{4})", operation)
            if target and int(target[1], 16) in addresses:
                labels.setdefault(int(target[1], 16), f"L_{target[1]}")
    filenames = []
    setup_comments = {0xC83C, 0xC86C, 0xC887, 0xC891}
    specific = {
        key: value for key, value in SPECIFIC.items()
        if ((name == "DemoSetup" and key in setup_comments)
            or (name == "Demo" and key >= 0xE000)
            or (name == "Menu" and key < 0xE000 and key not in setup_comments))
    }
    for index, (start, short_name, title, note) in enumerate(metadata):
        limit = metadata[index + 1][0] if index + 1 < len(metadata) else end
        selected = [r for r in records if start <= r[0] < limit]
        lines = [
            "; -----------------------------------------",
            "; " + title,
            f"; исходный диапазон #{start:04X}..#{limit - 1:04X}",
        ]
        contract = CONTRACTS.get((name, short_name))
        if contract:
            for section, values in zip(("In", "Out", "Corrupt"), contract):
                lines.append("; " + section + ":")
                lines.extend(";   " + value for value in values)
        lines.extend([
            "; Note:", ";   " + note,
            ";   инструкции и встроенные параметры сохранены в исходном порядке",
            "; -----------------------------------------",
        ])
        for position, operation, data, comment, is_data in selected:
            before = (comment_overrides or {}).get(position, specific.get(position))
            if before:
                lines.append(source_line(comment=before))
            if not is_data:
                target = re.fullmatch(r"(JP|JR|CALL|DJNZ) (?:(NZ|Z|NC|C|PO|PE|P|M),)?#([0-9A-F]{4})", operation)
                if target:
                    mnemonic, condition, target_hex = target.groups()
                    target_address = int(target_hex, 16)
                    target_name = labels.get(target_address, "#" + target_hex)
                    operation = mnemonic + " " + ((condition + ", ") if condition else "") + target_name
                    if condition:
                        kind = "вызов" if mnemonic == "CALL" else "переход"
                        comment = kind + ", если " + CONDITIONS[condition]
                    elif mnemonic == "CALL" and target_address in CALLS:
                        comment = CALLS[target_address]
                ret = re.fullmatch(r"RET (NZ|Z|NC|C|PO|PE|P|M)", operation)
                if ret:
                    comment = "выход, если " + CONDITIONS[ret[1]]
                if operation.startswith("CP ") and not before:
                    lines.append(source_line(comment="проверка границы или значения перед следующим выбором ветви"))
                elif operation.startswith("BIT ") and not before:
                    lines.append(source_line(comment="проверка отдельного признака в исходном состоянии"))
                elif operation.startswith(("ADD ", "ADC ", "SUB ", "SBC ")) and not before:
                    lines.append(source_line(comment="расчёт адреса, счётчика или разности, используемой следующим участком"))
                elif operation == "LDIR" and not before:
                    lines.append(source_line(comment="копирование BC байт из HL в DE с увеличением обоих адресов"))
                elif operation == "LDDR" and not before:
                    lines.append(source_line(comment="копирование BC байт с уменьшением исходного и конечного адресов"))
                elif re.match(r"LD \(#[0-9A-F]{4}\),", operation) and not before:
                    target_address = int(operation.split("#")[1][:4], 16)
                    if address <= target_address < end:
                        lines.append(source_line(comment="обновление исходного состояния либо изменяемого операнда внутри оверлея"))
            label = labels.get(position)
            if label and len(label) > 14:
                raise ValueError(label)
            lines.append(source_line(operation, comment or None, label))
        filename = f"{start:04X}_{short_name}.asm"
        filenames.append(filename)
        write(OUT / name / filename, lines)
    write(OUT / name / "Include.inc",
          [source_line(f'include "{filename}"') for filename in filenames])
    return {
        "name": name, "length": len(raw), "origin": address,
        "instruction_count": sum(not r[4] for r in records),
        "literal_byte_count": sum(len(r[2]) for r in records if r[4]),
        "records": [{"address": r[0], "length": len(r[2]), "hex": r[2].hex(),
                     "instruction": None if r[4] else r[1]} for r in records],
    }


