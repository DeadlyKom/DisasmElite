def line(operation, comment=None, label=None):
    prefix = (label + ":").ljust(16) if label else " " * 16
    result = prefix + operation
    if comment:
        assert len(result) < 80, result
        result = result.ljust(80) + "; " + comment
    return result

def heading(address):
    if address not in HEADERS:
        return []
    name, meaning, inputs, outputs, corrupts, notes = HEADERS[address]
    result = ["", "; " + "-" * 77, "; " + meaning, "; In:"]
    for item in inputs:
        result.append(";   " + item)
    result.append("; Out:")
    for item in outputs:
        result.append(";   " + item)
    result.append("; Corrupt:")
    for item in corrupts:
        result.append(";   " + item)
    result.append("; Note:")
    result.extend(";   " + item for item in notes)
    result.append("; " + "-" * 77)
    return result

def replace_symbols(operation):
    def sub(match):
        addr = int(match.group()[1:], 16)
        return ALIASES.get(addr, NAMES.get(addr, f"#{addr:04X}"))
    operation = re.sub(r"\$[0-9A-F]{4}\b", sub, operation)
    return operation.replace("$", "#").replace("DEFB ", "DB ")

def instruction_lines(instruction):
    address = instruction.address
    operation = replace_symbols(instruction.operation)
    result = heading(address)
    if address in NAMES:
        result.append((NAMES[address] + ":").ljust(16) + "; " +
                      (HEADERS[address][1] if address in HEADERS else
                       BEFORE.get(address, "продолжение текущего пути исполнения")))
    if address in BEFORE:
        result.append(" " * 16 + "; " + BEFORE[address])
    comment = None
    if address in CONDITIONS:
        word = "выход" if operation.startswith("RET ") else "переход"
        if operation.startswith("CALL "):
            # Для условного CALL комментарий прямо указывает факт вызова.
            word = "вызов"
        comment = f"{word}, если {CONDITIONS[address]}"
    elif re.match(r"(?:JR|JP|CALL) (?:NZ|Z|NC|C|PO|PE|P|M),", operation) or \
            re.match(r"RET (?:NZ|Z|NC|C|PO|PE|P|M)$", operation):
        raise AssertionError(f"Не описано условие {address:04X}: {operation}")
    result.append(line(operation, comment))
    return result

