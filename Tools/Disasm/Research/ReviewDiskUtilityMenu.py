def content_lines(path):
    result = []
    for line in path.read_text(encoding="utf-8-sig").splitlines():
        raw = line.split(";", 1)[0].rstrip()
        if raw.strip():
            result.append(raw)
    return result


def render():
    maps = json.loads((ROOT / "Tools/Disasm/Reports/DiskUtilityStaticMap.json").read_text(encoding="utf-8"))
    # Раскрывается только неперекрывающийся хвост, строковые десять байтов остаются DB.
    sys.path.insert(0, str(ROOT / "Tools/Disasm"))
    from InspectZ80 import decoder
    memory = bytearray(65536)
    memory[0xC800:0xD000] = (ROOT / "Tools/Disasm/Extracted/Active/03_cl.C").read_bytes()[:0x800]
    replacements = [{
        "address": 0xC859, "length": 10,
        "hex": memory[0xC859:0xC863].hex(), "instruction": None,
    }]
    for lo, hi in ((0xC863, 0xC871), (0xC872, 0xC87D)):
        if lo == 0xC872:
            replacements.append({"address": 0xC871, "length": 1, "hex": "04", "instruction": None})
        for instruction in decoder(memory).disassemble(lo, hi, "h"):
            replacements.append({
                "address": instruction.address, "length": len(instruction.bytes),
                "hex": instruction.bytes.hex(),
                "instruction": instruction.operation.replace("$", "#"),
            })
    maps[0]["records"] = sorted([
        r for r in maps[0]["records"] if not 0xC859 <= r["address"] < 0xC87D
    ] + replacements, key=lambda r: r["address"])
    assert bytes.fromhex("".join(r["hex"] for r in maps[0]["records"])) == memory[0xC800:0xD000]
    maps[0]["instruction_count"] = sum(r["instruction"] is not None for r in maps[0]["records"])
    maps[0]["literal_byte_count"] = sum(r["length"] for r in maps[0]["records"] if r["instruction"] is None)
    (ROOT / "Tools/Disasm/Reports/DiskUtilityStaticMap.json").write_text(
        json.dumps(maps, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    lengths = {r["address"]: r["length"] for r in maps[0]["records"]}
    paths = sorted((ROOT / "Source/DiskUtility/Menu").glob("*.asm"))
    assert len(paths) == len(R), (len(paths), len(R))
    output = []
    for index, path in enumerate(paths):
        start = int(path.name[:4], 16)
        end = int(paths[index + 1].name[:4], 16) if index + 1 < len(paths) else 0xD000
        spec = R[start]
        old = content_lines(path)
        header = [
            "; -----------------------------------------", "; " + spec["summary"],
            f"; исходный диапазон #{start:04X}..#{end - 1:04X}",
        ]
        for field, title in (("in", "In"), ("out", "Out"), ("corrupt", "Corrupt")):
            header.append("; " + title + ":")
            header.extend(";   " + line for line in spec[field].splitlines())
        header.append("; Note:")
        header.extend(";   " + line for line in spec["notes"])
        header.append("; -----------------------------------------")
        body = []
        address = start
        branches = iter(spec["branches"])
        used = 0
        previous = ""
        for raw in old:
            label = None
            instruction = raw.strip()
            if ":" in instruction:
                label, instruction = instruction.split(":", 1)
                instruction = instruction.strip()
            if address in spec["blocks"]:
                body.append("                ; " + spec["blocks"][address])
            # Метка остаётся на исходной инструкции, комментарий начинается в позиции 80.
            line = (label + ":").ljust(16) + instruction if label else " " * 16 + instruction
            if re.match(r"(?:JR|JP|CALL|RET)\s+(?:NZ|Z|NC|C|PO|PE|P|M)(?:,|$)", instruction):
                reason = next(branches)
                stem = "выход" if instruction.startswith("RET") else "вызов процедуры" if instruction.startswith("CALL") else "переход"
                line = line.ljust(80) + "; " + stem + ", если " + reason
                used += 1
            elif instruction.startswith("DB "):
                annotation = None
                if previous == "CALL #D956":
                    annotation = "порт и значение для ПЗУ, адрес возврата пропускает оба байта"
                elif previous == "CALL #D421":
                    annotation = "управляющий код текста, адрес возврата пропускает этот байт"
                elif previous in ("CALL ReadAt", "CALL ReadBuffer", "CALL WriteAt", "CALL WriteBuffer"):
                    annotation = "номер сектора после CALL, Transfer изменяет адрес возврата"
                if annotation:
                    line = line.ljust(80) + "; " + annotation
            else:
                annotation = {
                    "CALL #D956": "передача встроенной пары порт/значение через шлюз ПЗУ TR-DOS",
                    "CALL #D964": "обработчик ПЗУ TR-DOS с начальным адресом HL=0",
                    "CALL #D967": "приём потока контроллера через ПЗУ TR-DOS",
                    "CALL #D975": "очистка 768 атрибутных байтов, на выходе HL=#5B00 и BC=0",
                    "CALL #D421": "обработка следующего байта как встроенного управляющего кода",
                    "CALL #D48E": "вывод строки HL до нулевого байта штатным обработчиком игры",
                    "CALL #D425": "вывод символа или управляющего кода из A",
                    "CALL #D9C1": "чтение B секторов в HL по паре сектор/дорожка DE",
                    "CALL #E3CC": "редактирование имени в буфере с ограничением восьми символов",
                }.get(instruction)
                if annotation:
                    line = line.ljust(80) + "; " + annotation
            body.append(line)
            previous = instruction
            if instruction.startswith("DB "):
                address += len(instruction[3:].split(","))
            else:
                assert address in lengths, (path.name, hex(address), instruction)
                address += lengths[address]
        assert next(branches, None) is None, (path.name, "unused branch descriptions")
        assert used == len(spec["branches"])
        assert address == end, (path.name, hex(address), hex(end))
        result = "\n".join(header + body) + "\n"
        assert [x.split(";", 1)[0].rstrip() for x in result.splitlines() if x.split(";", 1)[0].strip()] == old
        path.write_text(result, encoding="utf-8")
        output.append({
            "file": path.relative_to(ROOT).as_posix(),
            "start": start, "end": end, "status": "reviewed",
            "summary": spec["summary"], "in": spec["in"].splitlines(),
            "out": spec["out"].splitlines(), "corrupt": spec["corrupt"].splitlines(),
            "evidence": spec["notes"] + [
                "Проверены исходные инструкции cl.C и вызываемые игровые продолжения.",
                "При редактировании комментариев последовательность операторов и байтов DB не изменилась.",
                "Граница записи соответствует физическому файлу, общие хвосты отмечены в описании.",
            ],
            "unresolved": [],
        })
        if start in (0xCBDB, 0xCBF4, 0xCE87, 0xC959, 0xCA48, 0xC859):
            output[-1]["evidence"].append(
                "Исполнение исходных инструкций проверено в Tools/Disasm/Reports/DiskUtilityMenuValidation.json.")
        if start in (0xC9D8, 0xCF1E, 0xCF9C):
            output[-1]["evidence"].append(
                "Переходы и реальные сектора отдельно проверены в Tools/Disasm/Reports/HiddenCopyPath.json.")
    (ROOT / "Tools/Disasm/Reports/DiskUtilityMenuSemantics.json").write_text(
        json.dumps(output, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"Reviewed {len(paths)} physical fragments, {sum(len(r['branches']) for r in R.values())} conditional instructions.")


if __name__ == "__main__":
    render()
