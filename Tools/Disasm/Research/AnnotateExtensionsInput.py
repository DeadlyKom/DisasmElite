def parse_file(path):
    result = []
    pc = None
    for line in path.read_text(encoding="utf8").splitlines():
        code = line.split(";",1)[0].rstrip()
        m = re.search(r"ASSERT \$ == #([0-9A-F]+)",code)
        if m:
            if pc is None:
                pc = int(m[1],16)
            else:
                assert pc == int(m[1],16), (path,hex(pc),m[1])
            continue
        if pc is None or not code.strip() or "module " in code or code.strip()=="endmodule":
            continue
        label = ""
        op = code.strip()
        if ":" in op:
            label,op = op.split(":",1)
            op = op.strip()
        if not op:
            continue
        if op.startswith("DB "):
            raw = bytes(int(x.strip().replace("#",""),16) for x in op[3:].split(","))
            assert MEM[pc:pc+len(raw)] == raw
            result.append([pc,label,op,raw,"data"])
            pc += len(raw)
        else:
            ins = DIS.disassemble(pc,pc+1,"h")[0]
            result.append([pc,label,op,ins.bytes,"code"])
            pc += len(ins.bytes)
    return result

def split_data(rows, cuts, decode_ranges):
    output = []
    for addr,label,op,raw,kind in rows:
        if kind=="code":
            output.append([addr,label,op,raw,kind])
            continue
        cursor = addr
        end = addr+len(raw)
        while cursor<end:
            active = next(((a,b) for a,b in decode_ranges if a<=cursor<b),None)
            if active:
                ins = DIS.disassemble(cursor,cursor+1,"h")[0]
                # Кандидат может пересечь исходную восьмибайтовую строку DB.
                output.append([cursor,label if cursor==addr else "",ins.operation.replace("$","#"),ins.bytes,"code"])
                cursor += len(ins.bytes)
            else:
                boundary = min([end]+[c for c in cuts if cursor<c<end]+[a for a,b in decode_ranges if cursor<a<end])
                data = bytes(MEM[cursor:boundary])
                output.append([cursor,label if cursor==addr else "","DB "+", ".join(f"#{v:02X}" for v in data),data,"data"])
                cursor=boundary
    # Удаляются продолжения прежних DB-строк, уже поглощённые новой командой.
    merged=[]
    for row in output:
        if merged and row[0]<merged[-1][0]+len(merged[-1][3]):
            consumed=merged[-1][0]+len(merged[-1][3])-row[0]
            if consumed>=len(row[3]):continue
            assert row[4]=="data", row
            row=[row[0]+consumed,"","DB "+", ".join(f"#{v:02X}" for v in row[3][consumed:]),row[3][consumed:],"data"]
        merged.append(row)
    return merged

