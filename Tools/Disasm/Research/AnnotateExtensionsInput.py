            cuts.update(range(0x701B,0x705F,4))
            cuts.update(range(0x705F,0x7089,3))
            cuts.update(range(0xFF58,0xFFA8,2))
            for _,message in MESSAGE_AT.values():
                cuts.update((message["start"],message["end"]))
            cuts.update([0x5D78,0x5DD0,0x5DF0,0x5E68,0x6F11,0x6F29,0x701B,0x7089,0xF117,0xF11A,0xF11C,0xF11E,0xF4D0,0xF8A8,0xF8B4,0xFAF7,0xFB31,0xFC04,0xFC08,0xFC0D,0xFC0E,0xFC0F,0xFC3B,0xFC3D,0xFD41,0xFD69,0xFD8A,0xFD8E,0xFD96,0xFD99,0xFDB3,0xFDF3,0xFDFB,0xFDFE,0xFF08,0xFF0A,0xFF0C,0xFF56,0xFF58,0xFFA8,0xFFD0])
            # Сначала объединяются соседние DB-строки, чтобы команды не разбивались на их границах.
            grouped=[]
            for row in rows:
                if grouped and row[4]=="data" and grouped[-1][4]=="data" and not row[1]:
                    grouped[-1][3]+=row[3]
                else:grouped.append(row.copy())
            rows=split_data(grouped,cuts,ranges)
            # Длинные ресурсы разбиваются максимум по восемь байтов без изменения границ.
            expanded=[]
            for addr,label,op,raw,kind in rows:
                if kind=="code":
                    expanded.append([addr,label,op,raw,kind]);continue
                for offset in range(0,len(raw),8):
                    data=raw[offset:offset+8]
                    expanded.append([addr+offset,label if not offset else "","DB "+", ".join(f"#{v:02X}" for v in data),data,kind])
            rows=expanded
            text=[f"                module {folder}",f"                module {path.stem}","; -----------------------------------------",f"; {title}",f"; исходный диапазон #{start:04X}..#{end-1:04X}",f"; смысловое имя {semantic}"]
            text += ["; "+line for line in details.split("|")]
            text += ["; -----------------------------------------","                ; проверка исходного начала фрагмента",f"                ASSERT $ == #{start:04X}"]
            for addr,label,op,raw,kind in rows:
                if addr in BLOCKS:text.append("                ; "+BLOCKS[addr])
                if kind=="data":
                    note=resource_note(addr,len(raw))
                    if note:text.append("                ; "+note)
                line=(label+":").ljust(16)+op if label else " "*16+op
                cond=re.match(r"(JR|JP|RET|CALL) (Z|NZ|C|NC|M|P|PE|PO)(,|$)",op)
                if cond:
                    assert addr in COND,(path,hex(addr),op)
                    prefix="выход, если " if cond[1]=="RET" else "вызов, если " if cond[1]=="CALL" else "переход, если "
                    line=line.ljust(80)+"; "+prefix+COND[addr]
                elif kind=="data":
                    line=line.ljust(80)+f"; данные #{addr:04X}..#{addr+len(raw)-1:04X}"
                text.append(line)
