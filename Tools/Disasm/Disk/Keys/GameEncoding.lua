-- Это байт изменяющегося состояния генератора, а не обычный байт кода
-- В исходниках проекта все шесть байтов #DEC0..#DEC5 уже возвращены
-- к исходным дисковым BC 57 82 0A 63 AD, поэтому их здесь трогать нельзя
-- Повторный вызов преобразователя на RAM после загрузки использовал бы
-- конечные семена D1 AD 4D A7 CC 45 и выбрал бы другую последовательность
-- С исходными семенами выбор воспроизводим, но вызов снова изменит сами семена
-- Фиксированные поправки позволяют сохранить их исходное дисковое состояние
