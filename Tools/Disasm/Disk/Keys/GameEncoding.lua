--
-- Формат строки:
--   [1] смещение байта внутри ELITE3.C, отсчёт от нуля
--   [2] маска XOR с одним установленным битом
--   [3] адрес того же байта в памяти, смещение плюс #4000
-- Например, первая строка меняет бит 7 байта по адресу #6AA1
-- Смещение этого байта в файле равно #2AA1, а не #6AA1
-- XOR с той же маской обратим, #CD XOR #10 даёт #DD и обратно
-- Здесь 244 различных адреса, поэтому порядок применения строк несущественен
