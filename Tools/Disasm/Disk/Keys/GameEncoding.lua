-- Исходный загрузчик перед запуском меняет отдельные биты команд и данных
-- Исходники игры содержат уже восстановленные команды, поэтому при упаковке
-- нужно вернуть эти биты, чтобы загрузчик затем снял кодирование ровно один раз
-- Без обратного кодирования загрузчик изменит биты уже правильных команд
-- Эта таблица создана для сборки проекта, в исходном TRD такой таблицы нет
